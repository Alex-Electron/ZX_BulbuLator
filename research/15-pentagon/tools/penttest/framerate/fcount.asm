; fcount.asm - счётчик кадров для замера частоты кадров машины с хоста.
; Каждый кадр копирует FRAMES (23672..23674, его увеличивает обработчик IM 1 ПЗУ) в первые три байта
; экрана. Хост читает зеркало экрана по JTAG вместе с глобальным таймером ARM, два раза с паузой:
; кадры / секунды = частота кадров, отсюда такт процессора = частота * длина кадра в тактах.
	org 32768
	ld a,1
	out (0FEh),a
	im 1
	ei
loop	halt
	ld hl,(23672)
	ld (16384),hl
	ld a,(23674)
	ld (16386),a
	xor a
	in a,(0FEh)
	cpl
	and 1Fh
	jr z,loop
	ret
