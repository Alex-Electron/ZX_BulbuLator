; pcont.asm - ЗАРЯД КОНТЕНШЕНА ПОРТОВ: четыре строки таблицы WoS x все восемь фаз.
; Код лежит в 0x8000 (на 48K контендятся только 0x4000..0x7FFF), поэтому выборки M1
; штрафа не получают и весь измеренный лишний такт принадлежит циклу ввода-вывода.
;   BC = 40FE  старший байт в 0x40..0x7F, A0 = 0  -> эталон C:1, C:3
;   BC = 40FF  то же, A0 = 1                      -> эталон C:1, C:1, C:1, C:1
;   BC = 00FE  старший вне диапазона, A0 = 0      -> эталон N:1, C:3
;   BC = 00FF  то же, A0 = 1                      -> эталон N:4
; Длина блока 137 T, 137 mod 8 = 1 -> фаза перебирается целиком за восемь блоков.
        org $8000
start:  di
        ld hl,$9000
        ld de,$9001
        ld bc,$0100
        ld (hl),$91
        ldir                    ; таблица IM2 257 байт = $91 -> вектор $9191
        ld a,$90
        ld i,a
        im 2
        ld sp,$8ff0
        ei
frame:  halt
        ld bc,767               ; выждать ~14000 T: попасть в бумагу
w1:     dec bc
        ld a,b
        or c
        jr nz,w1                ; 26 T на виток
        ld d,48
blk:    ld bc,$40fe
        ld a,0
        in a,(c)
        ld bc,$40ff
        ld a,0
        in a,(c)
        ld bc,$00fe
        ld a,0
        in a,(c)
        ld bc,$00ff
        ld a,0
        in a,(c)
        ld a,0
        dec d
        jp nz,blk
        jp frame
        org $9191
        ei
        ret
