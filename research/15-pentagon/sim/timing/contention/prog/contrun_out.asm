; contrun_out.asm - вариант (c) для портов: OUT (#FE),A в контендуемом ОЗУ 0x6000 (порт 0x02FE/0x07FE: N:1,C:3).
; ВНИМАНИЕ: переход в теле цикла - АБСОЛЮТНЫЙ 6002h, а не метка: метка собрана под org 8000h и увела бы
; цикл обратно в неконтендуемую копию (так и было в первой версии: платил только цикл ввода-вывода).
        org 8000h
        di
        ld hl,body
        ld de,6000h
        ld bc,bodyend-body
        ldir
        jp 6000h
body:
        ld a,2             ; 6000: 7 T
        out (0feh),a       ; 6002: 11 T  pc:4 pc+1:3 IO:4 (N:1,C:3)
        xor 5              ; 6004: 7 T   2 <-> 7
        jp 6002h           ; 6006: 10 T  -> 28 T на итерацию, всё в 0x6000
bodyend:
