#!/bin/bash
# wave2.sh - вторая волна: 128K, (c) плотные циклы, (d) фазы
cd "$(dirname "$0")"
R=./run.sh
S="MACHINE=128 PROG=prog/im2sweep.bin ORG=8000 ISR=1 CHAIN=8 ACCLOG=1 QUIET=1"
$R --wd=c1 $S INSTR=RD HLV=4000 PADT=14308 SWEEP=12 PADT2=14436 SWEEP2=6 PADT3=14536 SWEEP3=6 RUNUS=520000 &
$R --wd=c2 $S INSTR=RD HLV=C000 P7FFD=01 PADT=14308 SWEEP=10 RUNUS=240000 &
$R --wd=c3 $S INSTR=RD HLV=C000 P7FFD=00 PADT=14308 SWEEP=4 RUNUS=120000 &
$R --wd=c4 $S INSTR=OUTFE PADT=14308 SWEEP=10 RUNUS=240000 &
$R --wd=c5 $S INSTR=OUTC PORT=7FFD PADT=14307 SWEEP=10 RUNUS=240000 &
$R --wd=c6 $S INSTR=OUTC PORT=FFFD P7FFD=01 PADT=14307 SWEEP=6 RUNUS=160000 &
$R --wd=c7 $S INSTR=OUTC PORT=FFFD P7FFD=00 PADT=14307 SWEEP=6 RUNUS=160000 &
H="PROG=../../../harness/prog/marker_5000.bin ORG=5000 FRAMESTAT=1 QUIET=1"
$R --wd=d5 MACHINE=128 $H WINLINE=0 RUNUS=45000 &
$R --wd=e1 MACHINE=48 PROG=prog/contrun.bin ORG=8000 FRAMESTAT=1 QUIET=1 RUNUS=110000 &
$R --wd=e2 MACHINE=48 PROG=prog/contrun_rd.bin ORG=8000 FRAMESTAT=1 QUIET=1 RUNUS=110000 &
$R --wd=e3 MACHINE=48 PROG=prog/contrun_out.bin ORG=8000 FRAMESTAT=1 QUIET=1 RUNUS=110000 &
$R --wd=e4 MACHINE=128 PROG=prog/contrun.bin ORG=8000 FRAMESTAT=1 QUIET=1 RUNUS=110000 &
$R --wd=f1 MACHINE=48 $H WINLINE=100 CPUCKINIT=1 RUNUS=45000 &
$R --wd=f2 MACHINE=48 $H WINLINE=100 HCINIT=1 RUNUS=45000 &
$R --wd=f3 MACHINE=48 $H WINLINE=100 MWPULSE=24 RUNUS=65000 &
wait
echo "WAVE2 DONE"
