#!/bin/bash
# wave1.sh - первая волна прогонов контеншена (все параллельно, каждый в своём wd/)
cd "$(dirname "$0")"
R=./run.sh
S="MACHINE=48 PROG=prog/im2sweep.bin ORG=8000 ISR=1 CHAIN=8 ACCLOG=1 QUIET=1"
$R --wd=a1 $S INSTR=RD  PADT=14282 SWEEP=12 PADT2=14410 SWEEP2=8 PADT3=14506 SWEEP3=6 RUNUS=560000 &
$R --wd=a1b $S INSTR=RD PADT=57066 SWEEP=6 PADT2=57290 SWEEP2=4 RUNUS=240000 &
$R --wd=a2 $S INSTR=WR  PADT=14282 SWEEP=12 PADT2=14410 SWEEP2=8 RUNUS=440000 &
$R --wd=a3 $S INSTR=INCHL PADT=14282 SWEEP=8 RUNUS=200000 &
$R --wd=b1 $S INSTR=OUTFE PADT=14282 SWEEP=10 RUNUS=240000 &
$R --wd=b2 $S INSTR=INFE  PADT=14282 SWEEP=10 RUNUS=240000 &
$R --wd=b3 $S INSTR=OUTC PORT=7FFD PADT=14281 SWEEP=10 RUNUS=240000 &
$R --wd=b4 $S INSTR=INC  PORT=7FFD PADT=14281 SWEEP=10 RUNUS=240000 &
$R --wd=b5 $S INSTR=OUTC PORT=FFFD PADT=14281 SWEEP=6 RUNUS=160000 &
$R --wd=b6 $S INSTR=OUTC PORT=40FE PADT=14281 SWEEP=8 RUNUS=200000 &
H="PROG=../../../harness/prog/marker_5000.bin ORG=5000 FRAMESTAT=1 QUIET=1"
$R --wd=d1 MACHINE=48 $H WINLINE=0 RUNUS=45000 &
$R --wd=d2 MACHINE=48 $H WINLINE=100 RUNUS=45000 &
$R --wd=d3 MACHINE=48 $H WINLINE=191 RUNUS=45000 &
$R --wd=d6 MACHINE=PENT $H WINLINE=100 RUNUS=45000 &
wait
echo "WAVE1 DONE"
