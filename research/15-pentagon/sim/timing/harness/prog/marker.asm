; marker.asm - проверочная программа стенда tb_zx (собирать: pasmo --bin marker.asm marker.bin)
; Собирать prog/build.sh: он подставляет org и делает marker_8000.bin (банк 2, без контеншена) и
; marker_5000.bin (банк 5, с контеншеном). Грузить СТРОГО по своему ORG: код не позиционно-независим
; (ld hl,isr - абсолютный адрес; у Z80 нет способа узнать PC без абсолютных адресов). Оплачено ложным
; «дефектом контеншена» 28.08: бинарник для 8000 загрузили по 5000, LDIR скопировал нули из 0x803C.
; Стенд пишет JP ORG в байты 0..2 ПЗУ страниц 0 и 1. Программа не должна пересекать 0x4000..0x40FF,
; 0x6000..0x616C, 0x7000..0x7001 и стек 0x7FF0.
;   1) DI, бордюр = 2 (красный)
;   2) маркер 0x4000..0x40FF: байт[i] = i XOR 0xA5
;   3) таблица IM2 0x6000..0x6100 = 0x61, обработчик по 0x6161 считает прерывания в (0x7000)
;   4) EI, HALT в цикле - процессор стоит в неконтендящемся ОЗУ, T-состояния = pe3M5
        org 8000h               ; подменяется prog/build.sh
start:  di
        ld sp, 7ff0h
        ld a, 2
        out (0feh), a
        ld hl, 4000h
        ld b, 0
mk:     ld a, l
        xor 0a5h
        ld (hl), a
        inc hl
        djnz mk
        ld hl, 6000h            ; 257 байт 0x61 -> вектор всегда 0x6161
        ld de, 6001h
        ld bc, 256
        ld (hl), 61h
        ldir
        ld hl, isr              ; обработчик -> 0x6161. АБСОЛЮТНЫЙ адрес: бинарник обязан быть
        ld de, 6161h            ; собран под тот ORG, по которому грузится (prog/build.sh)
        ld bc, isr_end-isr
        ldir
        ld hl, 0
        ld (7000h), hl
        ld a, 60h
        ld i, a
        im 2
        ei
loop:   halt
        jr loop
isr:    push hl
        ld hl, (7000h)
        inc hl
        ld (7000h), hl
        pop hl
        ei
        reti
isr_end:
