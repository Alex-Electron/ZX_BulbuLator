/* =================================================================================================
 * rom_ident.h - v0.15.384 РАСПОЗНАВАТЕЛЬ СТРАНИЦЫ ПЗУ (16 КБ) ПО СОДЕРЖИМОМУ.
 *
 * Зачем отдельный модуль, а не строчка в loader_main.c. Задание владельца 19.08: «надо как-то уметь
 * показывать какие банки или содержимое в ром файле». Показывать - значит НАЗЫВАТЬ, а называть можно
 * только то, что распознано; а распознавание подписей - ровно тот код, который дешевле всего проверять
 * НА НАСТОЯЩИХ ФАЙЛАХ и на хосте, без платы (стенд rom_ident_host_test.c собирается обычным gcc).
 *
 * ⚠ ЭТО НЕ ЗАМЕНА rom_page_kind(). Тот отвечает на ОДИН вопрос - «в какой из наших четырёх слотов
 * положить страницу», и его ответ несёт раскладку (слот 2 = трап TR-DOS, слот 3 = сервисная), поэтому
 * его контракт трогать нельзя. Здесь - вопрос ДРУГОЙ: «что это за страница, как её назвать человеку».
 * Ответов тут много, и часть их - догадки по отпечатку первых байт, которым нельзя доверять раскладку.
 * Поэтому в интерфейсе метка берётся отсюда, а колонка «поедет в слот» - у rom_page_kind.
 * ================================================================================================= */
#ifndef ROM_IDENT_H
#define ROM_IDENT_H

#include <stdint.h>

#ifndef ROM_PG_SZ
#define ROM_PG_SZ 16384u                    /* страница ПЗУ - 16 КБ (та же константа, что в прошивке) */
#endif

/* Коды распознавания. Порядок значений не несёт смысла - смысл несёт метка и признак ниже. */
enum {
    RID_NOTZX = 0,      /* похоже, вообще не ПЗУ Спектрума (нет обращений к #FE) */
    RID_UNKNOWN,        /* ПЗУ Спектрума без известных нам подписей */
    RID_EMPTY_FF,       /* страница целиком 0xFF - пустое место в наборе */
    RID_EMPTY_00,       /* страница целиком 0x00 */
    RID_128MENU,        /* «1986 Sinclair Research» - 128-меню/редактор */
    RID_48BASIC,        /* «1982 Sinclair Research» - 48 BASIC */
    RID_128MOD,         /* отпечаток входа 128-меню, но подписи нет (переделанное ПЗУ) */
    RID_48MOD,          /* отпечаток входа 48 BASIC, но подписи нет (переделанное ПЗУ) */
    RID_TRDOS,          /* «TR-DOS Ver x.xx» - страница дисковода */
    RID_ESXDOS,         /* esxDOS (DivMMC) */
    RID_GLUK,           /* сервисное ПЗУ Mr Gluk Reset Service */
    RID_FATALL,         /* сервисное ПЗУ FATALL */
    RID_PROTEUS,        /* сервисное ПЗУ Proteus */
    RID_WDC,            /* WDCSETUP - настройка контроллера винчестера */
    RID_DIAG,           /* диагностическое ПЗУ (DiagROM / ZX Diagnostics) */
    RID_SDBOOT          /* загрузчик с карты (MINIBOOT и родня) */
};

/* Распознать страницу. `p` - ровно ROM_PG_SZ байт. В `out` (не меньше 20 байт) кладётся КОРОТКАЯ
   метка для интерфейса: только ASCII, ни одного многобайтового символа (канва - CP866).
   Возврат - код RID_*. `out` может быть 0, если нужен только код. */
int rom_page_ident(const uint8_t* p, char* out, int outn);

/* 1 = страница выглядит как ПЗУ Спектрума (есть подпись ИЛИ обращения к порту ULA #FE).
   Тот же вопрос, что у rom_page_is_zx() в прошивке, но доступный стенду. */
int rom_page_looks_zx(const uint8_t* p);

#endif /* ROM_IDENT_H */
