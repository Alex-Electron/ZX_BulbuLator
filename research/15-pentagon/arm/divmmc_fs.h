/* divmmc_fs.h - СИНТЕЗ ТОМА FAT16 ИЗ ПАПКИ НА КАРТЕ (основной режим DivMMC: проброс папки).
 *
 * Зачем отдельным файлом. loader_main.c уже под мегабайт, а здесь довольно замкнутая задача:
 * «дай сектор номер N так, будто это настоящая карта с файловой системой». Никакой связи с
 * фабрикой тут нет вовсе - модуль отдаёт байты, а кто их спросил (SPI-автомат DivMMC, стенд на
 * хосте или JTAG) ему безразлично. Поэтому он собирается и обычным gcc: -DDIVMMC_FS_HOST.
 *
 * Почему FAT16, а не FAT32. У FAT16 корневой каталог лежит в ОТДЕЛЬНОЙ области фиксированного
 * размера - для него не нужна цепочка кластеров, а значит корень отдаётся простым вычитанием
 * адреса. Плюс в FAT16 нет FSInfo с числом свободных кластеров, которое пришлось бы поддерживать
 * согласованным при записи. esxDOS понимает и то и другое, так что берём то, что дешевле.
 *
 * Главная идея раскладки: файл получает пробег кластеров подряд, потому что первичный
 * распределитель здесь наш собственный. Тогда «сектор -> кусок файла» это поиск пробега и одно
 * вычитание, без хождения по таблице размещения. ЗАПИСЬ это ломает: чужой драйвер волен выделить
 * рваную цепочку, поэтому пробегов у узла может быть несколько (см. divmmc_fs.c, таблица g_ext).
 */
#ifndef DIVMMC_FS_H
#define DIVMMC_FS_H

#include <stdint.h>

#define DMFS_SECSZ      512u
#define DMFS_MAXNODES   1024     /* файлов + папок во всём проброшенном дереве */
#define DMFS_NAMEPOOL   (48u*1024u)  /* общий пул имён (длинных, как они лежат на карте) */
#define DMFS_MAXDEPTH   6        /* глубина вложенности папок */
#define DMFS_MAXPATH    256      /* путь для FatFs */
/* Записей в корневом каталоге. У FAT16 корень - область ФИКСИРОВАННОГО размера, и её длина
   объявлена в BPB, поэтому число берётся не из воздуха. Классические 512 записей кончаются
   быстро: у имени вроде «Manic Miner (1983)(Bug-Byte).tap» уходит четыре записи вместо одной,
   то есть корень вмещал бы всего сотню файлов. Берём 2048 (128 секторов корня, генерируем на
   лету, места это не стоит). Если esxDOS вдруг окажется привередлив - вернуть 512, стенд ловит
   переполнение честно: лишнее уходит в «пропущено», том остаётся исправным.
   ВАЖНО: предел есть ТОЛЬКО у корня. Каталог подпапки - обычная цепочка кластеров, и в неё
   влезает столько, сколько позволит DMFS_MAXNODES. Большую коллекцию правильно класть не в
   корень проброшенной папки, а в подпапку. */
/* v355: ЗАПИСЕЙ КОРНЯ теперь ДВА значения, и выбирает владелец - потребители требуют разного.
   DMFS_ROOTENT_ESX (2048) - значение по умолчанию: на нём esxDOS грузит с папочного тома то, что
   на 512 зависает (Elysium State, найдено делением пополам 14.08).
   DMFS_ROOTENT_LFN (512)  - требование LFN-браузера Bob Fossil: он читает RootEntCnt буквально
   и при другом значении не стартует. Подробности ниже сохранены как есть. */
#define DMFS_ROOTENT_ESX 2048
#define DMFS_ROOTENT_LFN 512
#define DMFS_ROOTENT    DMFS_ROOTENT_ESX      /* 🥇 РОВНО 512, и это не наш выбор, а требование чужих разборщиков.
                                    Софт, который читает том СЫРЫМИ СЕКТОРАМИ, а не через файловую
                                    систему esxDOS, проверяет это поле буквально. LFN-браузер Bob
                                    Fossil: BROWSE.BIN +0x0B75 `CP 2` по старшему байту RootEntCnt,
                                    несовпадение -> код 1 -> синий бордюр -> выход ДО главного цикла.
                                    Снаружи это выглядит как «нарисовал рамку и вернулся в бейсик»,
                                    и полдня искалось в нашем железе. Мало того, размер корня он
                                    считает 16-битным HL*32: при 2048 это 65536, то есть НОЛЬ.
                                    Было 2048 - число выбиралось из соображения «побольше файлов в
                                    корне», без оглядки на тех, кто том разбирает сам.
                                    ⚠ Ограничение только на КОРЕНЬ: подкаталоги - цепочки кластеров
                                    и не ограничены. Переполнение корня прошивка обязана сказать
                                    словами - счётчик g_i.skipped для этого уже есть. */
#define DMFS_SPC        64       /* секторов в кластере FAT16: 32 КБ */
#define DMFS_SPC_SH     6        /* log2(DMFS_SPC): деления в горячем пути у нас нет */
/* 🥇 У FAT32 кластер МЕЛЬЧЕ намеренно. Спецификация даёт жёсткую нижнюю границу 65525 кластеров:
   меньше - и чужой разборщик обязан понять том как FAT16, то есть иначе, чем мы его написали.
   65525 кластеров по 4 КБ - это 268 МБ объявленного тома, почти весь пустой; для карты, которой
   не существует, это ничего не стоит, а 32-КБ кластер потребовал бы двух гигабайт. */
#define DMFS_SPC32      8        /* секторов в кластере FAT32: 4 КБ */
#define DMFS_SPC32_SH   3

/* --- ресурсы, которые появились вместе с записью ------------------------------------------- */
/* Пробеги кластеров. Первичная раздача тратит по одному на узел; чужой драйвер добавляет свои,
   когда дописывает файл или выделяет рваную цепочку. Соседние кластеры сливаются в один пробег,
   поэтому обычная работа таблицу почти не растит. */
#define DMFS_MAXEXT     2048
/* Значения таблицы размещения, которые ещё не удалось выразить пробегами узлов: драйвер строит
   цепочку ДО того, как напишет запись каталога, и до её прихода эти кластеры ничьи. Как только
   владелец находится, записи отсюда уходят. Сюда же переписывается цепочка узла, у которого
   драйвер перекроил размещение (см. chain_disown). */
#define DMFS_MAXFATD    2048
/* Приговорённые узлы: запись каталога уже помечена удалённой, но файл на карте ещё цел. Нужны
   ровно на один сектор каталога - чужой драйвер переименовывает файл как «удалить + создать»,
   и опознать переименование можно только по совпадению первого кластера и размера. */
#define DMFS_CONDEMNED  20
/* Секторов в буфере отложенных данных (2 МБ). Нужен ровно для обратного порядка: данные пришли
   раньше имени. При нормальном порядке (mtools и esxDOS пишут метаданные первыми) не тратится. */
#define DMFS_SPOOLSEC   4096

/* результат divmmc_fs_build */
enum { DMFS_OK = 0, DMFS_E_PATH, DMFS_E_OPEN, DMFS_E_EMPTY };

/* области тома. По ним же ловится форматирование: служебные структуры синтезируем МЫ,
   значит запись в загрузочный сектор или в таблицу разделов - это не «сохранение файла»,
   а попытка переразметить том. */
enum { DMFS_A_GAP = 0, DMFS_A_MBR, DMFS_A_BOOT, DMFS_A_FAT, DMFS_A_ROOT, DMFS_A_DATA, DMFS_A_OUT };

/* причины отказа в записи */
enum { DMFS_W_OK = 0, DMFS_W_FORMAT, DMFS_W_DIRENT, DMFS_W_DATA, DMFS_W_OUTSIDE, DMFS_W_NOTREADY,
       DMFS_W_FULL,        /* кончился какой-то из наших пределов (узлы, пробеги, буфер) */
       DMFS_W_CROSS,       /* кластер уже принадлежит другому файлу - перекрёстная ссылка */
       DMFS_W_MEDIA };     /* отказала настоящая карта: не создать/не записать файл */

typedef struct {
    uint32_t files, dirs, skipped;
    uint32_t bytes;              /* суммарный размер файлов */
    uint32_t vol_sectors;        /* размер «карты» в секторах - это и уйдёт в CSD */
    uint32_t part_lba;           /* начало раздела */
    uint32_t fat_lba;            /* первая копия таблицы размещения */
    uint32_t root_lba;           /* корневой каталог */
    uint32_t data_lba;           /* область данных (кластер 2) */
    uint32_t fat_sectors;        /* размер ОДНОЙ копии таблицы */
    uint32_t clusters;           /* всего кластеров данных */
    uint32_t clusters_used;      /* из них заняты файлами и подкаталогами на момент сборки */
    uint32_t cluster_bytes;
    int      truncated;          /* не всё влезло: узлы / имена / кластеры */
} dmfs_info_t;

/* Счётчики записи - их же удобно выводить в строке состояния и в диагностику. */
typedef struct {
    uint32_t w_total;      /* всего секторов принесли на запись */
    uint32_t w_ok;         /* приняли */
    uint32_t w_rej;        /* отвергли (по любой причине) */
    uint32_t w_fat, w_dir, w_data;   /* принято по областям */
    uint32_t created, deleted, renamed, resized;
    uint32_t stolen;       /* цепочек, отобранных у прежнего владельца по требованию таблицы */
    uint32_t spooled;      /* секторов уложено в буфер отложенных данных */
    uint32_t spool_live;   /* из них ещё не разобрано по файлам */
    uint32_t orphan;       /* секторов, которые так и не нашли владельца */
    int      locked;       /* том заперт после попытки форматирования */
} dmfs_wstat_t;

/* Построить том из папки (например "0:/DIVMMC"). */
int          divmmc_fs_build(const char* folder);
void         divmmc_fs_set_rootent(unsigned n);   /* v355: до build; 512 или 2048, иное - к ближайшему */
void         divmmc_fs_set_format(int fat32);    /* v359: до build; 0 = FAT16, 1 = FAT32 */
void         divmmc_fs_close(void);
int          divmmc_fs_ready(void);

/* Размер синтезированной карты в секторах по 512 байт. */
uint32_t     divmmc_fs_sectors(void);

/* Сектор карты. 0 = отдали, иначе адрес вне тома (карта обязана ответить ошибкой). */
int          divmmc_fs_read(uint32_t lba, uint8_t* buf);

/* Запись. 0 = принято, иначе код DMFS_W_*. Всё, что чужой драйвер FAT пишет в том, доезжает
   до настоящей папки; переразметка тома отвергается. */
int          divmmc_fs_write(uint32_t lba, const uint8_t* buf);

/* Досбросить на карту всё, что держат открытые файлы (у FatFs это f_sync). Вызывать не
   обязательно - каждая законченная операция синхронизируется сама, - но перед выключением
   питания или сменой ядра это дешёвая страховка. */
int          divmmc_fs_flush(void);

int          divmmc_fs_area(uint32_t lba);
const char*  divmmc_fs_msg(void);                 /* короткая строка для строки состояния */
const dmfs_info_t*  divmmc_fs_info(void);
const dmfs_wstat_t* divmmc_fs_wstat(void);

/* Диагностика: во что отображается сектор. Возвращает область; для данных отдаёт имя файла
   (или папки) и смещение внутри него. */
int          divmmc_fs_map(uint32_t lba, const char** name, uint32_t* off);

#endif /* DIVMMC_FS_H */
