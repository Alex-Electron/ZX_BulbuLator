/* v270: живые регистры процессора карты. Нужны, чтобы РАЗЛИЧИТЬ «карта считает» и «карта считает
   лишнее»: цикл пересчёта сэмплов (ПЗУ 0x0EFB) гоняется по страницам счётчиком B, а `DJNZ` при
   B=0 крутится 256 РАЗ - это 8 МБ адресного пространства и 24 с ожидания при 12 МГц. Приборно
   видно по обратному отсчёту B. */
unsigned gs_regs_bcde(void){
    return ((unsigned)gs_cpu.registers.byte[Z80_B] << 24) | ((unsigned)gs_cpu.registers.byte[Z80_C] << 16)
         | ((unsigned)gs_cpu.registers.byte[Z80_D] << 8)  |  (unsigned)gs_cpu.registers.byte[Z80_E];
}
unsigned gs_regs_ahl(void){
    return ((unsigned)gs_cpu.registers.byte[Z80_A] << 24) | ((unsigned)gs_cpu.registers.byte[Z80_H] << 16)
         | ((unsigned)gs_cpu.registers.byte[Z80_L] << 8)  |  (unsigned)(gs_page & 0x3Fu);
}
/* рабочие ячейки прошивки карты (её ОЗУ 0x4000.. = gs_ram[0]) - оболочка кладёт их в мейлбокс,
   потому что ЧИТАТЬ gs_ram по JTAG нельзя: он в КЭШИРУЕМОЙ DDR и отдаст несогласованное */
unsigned gs_ram4(unsigned addr){
    unsigned o = (addr >= 0x4000u) ? (addr - 0x4000u) : 0u;
    if(o + 3u >= gs_ram_sz) return 0u;
    return ((unsigned)gs_ram[o+3] << 24) | ((unsigned)gs_ram[o+2] << 16)
         | ((unsigned)gs_ram[o+1] << 8)  |  (unsigned)gs_ram[o];
}

/* v272: ПОЧЕМУ ТИШИНА - тремя числами. `gs_n_latch` растёт только когда карта ЧИТАЕТ окно
   0x6000..0x7FFF (там и только там защёлкивается сэмпл канала), громкости ставит сам модуль
   внутренними портами 6..9, а `gs_ch` - то, что реально уходит в микшер. Без этих трёх мест
   «тихо» можно объяснить и остановившейся картой, и нулевой громкостью, и неверным форматом. */
unsigned gs_latch_get(void){ return gs_n_latch; }
unsigned gs_vols_get(void){
    return ((unsigned)gs_vol[3] << 24) | ((unsigned)gs_vol[2] << 16)
         | ((unsigned)gs_vol[1] << 8)  |  (unsigned)gs_vol[0];
}
unsigned gs_chans_get(void){
    return ((unsigned)(uint8_t)gs_ch[3] << 24) | ((unsigned)(uint8_t)gs_ch[2] << 16)
         | ((unsigned)(uint8_t)gs_ch[1] << 8)  |  (unsigned)(uint8_t)gs_ch[0];
}
