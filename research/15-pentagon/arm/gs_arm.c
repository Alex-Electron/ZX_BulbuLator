/* --- ОЧЕРЕДЬ ДАННЫХ ОТ СПЕКТРУМА (B0108) ---
 * 🥇 Зачем очередь, если в железе регистр данных ОДИН. Потому что X-Player заливает сэмплы
 * страницами по 256 байт и на ГРАНИЦЕ СТРАНИЦЫ пишет байт БЕЗ опроса флага (`OUTI` стоит раньше
 * проверки; между `JR Z` -> `DEC E` -> `JP NZ` проходит ~24 такта Z80, около 7 мкс). На настоящей
 * карте флаг снимается за микросекунды, поэтому это законно; у нас подтверждение идёт через ARM и
 * стоит сотни микросекунд - каждый 256-й байт пропадал (на модуле 22 КБ это 87 байт, модуль бит).
 * Теперь байты принимает упругая очередь: 256 позиций в ПЛИС + продолжение здесь. Карта вычерпывает
 * их своим темпом (12 МГц), а флаг данных для МАШИНЫ означает «очередь полна», а не «байт не
 * прочитан». Порядок сохраняется, потерь нет, тайм-аутов у GS-софта не бывает вовсе (проверено по
 * распакованному коду X-Player, Mod Player и драйвера производителя) - значит «медленнее настоящей
 * карты» законно, а «потеряно» - нет.
 */
#define GS_INQ_LEN  32768u                    /* 32 КБ: модуль целиком влезает, дальше работает
                                                 обратное давление через флаг «очередь полна» */
#define GS_INQ_MASK (GS_INQ_LEN - 1u)
/* 🥇 ОДНА ОЧЕРЕДЬ НА ДАННЫЕ И КОМАНДЫ. В железе регистр обмена ОДИН, и порядок записей Спектрума
   сохраняется сам собой. Упругая очередь этот порядок ломала двумя способами, и оба стоили звука:
     - `#D2 Close Stream` обгонял ещё не вычерпанные байты, и карта закрывала поток на середине;
     - если держать команду до опустошения очереди, намертво виснет обычная пара «параметр, потом
       команда» (`SD номер : SC #39`): в холостом цикле карта порт данных не читает вовсе.
   Поэтому в очередь кладутся ОБА вида записей с признаком: данные карта забирает портом 2, а
   команда выдаётся ей ровно тогда, когда дошла её очередь И предыдущая уже подтверждена. */
#define GS_Q_CMD 0x100u                       /* признак «это команда, а не байт данных» */
static uint16_t gs_inq[GS_INQ_LEN];
static volatile uint32_t gs_inq_w, gs_inq_r;  /* монотонные индексы (32 бита = атомарно на A9) */
static volatile uint8_t  gs_din_last;         /* последнее вычерпанное - холостое чтение порта 2 отдаёт его */
static unsigned gs_n_indrop;                  /* байтов потеряно на нашей стороне (должно быть 0) */
static uint32_t gs_ncmd_q;                    /* сколько НЕвыданных команд лежит в очереди */
/* 🥇 v0.15.298 ГДЕ В ОЧЕРЕДИ ЛЕЖИТ БЛИЖАЙШАЯ КОМАНДА - ЗАПОМИНАЕМ, А НЕ ИЩЕМ КАЖДЫЙ РАЗ.
   Обгон команды (см. gs_cmd_release) искал её ОБХОДОМ всей очереди, а очередь бывает на 32 тысячи
   записей и обход шёл на КАЖДЫЙ вызов (120 тыс/с). Пока карта занята собой - например, чистит
   мегабайт своей памяти при инициализации, - обход не находил ничего и повторялся вхолостую:
   миллиарды шагов в секунду ровно в те моменты, когда карта и так не успевает. Позицию ставит
   запись команды, снимает - её выдача; неизвестной она бывает не дольше одного разбора. */
static uint32_t gs_cmd_pos;                   /* монотонный индекс ближайшей невыданной команды */
static int      gs_cmd_pos_ok;                /* 0 = позиция неизвестна (нужен один разбор очереди) */
static uint32_t gs_scan_i;                    /* v299: где остановился разбор очереди (он идёт кусками) */
static int      gs_scan_on;                   /* v299: разбор начат и не закончен */
unsigned gs_inq_used(void){ return (unsigned)(gs_inq_w - gs_inq_r); }
unsigned gs_inq_room(void){ return GS_INQ_LEN - 1u - gs_inq_used(); }
unsigned gs_indrop_get(void){ return gs_n_indrop; }
static int gs_inq_head_is_data(void);   /* тело ниже: в голове очереди ДАННЫЕ, а не команда */
/* v269 приборы для разбора «пауза после загрузки модуля»: сколько раз карта ПЕРЕКЛЮЧАЛА СТРАНИЦУ
   (порт 0) и где лежит её ОЗУ - по нему читаются рабочие ячейки прошивки прямо через JTAG. */
unsigned gs_pgsel_get(void){ return gs_n_pwr[0]; }
/* v298: сколько раз карта прочитала порт флагов (0x4). В холостом цикле прошивки (`LOADWT`) это
   происходит непрерывно, а пока она мерит и чистит свою память - не происходит вовсе. По этому
   счётчику видно, ЗАКОНЧИЛА ли карта инициализацию, и прогон при включении можно не гадать по
   часам, а прекращать по делу (см. gs_boot). */
unsigned gs_poll_get(void){ return gs_n_prd[4]; }
unsigned gs_rambase_get(void){ return (unsigned)(unsigned long)gs_ram; }
unsigned gs_cyc_get(void);

