/* Такты Z80 до следующего прерывания. Считаем ТАКТАМИ ПРОЦЕССОРА, а не таймером ARM: иначе при любом
 * рассогласовании скорости эмуляции звук поедет по темпу, а не просто станет тише.
 * 🥇 v0.15.298 БЕЗ ДЕЛЕНИЯ В ГОРЯЧЕМ ПУТИ. Раньше «сколько тактов осталось до прерывания» считалось
 * делением на каждом шаге прогона (не реже раза на выходной сэмпл, 48 тыс/с, а на деле чаще), а у
 * Cortex-A9 целочисленного делителя НЕТ - это вызов библиотечной подпрограммы. Период известен
 * заранее: 12000000/37480 = 320 тактов и остаток 6400/37480, поэтому держим обычный обратный
 * счётчик и перезаряжаем его по Брезенхэму - одно сложение и одно сравнение. */
/* v0.15.336: величины стали ПЕРЕМЕННЫМИ (см. gs_set_clock_hz). 12 МГц -> 320 и 6400,
   18 МГц -> 480 и 9600, 24 МГц -> 640 и 12800; частота прерывания при этом ровно 37480 Гц. */
#define GS_INT_PER  (gs_int_per_v)                             /* целых тактов на прерывание */
#define GS_INT_REM  (gs_int_rem_v)                             /* дробная часть его периода */
