/* ---------------- карта памяти ----------------
 * 0x0000-0x3FFF  первые 16 КБ ПЗУ
 * 0x4000-0x7FFF  первые 16 КБ первой страницы ОЗУ
 * 0x8000-0xFFFF  листаемая страница 32 КБ (0 = ПЗУ, 1 = первая страница ОЗУ, 2.. = ОЗУ)
 *
 * 🥇 v0.15.298 СТРАНИЦУ АДРЕСУЕМ ТАБЛИЦЕЙ, А НЕ АРИФМЕТИКОЙ. Причина: gs_map зовётся на КАЖДЫЙ
 * доступ Z80 (при 12 МГц это ~3 млн раз в секунду), и в нём стояли умножение `(pg-1)*0x8000` и
 * сравнение с ОБЪЯВЛЕННЫМ объёмом `gs_ram_sz`. Сама по себе эта работа O(1), но она повторяет на
 * каждом байте то, что меняется только при записи в порт 0 и при смене объёма карты. Считаем
 * заранее: база каждой из 64 страниц лежит в таблице, а текущая ещё и защёлкнута в двух указателях
 * (отдельно чтение и запись - у страницы 0 запись обязана пропадать, это ПЗУ). Горячий путь стал
 * «взять указатель и прибавить смещение», и он одинаков для 128 КБ и для 4 МБ - объём памяти карты
 * больше не участвует в её темпе ВООБЩЕ.
 */
static uint8_t* gs_pg_rd[64];                 /* куда смотрит страница при ЧТЕНИИ (0 = памяти нет) */
static uint8_t* gs_pg_wr[64];                 /* при ЗАПИСИ (0 = ПЗУ или несуществующая страница) */
static uint8_t* gs_cur_rd;                    /* защёлка текущей страницы: ставится записью в порт 0 */
static uint8_t* gs_cur_wr;
static void gs_pages_rebuild(void)
{
    for(unsigned p = 0; p < 64u; p++){
        if(p == 0u){                                   /* страница 0 = вторая половина ПЗУ, только чтение */
            gs_pg_rd[p] = &gs_rom[0];
            gs_pg_wr[p] = 0;
        } else if((uint32_t)p * 0x8000u <= gs_ram_sz){ /* страницы целые, поэтому проверка одна на всю */
            gs_pg_rd[p] = &gs_ram[((uint32_t)p - 1u) * 0x8000u];
            gs_pg_wr[p] = gs_pg_rd[p];
        } else {                                       /* за объявленным объёмом памяти нет вовсе:
                                                          чтение отдаёт 0xFF, запись пропадает - именно
                                                          по этому карта и МЕРИТ свою память */
            gs_pg_rd[p] = 0;
            gs_pg_wr[p] = 0;
        }
    }
    gs_cur_rd = gs_pg_rd[gs_page & 0x3Fu];
    gs_cur_wr = gs_pg_wr[gs_page & 0x3Fu];
}
static inline uint8_t* gs_map(uint16_t a, int write)
{
    if(a < 0x4000u) return write ? 0 : &gs_rom[a];                 /* ПЗУ: запись игнорируем */
    if(a < 0x8000u) return &gs_ram[a - 0x4000u];                   /* первая страница ОЗУ, нижняя половина */
    {   uint8_t* b = write ? gs_cur_wr : gs_cur_rd;
        return b ? (b + (a - 0x8000u)) : 0;
    }
}

uint8_t gs_mem_read(uint16_t a)
{
    uint8_t* p = gs_map(a, 0);
    uint8_t  v = p ? *p : 0xFFu;
    /* 🥇 защёлкивание канала по ЧТЕНИЮ окна 0x6000..0x7FFF, канал из A[9:8], байт в знаковый */
    if((a & 0xE000u) == 0x6000u){
        gs_ch[(a >> 8) & 3u] = (int8_t)(v ^ 0x80u);
        gs_n_latch++;
    }
    return v;
}

void gs_mem_write(uint16_t a, uint8_t v)
{
    uint8_t* p = gs_map(a, 1);
    if(p) *p = v;
}

/* --- 🥇 ОЧЕРЕДЬ ОТВЕТОВ КАРТЫ (v0.15.334). Лечит затыки звука на смене паттернов. ---
 *
 * Болезнь. `HSEND` в прошивке карты (ПЗУ 0xC25D: `IN A,(4) : OR A : RET P : RRCA : JP NC,HSEND :
 * JP главный_цикл`) КРУТИТСЯ, пока Спектрум не заберёт байт: единственный выход - приход новой
 * команды. Команды `#63`/`#64` (анализатор) отдают по 4 байта, то есть по четыре таких ожидания, а
 * плеер читает анализатор каждый кадр. У настоящей карты один обмен стоит 2-10 мкс, у нас - не
 * меньше ДВУХ проходов главного цикла оболочки (замеренный хвост: 1077 проходов длиннее
 * миллисекунды, худший 134 мс). Всё это время карта не зовёт `ENGINE`, кольцо квантов
 * (8 x 256 x 4 = 54.6 мс звука) тает, и срабатывает `QTFAULT` (`INTTST.a80:160`), который кончается
 * `RET` БЕЗ `EI`: прерывания остаются запрещены, защёлок сэмплов нет, ЦАП держит уровень. Это и
 * есть слышимая дыра. Лечить надо СТОИМОСТЬ ОДНОГО БАЙТА, а не темп эмуляции.
 *
 * Лечение. Оболочка забирает байт у карты в очередь и отпускает `HSEND` в том же кванте. Машина
 * при этом вычерпывает очередь в своём темпе - ей ждать безвредно, у неё нет тающего кольца.
 *
 * 🥇 ЗАБИРАТЬ НАДО НЕ НА ЗАПИСИ, А НА ПЕРВОМ ОПРОСЕ - и вот почему (оплачено сломанной картой).
 * Первая версия правки клала байт в очередь прямо из `OUT (3),A`. Карта тут же перестала работать:
 * `#20` вернул 0x000F00 вместо 0x07C000, `#38` выдал номер сэмпла 192 вместо 1, прерываний 0.
 * Причина - в железе порт 3 это РЕГИСТР, а не поток: байт, который никто не забрал, следующая
 * запись просто затирает. Прошивка этим законно пользуется и пишет туда мусор, которого Спектрум
 * не ждёт: два раза при инициализации (последний - 0x0F, своё же число страниц ОЗУ) и ещё раз в
 * общей развилке команд (ПЗУ 0xC289 `XOR A : OUT (3),A : IN A,(2) : OUT (5),A`, где следующий же
 * `IN A,(2)` гасит бит7). Очередь превращала затирание в лишние записи: перед первым настоящим
 * ответом в ней уже лежали два мусорных байта, поток ответов уехал на два байта и не выправлялся
 * никогда - оттуда и 0x0F в ответе на `#20`, и 0xC0 (второй байт `#20`) в роли номера сэмпла.
 *
 * Опрос как признак разделяет эти два случая ТОЧНО, а не по догадке: мусорный байт карта пишет и
 * либо сама гасит его `IN A,(2)`, либо затирает следующей записью - и НИ РАЗУ при этом не читает
 * порт флагов. Замер по этому самому ПЗУ (инициализация + `#20` + 50 кадров окна трекера): 455
 * записей в порт 3, из них мусорных 2, и у обеих число опросов между записью и гашением РОВНО 0.
 * А байт, которого карта ждёт, опрашивается сразу же - `HSEND` стоит на `IN A,(4)` следующей
 * инструкцией. Цена выхода из `HSEND` при этом даже меньше, чем у настоящей карты: 11 тактов
 * (~0.9 мкс) против 2-10 мкс.
 *
 * 🥇 И ХВОСТ ОТВЕТА ОБЯЗАН ИСЧЕЗАТЬ ПО НОВОЙ КОМАНДЕ - иначе очередь опаснее болезни. Бит7 у GS
 * ОДИН на оба направления (документация карты: он ставится и записью Спектрума в регистр данных, и
 * записью карты в регистр вывода; снимается чтением любой из сторон). Отсюда два следствия.
 * Первое: недочитанный хвост многобайтового ответа - ШТАТНОЕ событие протокола, а не экзотика:
 * `HSEND` сам уходит в главный цикл по приходу новой команды (`JP NC,#C25D` крутиться,
 * `JP #026B` уйти), и хост имеет полное право не дочитать. В регистре такой хвост самоизлечивался
 * (следующий ответ его затирал), в очереди - нет: он встал бы в голову и сдвинул СЛЕДУЮЩИЙ ответ.
 * Второе: пока в очереди лежит невзятый байт, бит7 поднят, а документированное ожидание отправки
 * данных `WD: IN A,(#BB) : RLCA : JR C,WD` НЕ ИМЕЕТ ТАЙМ-АУТА - хост завис бы навсегда.
 * Поэтому запись в `#BB` (любая команда - в том числе `#00 Reset flags` и документированная
 * последовательность против зависания `XOR A : OUT (#B3),A : OUT (#BB),A : IN A,(#BB)`, где тоже
 * есть запись в `#BB`) ОЧИЩАЕТ очередь ответов. Регистр `gs_dout`/`gs_outp` при этом не трогаем:
 * без очереди хвост вёл себя именно так, и поведение обязано плавно сходиться к прежнему.
 *
 * Порядок байтов внутри одного ответа очередь сохраняет. Единственное отличие от настоящей карты:
 * между байтами многобайтового ответа бит7 не успевает мигнуть в ноль. Софт, ждущий именно СНЯТИЯ
 * бита перед следующим байтом, встретился нам ровно один раз (X-Player в фазе ЗАЛИВКИ, тот самый
 * `WD`) - но там он ждёт снятия флага ДАННЫХ, а очередь ответов к моменту заливки уже очищена
 * записью команды `#D1 Open Stream`.
 *
 * 🥇 ПЕРВЫЙ БАЙТ ОТВЕТА ХОСТ ЧИТАЕТ БЕЗ ОПРОСА БИТА7 (`SC #63 / WC / GD / WN / GD ...`): его гейт -
 * снятие флага КОМАНД, а не флаг данных. Значит голова обязана быть верной уже к моменту, когда
 * оболочка публикует `b0 = 0`. Инвариант держится сам: прошивка пишет байт РАНЬШЕ, чем снимает флаг
 * команд (ПЗУ 0xC2B8 `OUT (3),A : OUT (5),A : CALL HSEND`), а `gs_dout_get`/`gs_zx_read_data` при
 * пустой очереди отдают регистр - то есть тот же самый байт, ещё до его переезда в очередь.
 *
 * Глубина настраивается: `gs_outq_set_depth(0)` выключает очередь и возвращает прежнее поведение
 * БАЙТ-В-БАЙТ (все четыре внешние функции сводятся к прежним выражениям) - это годится и для A/B,
 * и для опции машины, если найдётся софт, которому нужна честная задержка. Когда очередь полна,
 * всё работает как раньше: карта честно ждёт места, опрашивая порт флагов. То есть очередь -
 * строгое надмножество прежнего поведения, а не замена.
 *
 * Чего очередь НЕ лечит (сказано прямо, чтобы не искали лечение там, где его нет): бит7 порта
 * флагов у карты собран как `gs_inq_head_is_data() || gs_outp`, и это НЕ наша выдумка - в железе
 * регистр обмена один, и один флаг честно значит «регистр занят» в обе стороны. Но наша ВХОДНАЯ
 * очередь держит этот флаг поднятым, пока в ней есть хоть байт, поэтому при невычерпанных данных
 * `HSEND` выходит не по «байт забрали», а по аварийному «пришла новая команда». Это отдельная
 * болезнь того же флага, и очередью ответов она не лечится. */
#define GS_OUTQ_SZ    16u                     /* самый длинный ответ ПЗУ - 4 байта (#63/#64); запас 4x */
#define GS_OUTQ_MASK  (GS_OUTQ_SZ - 1u)
static volatile uint8_t  gs_outq[GS_OUTQ_SZ];
static volatile unsigned gs_outq_w, gs_outq_r;
static unsigned gs_outq_depth = GS_OUTQ_SZ;   /* 0 = выключено, прежнее поведение байт-в-байт */
static unsigned gs_outq_peak;                 /* прибор: максимальная занятость очереди */
static unsigned gs_outq_taken;                /* прибор: сколько байтов забрано на опросе */
static uint32_t gs_out_t0;                    /* такт, на котором карта положила байт в регистр */
static uint8_t  gs_out_spun;                  /* карта уже спрашивала про этот байт - значит ЖДЁТ его */
static uint32_t gs_outq_spin;                 /* 🥇 прибор: сколько раз карта спросила «забрали?». Он
                                                 честен в ОБОИХ режимах и потому годится для A/B: с
                                                 очередью выходит ровно по одному опросу на байт, без
                                                 неё - весь цикл ожидания HSEND. */
static uint32_t gs_outq_wait_max;             /* 🥇 и сколько ТАКТОВ карта на этом простояла. Считаем
                                                 ТОЛЬКО байты, которых она ждала: ответ #62 карта
                                                 кладёт в регистр и уходит, его лежание - не простой. */
static uint32_t gs_outq_wait_sum, gs_outq_wait_n;
static unsigned gs_outq_used(void){ return gs_outq_w - gs_outq_r; }
void     gs_outq_set_depth(unsigned d){ gs_outq_depth = (d > GS_OUTQ_SZ) ? GS_OUTQ_SZ : d; }
unsigned gs_outq_get_depth(void){ return gs_outq_depth; }
unsigned gs_outq_get_used(void) { return gs_outq_used(); }
unsigned gs_outq_get_peak(void) { return gs_outq_peak; }
unsigned gs_outq_get_taken(void){ return gs_outq_taken; }
unsigned gs_outq_get_spin(void) { return gs_outq_spin; }
unsigned gs_outq_wait_worst(void){ return gs_outq_wait_max; }
unsigned gs_outq_wait_avg(void){ return gs_outq_wait_n ? (unsigned)(gs_outq_wait_sum / gs_outq_wait_n) : 0u; }
/* Байт ушёл от карты (в очередь или прямо машине) - закрываем счёт ожидания. Гашение своим же
   `IN A,(2)` и затирание следующей записью сюда НЕ идут: там карта ничего не ждала. */
static void gs_out_handoff(void)
{
    uint32_t d;
    if(!gs_out_spun) return;                  /* карта его не ждала - это не её простой */
    d = gs_n_cyc - gs_out_t0;
    if(d > gs_outq_wait_max) gs_outq_wait_max = d;
    gs_outq_wait_sum += d; gs_outq_wait_n++;
}
/* Карта спрашивает порт флагов, а бит7 у неё поднят - значит она стоит в `HSEND` и ждёт. Забираем
   байт себе и отпускаем её ПРЯМО НА ЭТОМ ЧТЕНИИ: `OR A : RET P` увидит уже снятый бит. */
static void gs_outq_offer(void)
{
    if(!gs_outp) return;
    if(gs_outq_used() >= gs_outq_depth) return;   /* глубина 0 = выключено; полна = карта ждёт места */
    gs_outq[gs_outq_w++ & GS_OUTQ_MASK] = gs_dout;
    if(gs_outq_used() > gs_outq_peak) gs_outq_peak = gs_outq_used();
    gs_outq_taken++;
    gs_outp = 0;
    gs_out_handoff();
}

/* ---------------- внутренние порты (A[3:0]) ---------------- */
/* 🥇 Побочные эффекты портов 2/3/5/A/B в gs.v висят на ЛЮБОМ IORQ, а не только на записи:
   `if (~cpu_iorq_n & cpu_m1_n) case(cpu_a_bus[3:0]) 'h2: bit7<=0; 'h3: bit7<=1; 'h5: bit0<=0; ...`
   Поэтому эффект обязан быть в обоих направлениях. ИСПРАВЛЕНИЕ прежнего комментария: прошивка
   gs105b снимает флаг команд ЗАПИСЬЮ `OUT (5),A` - в ПЗУ 101 такая пара и НИ ОДНОГО `IN A,(5)`
   (проверено сканом образа). Утверждение про чтение было моим домыслом; на логику это не влияет,
   но обоснование было ложным. */
static void gs_port_side_effects(uint16_t port)
{
    switch(port & 0x0Fu){
    /* 🥇 v267: обращение к порту 0x2 ГАСИТ и «есть байт от карты». В апстриме флаг ОДИН
       (`gs.v:145` `'h2: bit7 <= 0`), а я разнёс его на два - очередь входа и признак выхода - и
       забыл про эту связь. Цена: X-Player послал команду 0xD1 с байтом данных и встал навсегда в
       `WD: IN A,(#BB) : RLCA : JR C,WD` (он ждёт СНЯТИЯ бита7 перед следующим байтом), потому что
       `outp` стоял с инициализации карты, а снять его могло только чтение #B3 машиной - которого
       плеер в этой фазе не делает вовсе. Байт при этом ВЫЧЕРПЫВАЕТСЯ только если он есть
       (гоча v264: прошивка делает холостые чтения этого порта из ПЗУ). */
    case 0x2: gs_outp = 0; break;
    case 0x3: gs_outp = 1; break;                    /* карта отдала байт Спектруму */
    case 0x5: gs_b0 = 0; break;                      /* CLRCBIT: только карта имеет право снять флаг команд */
    /* Порты 0xA/0xB прошивка gs105b НЕ ИСПОЛЬЗУЕТ НИ РАЗУ (проверено сканом ПЗУ: ни `DB 0A/0B`,
       ни `D3 0A/0B` в коде нет - две найденные пары `D3 0A` лежат внутри таблицы частот). Держим
       их как в КОДЕ живого апстрима (`gs.v:148-149`), а не как в его шапке: шапка говорит про
       бит5 порта #06, код берёт `port_09[5]` - это громкость КАНАЛА 4. Расхождение апстрима с
       собственной документацией; выбран код, потому что он проверен в поле. */
    case 0xA: gs_outp = (uint8_t)!(gs_page & 1u); break;
    case 0xB: gs_b0 = (uint8_t)((gs_vol[3] >> 5) & 1u); break;
    default: break;
    }
}

uint8_t gs_port_read(uint16_t port)
{
    uint8_t v;
    gs_n_prd[port & 0x0Fu]++;
    switch(port & 0x0Fu){
    case 1:  gs_n_cmdrd++; v = gs_cmd; break;                       /* команда от Спектрума */
    case 2:  v = gs_inq_head_is_data() ? (uint8_t)(gs_inq[gs_inq_r & GS_INQ_MASK] & 0xFFu) : gs_din_last; break;
    case 4:  if(gs_outp){ gs_outq_spin++; gs_out_spun = 1; }   /* карта спрашивает «забрали?» - значит ЖДЁТ */
             gs_outq_offer();               /* ...вот здесь и забираем (см. очередь ответов выше) */
             v = (uint8_t)(((gs_inq_head_is_data() || gs_outp) ? 0x80u : 0u) | 0x7Eu | (gs_b0 ? 1u : 0u)); break;
    default: v = 0xFFu; break;
    }
    /* 🥇 v264: порт 0x02 - ЗАЩЁЛКА, а не поток. Прошивка GS делает ХОЛОСТОЕ чтение этого порта из
       ПЗУ, и если потреблять байт на каждом чтении, настоящие данные пропадают, а плеер сбивается.
       Вычерпываем ТОЛЬКО когда в очереди что-то есть; при пустой отдаём последнее значение, не
       трогая состояние. Остальные порты - как прежде. */
    if((port & 0x0Fu) == 0x2u){
        if(gs_inq_head_is_data()){ gs_din_last = v; gs_inq_r++; }   /* вычерпываем ТОЛЬКО данные */
        gs_port_side_effects(port);                          /* но флаг гасим всегда - как апстрим */
    } else {
        gs_port_side_effects(port);
    }
    return v;
}

void gs_port_write(uint16_t port, uint8_t v)
{
    gs_n_pwr[port & 0x0Fu]++;
    switch(port & 0x0Fu){
    /* v298: заодно защёлкиваем базы страницы - дальше доступы идут БЕЗ арифметики (см. gs_map) */
    case 0x0: gs_page = v & 0x3Fu; gs_cur_rd = gs_pg_rd[gs_page]; gs_cur_wr = gs_pg_wr[gs_page]; break;
    case 0x3: gs_dout = v; gs_out_t0 = gs_n_cyc; gs_out_spun = 0; break;   /* байт для Спектрума */
    case 0x6: gs_vol[0] = v & 0x3Fu; gs_n_vol++; break;
    case 0x7: gs_vol[1] = v & 0x3Fu; break;
    case 0x8: gs_vol[2] = v & 0x3Fu; break;
    case 0x9: gs_vol[3] = v & 0x3Fu; break;
    default: break;
    }
    gs_port_side_effects(port);
}

/* ---------------- сторона Спектрума ----------------
 * Эти четыре функции вызываются обслуживанием ловушки портов: фабрика защёлкнула доступ, ARM его
 * разбирает. Правила бит - те же, что в gs.v: чтение #B3 сбрасывает бит7, запись #B3 ставит бит7,
 * запись #BB ставит бит0.
 */
/* 🥇 КОМАНДА НЕ ИМЕЕТ ПРАВА ОБОГНАТЬ ДАННЫЕ. Упругая очередь развязала Спектрум и карту по ДАННЫМ,
   но команды идут отдельным путём и доходили МГНОВЕННО - а на настоящей карте регистр данных один
   и флаг гейтит каждый байт, поэтому к моменту команды карта заведомо вычерпала весь поток.
   Симптом на стенде: сэмпл 4096 байт отдан, в очереди ещё 2248, а `#D2 Close Stream` уже пришёл -
   карта закрывает поток на середине, и играть нечего. Ровно это и происходило с модулем на плате:
   заливка «успешна», звука нет. Держим команду у себя, пока очередь не опустеет; флаг команд при
   этом остаётся поднятым, то есть машина законно ждёт - как ждала бы и у настоящей карты. */
void    gs_zx_write_cmd (uint8_t v){
    /* 🥇 Новая команда обрывает прошлый ответ - так делает и сама карта (`HSEND` уходит в главный
       цикл по флагу команд). Недочитанный хвост в очереди сдвинул бы следующий ответ, а поднятый
       им бит7 навсегда повесил бы хост в его ожидании отправки данных `WD` (тайм-аута там нет).
       Регистр не трогаем: без очереди хвост вёл себя ровно так, и поведение сходится к прежнему. */
    gs_outq_w = gs_outq_r = 0;
    if(gs_inq_room() == 0u){ gs_n_indrop++; return; }
    if(!gs_cmd_pos_ok){ gs_cmd_pos = gs_inq_w; gs_cmd_pos_ok = 1; }   /* v298: помним, ГДЕ она легла */
    gs_inq[gs_inq_w & GS_INQ_MASK] = (uint16_t)(v | GS_Q_CMD);
    gs_inq_w++; gs_ncmd_q++;
}
/* 🥇 КОГДА КОМАНДА ИМЕЕТ ПРАВО ОБОГНАТЬ ДАННЫЕ. В железе регистров ДВА - командный и данных, у
   каждого свой флаг, поэтому обычная пара «параметр, потом команда» (`SD номер : SC #39`) работает
   без всякого порядка: обработчик команды сам читает параметр из регистра данных. Порядок важен
   ТОЛЬКО внутри ПОТОКА, где Спектрум гонит байты, а флаг гейтит каждый: там `#D2 Close Stream` не
   может прийти раньше последнего байта. У нас очередь упругая, и оба случая надо различать - по
   ПОВЕДЕНИЮ КАРТЫ: пока она вычерпывает очередь, идёт поток, и команда ждёт; перестала вычерпывать
   (холостой цикл порт данных не читает вовсе) - значит это параметр к самой команде, и держать
   её больше нельзя, иначе намертво зависнем. Порог 2000 тактов ~ 166 мкс виртуального времени. */
#define GS_CMD_STALL 2000u
/* 🥇 v0.15.299 ПРАВИЛО ОЖИДАНИЯ ПРИДУМАНО ДЛЯ ПОТОКА ДАННЫХ - К ОПРОСУ СОСТОЯНИЯ ОНО НЕ ОТНОСИТСЯ.
   Наблюдение владельца с живой платы: «когда закрывается окно плеера (трекера, где всё бежит и
   мигает) - музыка идёт БЕЗ СБОЕВ». Окно трекера десятки раз в секунду спрашивает у карты позицию,
   ноты и громкости (#60..#64), и КАЖДЫЙ такой запрос шёл через ту же машинерию, что и поток
   сэмплов: если в очереди перед ним лежал хоть один невзятый байт, запрос ждал 2000 тактов
   виртуального времени (166 мкс), а потом ещё и СХЛОПЫВАЛ данные.
   Обгон разрешён только командам, которые НЕ ЧИТАЮТ входной регистр данных. Точный список ниже
   сверен с обработчиками ПЗУ: прежняя проверка целых диапазонов ошибочно включала #22/#2A..#2F и
   #65/#66/#6A/#6B, которые забирают один или два входных байта и потому не имеют права обгонять. */
static int gs_cmd_is_query(uint8_t c){
    switch(c){
    case 0x20: case 0x21: case 0x23:
    case 0x60: case 0x61: case 0x62: case 0x63: case 0x64:
    case 0x67: case 0x68: case 0x69:
        return 1;
    default:
        return 0;
    }
}
static unsigned gs_n_query;                   /* сколько запросов ушло мимо очереди - прибор темпа */
unsigned gs_query_get(void){ return gs_n_query; }
static uint32_t gs_inq_r_seen, gs_stall_cyc;
/* На живой плате перед #20 поймана ровно очередь [данные, метка съеденной команды, #20].
   Первый байт ответа #20 машина читала, но старые данные продолжали держать внутренний bit7, и
   обе стороны навсегда ждали друг друга. Удаляем только эту доказанную форму старой защёлки:
   активный поток без метки под это условие попасть не может. */
static int gs_drop_stale_latch_before(uint32_t pos){
    uint32_t r = gs_inq_r;
    uint16_t d;
    if(pos - r != 2u) return 0;
    d = gs_inq[r & GS_INQ_MASK];
    if((d & GS_Q_CMD) || d == 0x200u) return 0;
    if(gs_inq[(r + 1u) & GS_INQ_MASK] != 0x200u) return 0;
    gs_inq_r = pos;
    gs_inq_r_seen = pos;
    gs_stall_cyc = 0;
    gs_scan_on = 0;
    return 1;
}
static void gs_cmd_release(void){
    if(gs_b0) return;                                     /* прошлая ещё не подтверждена картой */
    if(gs_inq_w == gs_inq_r) return;
    if(gs_inq_r != gs_inq_r_seen){ gs_inq_r_seen = gs_inq_r; gs_stall_cyc = 0; }
    {   uint16_t e = gs_inq[gs_inq_r & GS_INQ_MASK];
        if(e & GS_Q_CMD){                                  /* команда в голове - отдаём сразу */
            gs_cmd = (uint8_t)(e & 0xFFu); gs_b0 = 1; gs_inq_r++; gs_inq_r_seen = gs_inq_r;
            if(gs_ncmd_q) gs_ncmd_q--;
            gs_cmd_pos_ok = 0;                             /* следующую найдём один раз, когда понадобится */
            return;
        }
    }
    if(gs_ncmd_q == 0u) return;                            /* 🥇 v298: команд в очереди НЕТ - искать нечего.
                                                              Без этой строки обход всей очереди шёл на
                                                              каждом вызове, стоило карте задуматься. */
    /* 🥇 v0.15.299 ЗАПРОС СОСТОЯНИЯ - НЕМЕДЛЕННО И ДЁШЕВО (см. gs_cmd_is_query выше).
       Условие `gs_cmd_pos_ok` тут не ограничение, а гарантия дешевизны: позицию запоминает сама
       запись команды, и она известна ровно в том случае, который и бывает у трекера - одна команда
       в очереди. Когда команд накопилось несколько, позиция ближайшей неизвестна, и лезть её ИСКАТЬ
       здесь нельзя: обход очереди на 32 тысячи записей в горячем пути и есть та работа, которую
       v298 отсюда убирал. Такой запрос просто пойдёт прежней дорогой - он не первый в очереди, и
       перед ним всё равно стоит другая команда. */
    if(gs_cmd_pos_ok){
        uint16_t e = gs_inq[gs_cmd_pos & GS_INQ_MASK];
        if((e & GS_Q_CMD) && gs_cmd_is_query((uint8_t)(e & 0xFFu))){
            gs_cmd = (uint8_t)(e & 0xFFu);
            (void)gs_drop_stale_latch_before(gs_cmd_pos);
            gs_b0  = 1;
            /* 🥇 ЯЧЕЙКУ ЗАПРОСА НАДО ВЕРНУТЬ ОЧЕРЕДИ, А НЕ ПРОСТО ПОМЕТИТЬ. Пометка «съедено»
               освобождается только когда до неё дойдёт ГОЛОВА, а голова стоит за невзятым байтом
               данных - и пока карта его не читает, пометки копятся. На стенде с одним повисшим
               байтом это дало 7501 запись в очереди за пять секунд опроса, то есть за полминуты
               очередь на 32 тысячи переполнилась бы и начали бы теряться команды. У трекера запрос
               ВСЕГДА последний в очереди (он только что пришёл), поэтому просто сдвигаем хвост
               назад; пометка остаётся только в редком случае, когда за запросом уже легли данные -
               там она освободится штатно, вместе с ними. */
            if(gs_cmd_pos == gs_inq_w - 1u) gs_inq_w--;
            else gs_inq[gs_cmd_pos & GS_INQ_MASK] = 0x200u;
            if(gs_ncmd_q) gs_ncmd_q--;
            gs_cmd_pos_ok = 0;
            gs_n_query++;
            return;
        }
    }
    if(gs_stall_cyc < GS_CMD_STALL) return;                /* карта ещё берёт данные - это поток */
    /* 🥇 v0.15.299 РАЗБОР ОЧЕРЕДИ - ШАГАМИ ПО 512, А НЕ ЦЕЛИКОМ ЗА ВЫЗОВ.
       Требование владельца «ни одна ветка протокола не должна занимать столько, чтобы пропустить
       период ЦАП» здесь вполне конкретно: очередь бывает на 32 тысячи записей, один сплошной обход
       это около 30 мкс, а период ЦАП - 20.8 мкс. Разбор редкий (один на команду), но раз он
       случается прямо в производстве звука, режем его на куски и продолжаем с того же места. */
    if(!gs_cmd_pos_ok){
        uint32_t i, lim = 512u;
        if(!gs_scan_on){ gs_scan_i = gs_inq_r; gs_scan_on = 1; }
        /* курсор обязан лежать МЕЖДУ головой и хвостом: голову двигает схлопывание, хвост -
           возврат ячейки запроса. Вылез за любой край - начинаем разбор сначала, это дешевле
           одного лишнего прохода и надёжнее любых рассуждений о порядке событий. */
        if((int32_t)(gs_scan_i - gs_inq_r) < 0) gs_scan_i = gs_inq_r;
        if((int32_t)(gs_inq_w - gs_scan_i) < 0) gs_scan_i = gs_inq_r;
        for(i = gs_scan_i; i != gs_inq_w && lim; i++, lim--){
            if(gs_inq[i & GS_INQ_MASK] & GS_Q_CMD){ gs_cmd_pos = i; gs_cmd_pos_ok = 1; break; }
        }
        gs_scan_i = i;
        if(!gs_cmd_pos_ok){
            if(i == gs_inq_w){ gs_ncmd_q = 0; gs_scan_on = 0; }  /* счётчик разошёлся с очередью - чиним счётчик */
            return;                                              /* не дошли - продолжим следующим вызовом */
        }
        gs_scan_on = 0;
    }
    {   uint32_t i = gs_cmd_pos;                           /* карта встала: пропускаем команду вперёд */
        gs_cmd = (uint8_t)(gs_inq[i & GS_INQ_MASK] & 0xFFu);
        gs_b0 = 1;
        gs_inq[i & GS_INQ_MASK] = 0x200u;                  /* пометка «съедено», данные не сдвигаем */
        if(gs_ncmd_q) gs_ncmd_q--;
        gs_cmd_pos_ok = 0;
        /* 🥇 И СХЛОПНУТЬ НЕВЗЯТЫЕ ДАННЫЕ ДО ПОСЛЕДНЕГО БАЙТА. В железе регистр данных ОДИН:
           если карта их не прочитала, каждая следующая запись Спектрума просто затирала
           предыдущую, и до карты дошёл бы только ПОСЛЕДНИЙ байт. Наша очередь их копила -
           на плате Z-Player оставил в ней 258 повисших байт, и карта потом читала бы из
           потока чужое. Схлопываем ровно в момент обгона, то есть тогда же, когда стало
           ясно, что это не поток.
           v298: последний байт ищем НАЗАД от команды и останавливаемся на первом же - это тот
           самый «последний», и обход всей очереди больше не нужен. Пометки «съедено» (0x200)
           пропускаем: раньше они проходили проверку на данные и могли встать в очередь как байт. */
        {   uint32_t k = i, last_ok = 0; uint16_t last = 0;
            while(k != gs_inq_r){
                uint16_t e;
                k--;
                e = gs_inq[k & GS_INQ_MASK];
                if(!(e & GS_Q_CMD) && e != 0x200u){ last = e; last_ok = 1; break; }
            }
            gs_inq_r = i;                                  /* всё до команды выброшено */
            if(last_ok){                                   /* последний байт оставляем, как регистр */
                gs_inq_r--;
                gs_inq[gs_inq_r & GS_INQ_MASK] = last;
            }
            gs_inq_r_seen = gs_inq_r;
        }
    }
}
/* Счётчиком, а не обходом: зеркало флагов зовётся с КАЖДЫМ проходом насоса (замерено 218 тыс/с),
   а очередь бывает на 32 тысячи записей - обход там означал бы миллиарды тактов в секунду. */
static int gs_cmd_waiting(void){ return gs_ncmd_q != 0u; }
/* 🥇 ДВА ВЗГЛЯДА НА ФЛАГ КОМАНД, И ПУТАТЬ ИХ НЕЛЬЗЯ. Пока команда ждёт очередь, КАРТА не должна
   видеть флаг вовсе: её цикл загрузки (`LOADWT`: `IN A,(FLAGS) : AND #81 : RRCA : IN A,(DATRG) :
   JR C,LOADCM`) проверяет бит0 РАНЬШЕ данных и, увидев флаг, уходит читать команду - и прочитает
   СТАРУЮ. А МАШИНА обязана видеть флаг поднятым, иначе решит, что команда принята, и пошлёт
   следующую. Поэтому внутренний порт 4 отдаёт только `gs_b0`, а зеркало для фабрики - `gs_b0`
   ИЛИ «команда отложена». */
void    gs_zx_write_data(uint8_t v){                        /* байт из очереди фабрики */
    if(gs_inq_room() == 0u){ gs_n_indrop++; return; }       /* переполнение видно прибором */
    gs_inq[gs_inq_w & GS_INQ_MASK] = v;
    gs_inq_w++;                                             /* индекс ПОСЛЕ данных */
}
/* сколько ДАННЫХ ждёт карту прямо сейчас (до ближайшей команды) - это и есть её флаг данных */
static int gs_inq_head_is_data(void){
    while((gs_inq_w != gs_inq_r) && (gs_inq[gs_inq_r & GS_INQ_MASK] == 0x200u)) gs_inq_r++;  /* съеденная команда */
    return (gs_inq_w != gs_inq_r) && !(gs_inq[gs_inq_r & GS_INQ_MASK] & GS_Q_CMD);
}
uint8_t gs_zx_read_data (void)                                        /* машина забрала байт карты */
{
    /* Очередь впереди регистра: в ней лежат байты, которые карта уже отдала. `gs_outp` при этом
       НЕ гасим - он значит «в регистре лежит ЕЩЁ один, более новый байт», и погасить его здесь
       значило бы соврать карте, что забрали и его тоже. */
    if(gs_outq_used()) return gs_outq[gs_outq_r++ & GS_OUTQ_MASK];
    if(gs_outp) gs_out_handoff();
    gs_outp = 0;
    return gs_dout;
}
/* v258: отдать ответный байт БЕЗ побочного действия - фабрика сама снимает флаг по чтению
   машиной, а оболочке нужно лишь держать регистр в актуальном состоянии. */
uint8_t gs_dout_get(void)          { return gs_outq_used() ? gs_outq[gs_outq_r & GS_OUTQ_MASK]
                                                              : gs_dout; }
/* v261: живое состояние процессора GS для диагностики снаружи. Без него видно только края
   обмена, и непонятно, работает ли эмулятор вообще. */
unsigned gs_pc_get(void)           { return gs_cpu.pc; }
unsigned gs_iff_get(void)          { return (unsigned)((gs_cpu.iff1?1:0) | (gs_cpu.im<<1) | (gs_int_pend?8:0)); }
unsigned gs_cmdrd_get(void)        { return gs_n_cmdrd; }
unsigned gs_int_get(void)          { return gs_n_int; }
unsigned gs_page_get(void)         { return gs_page; }
/* Слово для ЗЕРКАЛА в фабрику. Бит7 здесь - ТОЛЬКО «у карты есть непрочитанный байт»: флаг данных
   для машины фабрика собирает сама как «очередь полна ИЛИ есть байт от карты» (B0108). */
uint8_t gs_zx_read_stat (void)     { return (uint8_t)(((gs_outp || gs_outq_used()) ? 0x80u : 0u) | 0x7Eu
                                                    | ((gs_b0 || gs_cmd_waiting()) ? 1u : 0u)); }

/* ---------------- микшер ----------------
 * Выход как в апстриме: L = ch1·vol1 + ch2·vol2, R = ch3·vol3 + ch4·vol4. Разрядность: сэмпл знаковый
 * 8 бит, громкость 6 бит -> произведение до 14 бит со знаком, сумма двух - до 15.
 */
void gs_mix(int16_t* l, int16_t* r)
{
    int32_t a = (int32_t)gs_ch[0] * (int32_t)gs_vol[0];
    int32_t b = (int32_t)gs_ch[1] * (int32_t)gs_vol[1];
    int32_t c = (int32_t)gs_ch[2] * (int32_t)gs_vol[2];
    int32_t d = (int32_t)gs_ch[3] * (int32_t)gs_vol[3];
    *l = (int16_t)(a + b);
    *r = (int16_t)(c + d);
}

/* ---------------- живой источник для звукового тракта ----------------
 * Один выходной сэмпл ЦАП: прогнать карту на такты, приходящиеся на его период, и снять микшер.
 * 🥇 Темп задаёт ЦАП, а не часы ARM. Фабричный FIFO вычерпывается ровно на 47996 Гц, поэтому пока
 * оболочка отдаёт по сэмплу на период, карта идёт в реальном времени 12 МГц сама собой - и музыка
 * не «поедет» по темпу, как поехала бы при привязке к таймеру (v258..v264 считали такты по XTime).
 * 12000000 / 47996 = 250.0208 такта на сэмпл: целые 250 плюс дробь по Брезенхэму.
 * Эмулятор кончает ИНСТРУКЦИЮ, а не такт, поэтому недобор/перебор переносим долгом.
 */
uint32_t gs_run(uint32_t cycles);                   /* тело ниже - прототип, чтобы не было неявного */
/* 🥇 v0.15.298 ТЕМП ПРИВЯЗАН К ЧАСАМ, А НЕ К ЧИСЛУ ПРОХОДОВ ЦИКЛА.
   Часы здесь - сам ЦАП: фабрика вычерпывает его очередь ровно 47996 раз в секунду независимо от
   того, чем занята оболочка. Пока карта успевает, каждый выданный сэмпл честно стоит 250.0208
   такта, и это и есть 12 МГц. Но если очередь опустела, ЦАП получает тишину, а виртуальное время
   карты в этот миг НЕ ИДЁТ ВООБЩЕ - и назад оно уже не возвращалось: карта навсегда отставала от
   реального времени, а GS-софт машины видел это как «9 МГц вместо 12». Теперь пропущенные слоты
   ЦАП становятся ДОЛГОМ в тактах (его вносит насос через gs_debt_slots), и карта его отрабатывает
   - но не рывком: не быстрее +25 % к темпу за сэмпл и не больше четверти секунды долга всего.
   Потолок нужен ровно затем, чтобы после долгой паузы (диалог, чтение с карты) музыка не
   выстрелила скороговоркой. */
#define GS_DEBT_MAX  (gs_clk_hz / 4u)               /* 0.25 с виртуального времени - разумный потолок догона */
static uint32_t gs_debt;                            /* сколько тактов карта задолжала реальному времени */
void gs_debt_slots(unsigned slots){                 /* слотов ЦАП прошло МИМО карты (очередь была пуста) */
    uint32_t add = slots * gs_smp_per_v;            /* тактов на слот ЦАП; дробь тут - шум */
    if(add > GS_DEBT_MAX || gs_debt > GS_DEBT_MAX - add) gs_debt = GS_DEBT_MAX;
    else gs_debt += add;
}
unsigned gs_debt_get(void){ return gs_debt; }

/* ================= v0.15.332 ПРИБОР «ГДЕ КАРТА ТЕРЯЕТ ЗВУК» =================
   Вопрос, на который отвечает прибор: почему при живом Z-Player на стыке паттерна пропадает звук,
   а в игре и в TR-DOS тот же модуль играет ровно.

   Разбор прошивки карты (исходники gs105b, firmware/src) говорит следующее:
     - кольцо квантов у карты `QTMAP DEFS #20` = 8 слотов x 256 сэмплов x 4 канала = 8 КБ = окно
       0x6000..0x7FFF, то есть ВЕСЬ её предбуфер это 54.6 мс звука;
     - наполняет кольцо ГЛАВНЫЙ цикл (`COMINT_` -> `CALL ENGINE`), он же командный интерпретатор,
       и команду он обслуживает РАНЬШЕ звука;
     - `#63 Get Channel Notes` и `#64 Get Channel Volumes` отдают по 4 байта, и после КАЖДОГО зовут
       `HSEND` — а `HSEND` крутится, пока Спектрум байт не заберёт (`COM_H.a80:873-878`);
     - 🥇 когда кольцо опустело, прерывание уходит в `QTFAULT` (`INTTST.a80:160`), а тот кончается
       `RET` БЕЗ `EI`: прерывания остаются запрещены, сэмплы не защёлкиваются вовсе, ЦАП держит
       последний уровень — до `QTPLAY` (`INTTST.a80:338`), где стоит `IM 1`/`EI`.
   То есть «дыра» это не наш звуковой тракт, а собственный underrun карты, до которого её доводит
   дорогое рукопожатие: у настоящей GS байт ответа стоит 2..10 мкс, у нас — проход главного цикла.

   Адреса сняты СКАНОМ `assets_gs105b.rom` по сигнатурам из исходников (не по догадке). ПЗУ карты
   видно в двух окнах сразу: нижние 16 КБ по 0x0000 (там обработчик прерывания, там же QTFAULT и
   QTPLAY) и страница 0 по 0x8000 (там главный цикл и HSEND), поэтому у мест из нижней половины
   проверяются ОБА адреса.

   Часы прибора — сэмплы ЦАП (47996/с): длина дыры в сэмплах и есть то, что слышно. */
uint32_t gs_pc_hits[5] = {0,0,0,0,0};    /* 0 HSEND, 1 HGET, 2 HTAIL2, 3 QTFAULT, 4 QTPLAY */
static uint32_t gs_n_smpout = 0;         /* сэмплов ЦАП выдано, монотонно — часы прибора */
static uint32_t gs_hole_open = 0;        /* карта сейчас в QTFAULT: прерывания запрещены */
static uint32_t gs_hole_t0   = 0;
static uint32_t gs_hole_n    = 0;        /* сколько дыр всего */
static uint32_t gs_hole_max  = 0;        /* самая длинная дыра, сэмплов */
static uint32_t gs_hole_sum  = 0;        /* суммарно сэмплов в дырах */

void gs_hole_begin(void){                /* исполнен QTFAULT: кольцо квантов пусто */
    if(!gs_hole_open){ gs_hole_open = 1; gs_hole_t0 = gs_n_smpout; }
}
void gs_hole_end(void){                  /* исполнен QTPLAY: прерывания снова разрешены */
    if(gs_hole_open){
        uint32_t d = gs_n_smpout - gs_hole_t0;
        gs_hole_open = 0;
        gs_hole_n++;
        gs_hole_sum += d;
        if(d > gs_hole_max) gs_hole_max = d;
    }
}
unsigned gs_hits_get(unsigned i){ return (i < 5u) ? gs_pc_hits[i] : 0u; }
unsigned gs_holes_get(void)     { return gs_hole_n;   }
unsigned gs_holemax_get(void)   { return gs_hole_max; }
unsigned gs_holesum_get(void)   { return gs_hole_sum; }
unsigned gs_smpout_get(void)    { return gs_n_smpout; }
void gs_diag2_reset(void){
    for(unsigned i = 0; i < 5u; i++) gs_pc_hits[i] = 0;
    gs_hole_open = 0; gs_hole_n = 0; gs_hole_max = 0; gs_hole_sum = 0;
}

void gs_render(int16_t* l, int16_t* r)
{
    static uint32_t frac = 0;
    static int32_t  owe  = 0;
    uint32_t want = gs_smp_per_v;                   /* v0.15.336: тактов на сэмпл ЦАП при текущей частоте */
    gs_n_smpout++;                   /* v0.15.332: часы прибора — сэмплы ЦАП */
    frac += gs_smp_rem_v;                           /* 12 МГц: 12000000 - 250*47996 = 1000 */
    if(frac >= GS_DAC_HZ){ frac -= GS_DAC_HZ; want++; }
    if(gs_debt){                                    /* догон отставания - не больше четверти темпа */
        uint32_t add = want >> 2;
        if(add > gs_debt) add = gs_debt;
        gs_debt -= add; want += add;
    }
    /* v0.15.329 ОТКАТ BURST (v328). Burst min(starve,24k) на сэмпл ЦАП разгонял
       Z80 GS в десятки раз относительно стены: на стыке паттерна менялся ТЕМП и
       лезли писки (владелец 11.08). Mute (v320) хуже; полный догон starve = pitch-up.
       Возврат к модели v326: только x8 и только в игре (gs_n_int>0), starve∈(2k,2M),
       потолок 4000 тактов/сэмпл на 12 МГц (v0.15.336: он масштабируется с частотой карты,
       иначе разгон срезался бы ровно на догоне) — без ускорения «закрыть весь DI за 1.5 мс».
       Дальше: не wall-burst, а разбор DI/PC на spike и/или note-on (класс 2 MURMULATOR). */
    if(gs_lat_last_cyc && gs_n_int > 0u){
        uint32_t starve = gs_n_cyc - gs_lat_last_cyc;
        if(starve > 2048u && starve < 2000000u)
            want *= 8u;
    }
    {
        int32_t tcy = (int32_t)want + owe;
        if(tcy < 0)    tcy = 0;
        if(tcy > (int32_t)gs_tcy_cap_v) tcy = (int32_t)gs_tcy_cap_v;   /* v0.15.336: потолок тоже по частоте */
        if(tcy > 0){ uint32_t did = gs_run((uint32_t)tcy); owe = tcy - (int32_t)did; }
    }
    gs_mix(l, r);
}



/* ---------------- прогон ----------------
 * Возвращает фактически исполненное число тактов Z80. Прерывание раздаём по счётчику ТАКТОВ, режим
 * IM1 (у GS обработчик на 0x0038, вектор в ПЗУ - `JP 0x2030`).
 */
uint32_t gs_run(uint32_t cycles)
{
    uint32_t done = 0;
    if(!gs_rom_ok) return 0;
    gs_cmd_release();
    while(done < cycles){
        /* Таймер INT: пока просрочен — догоняем периодами (не по одному +320 за
           итерацию с left=1: иначе int_left уходит в минус, held++ каждый такт,
           карта ползёт на ~1 МГц и debt упирается в потолок — прибор v324). */
        while(gs_int_left <= 0){
            gs_int_reload();
            gs_int_pend = 1;
        }
        /* Уровень INT: сначала пробуем принять (как сэмпл ноги между инструкциями).
           Если DI — не снимаем pend, жжём held и идём в эмуляцию. */
        if(gs_int_pend){
            int ic = Z80Interrupt(&gs_cpu, 0xFFu, 0);
            if(ic > 0){
                gs_int_pend = 0;
                gs_n_int++;
                done += (uint32_t)ic;
                gs_n_cyc += (uint32_t)ic;
                gs_int_left -= ic;
                gs_cmd_release();
                continue;   /* сразу снова: возможно новый period уже вышел */
            }
            gs_n_intheld++;
        }
        {
            uint32_t left = (uint32_t)gs_int_left; /* здесь уже > 0 */
            if(left > cycles - done) left = cycles - done;
            if(left == 0u) break;
            unsigned lat0 = gs_n_latch;
            int did = Z80Emulate(&gs_cpu, (int)left, 0);
            if(did <= 0) break;
            gs_stall_cyc += (uint32_t)did;
            gs_cmd_release();
            done += (uint32_t)did;
            gs_n_cyc += (uint32_t)did;
            gs_int_left -= did;
            if(gs_n_latch != lat0){
                uint32_t pos = gs_modpos4();
                if(gs_lat_last_cyc){
                    uint32_t gap = gs_n_cyc - gs_lat_last_cyc;
                    if(gap > gs_lgap_win){
                        uint32_t held = gs_n_intheld - gs_lat_last_held;
                        uint32_t ints = gs_n_int - gs_lat_last_int;
                        if(held > 0xFFFFu) held = 0xFFFFu;
                        if(ints > 0xFFFFu) ints = 0xFFFFu;
                        gs_lgap_win = gap;
                        gs_lgap_pc = ((gs_lat_last_pc & 0xFFFFu) << 16) |
                                     ((uint32_t)gs_cpu.pc & 0xFFFFu);
                        gs_lgap_pos0 = gs_lat_last_pos;
                        gs_lgap_pos1 = pos;
                        gs_lgap_irq = (held << 16) | ints;
                    }
                }
                gs_lat_last_cyc = gs_n_cyc;
                gs_lat_last_pc = (uint32_t)gs_cpu.pc;
                gs_lat_last_pos = pos;
                gs_lat_last_held = gs_n_intheld;
                gs_lat_last_int = gs_n_int;
            }
        }
    }
    return done;
}


void gs_reset(void)
{
    Z80Reset(&gs_cpu);
    gs_page = 0;
    gs_int_left = (int32_t)GS_INT_PER; gs_int_frac = 0;   /* v298: счётчик прерываний вместо аккумулятора */
    gs_int_pend = 0;                                      /* v299: висящее прерывание прошлой жизни не наследуем */
    gs_debt = 0;                                          /* долг прошлой жизни карты не наследуем */
    gs_pages_rebuild();                                   /* таблица страниц под текущий объём + защёлка */
    gs_cmd = gs_dout = 0; gs_b0 = gs_outp = 0;
    gs_outq_w = gs_outq_r = 0; gs_outq_peak = gs_outq_taken = 0;   /* очередь ответов - тоже состояние */
    gs_out_t0 = 0; gs_out_spun = 0; gs_outq_spin = 0;
    gs_outq_wait_max = gs_outq_wait_sum = gs_outq_wait_n = 0;
    gs_inq_w = gs_inq_r = 0; gs_din_last = 0;   /* B0108: очередь тоже пуста */
    gs_ncmd_q = 0; gs_inq_r_seen = 0; gs_stall_cyc = 0;
    gs_cmd_pos = 0; gs_cmd_pos_ok = 0;
    gs_scan_i = 0; gs_scan_on = 0;              /* v299: незаконченный разбор очереди тоже не наследуем */
    gs_lat_last_cyc = gs_lat_last_pc = gs_lat_last_pos = 0;
    gs_lat_last_held = gs_lat_last_int = 0;
    gs_lgap_win = gs_lgap_pc = gs_lgap_pos0 = gs_lgap_pos1 = gs_lgap_irq = 0;
    for(int i = 0; i < 4; i++){ gs_ch[i] = 0; gs_vol[i] = 0; }
}

