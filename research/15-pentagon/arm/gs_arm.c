/* gs_arm.c - General Sound на ARM: процессор, память и микшер живут здесь, в фабрике остаётся только
 * ловушка портов #BB/#B3. Модель снята с живого апстрима MiSTer (`rtl/gs.v`), см. GENERAL_SOUND_PLAN.md.
 *
 * Что в железе GS: Z80, 32 КБ ПЗУ, ОЗУ страницами по 32 КБ, прерывание 37 480 Гц, четыре канала PCM
 * по 8 бит с шестибитной громкостью, выход L = ch1+ch2, R = ch3+ch4.
 *
 * 🥇 Главная неочевидность: у каналов НЕТ своих портов. Сэмпл защёлкивается САМ при чтении процессором
 * памяти в окне 0x6000..0x7FFF, а номер канала берётся из адреса (A[9:8]), и байт при этом
 * переворачивается в знаковый: {~d[7], d[6:0]}. Пропустить это = получить корректно работающий
 * процессор и полную тишину на выходе.
 */

#include <stdint.h>
#include "z80emu/z80emu.h"

#define GS_ROM_SZ    0x8000u                  /* 32 КБ ПЗУ (gs105b) */
/* 🥇 v268 ОБЪЁМ ОЗУ = 512 КБ, КАК У БАЗОВОЙ КАРТЫ, а не «сколько дадим». Причины две, обе замерены:
   1) Прошивка сообщает софту ЧИСЛО СТРАНИЦ (команда #23), и Mod Player сверяет его с ТРОЙКОЙ
      (базовая версия: 512 КБ = 128 КБ программе + 3 x 128 КБ сэмплам), иначе печатает
      «WARNING! GS, NOT PRESENT?!» и не играет.
   2) Плеер после заливки модуля гоняет по ВСЕЙ памяти сэмплов пересчёт байта (+0x80): ПЗУ 0x0EFB
      `LD A,(HL) : ADD A,0x80 : LD (HL),A : INC L : JP NZ` плюс `DJNZ` по страницам. Время цикла
      линейно объёму, а карта у нас идёт РОВНО 12 МГц - на 2 МБ это секунды ожидания вместо ~1 с,
      и выглядит как зависание. Оплачено ложным диагнозом «карта встала на команде 0x31».
   Больший объём (1/2/4 МБ) - это отдельная опция машины, а не дефолт: он ломает совместимость. */
/* 🥇 ОБЪЁМ ОЗУ КАРТЫ - ЭТО НАСТРОЙКА СОВМЕСТИМОСТИ, А НЕ ЩЕДРОСТЬ. Прошивка сообщает софту число
   страниц (команда #23), и оно зависит от того, сколько памяти карта намерила при старте. Таблица
   страниц RAMPG начинается со СТРАНИЦЫ 2 - первая занята переменными самой прошивки, - поэтому:
       128 КБ  -> NUMPG=3  базовая версия из руководства; Mod Player v2.5 сверяет её БУКВАЛЬНО
                  (`CP 3`) и иначе печатает «WARNING! GS, NOT PRESENT?!»
       512 КБ  -> NUMPG=15 дефолт: X-Player адресует сэмплы индексом 3, которого у 128 КБ нет вовсе
                  (проверено на плате: сэмплы уходят в никуда, в микшер идёт шум)
       1 МБ    -> NUMPG=31
       2 МБ    -> NUMPG=62  ПОТОЛОК, дальше не бывает - см. следующий абзац
   Массив держим на максимум, а границу двигаем в рантайме: смена объёма требует перезапуска карты,
   потому что память она мерит один раз при инициализации. */
/* 🥇 v0.15.299 «4 МБ» БЫЛО ЛОЖЬЮ В ИНТЕРФЕЙСЕ, И ЭТО ИЗМЕРЕНО, А НЕ ВЫВЕДЕНО.
   Номер страницы карта задаёт ОДНИМ портом #00, и он ШЕСТИБИТНЫЙ - и в живом апстриме
   (`cores/zx-mister/rtl/gs.v`: `reg [5:0] port_00`, адрес памяти `{page_addr, ...}` = 21 бит = 2 МБ),
   и в самой прошивке gs105b. Значит страниц по 32 КБ бывает 0..63, страница 0 - ПЗУ, и на ОЗУ
   остаётся 63 страницы = 2016 КБ. Проверено хостовым стендом (прошивка МЕРИТ память сама, ячейка
   NUMPG 0x4080):
       объявили 128 КБ -> NUMPG=3, 512 КБ -> 15, 1 МБ -> 31, 2 МБ -> 62, 4 МБ -> ТОЖЕ 62.
   То есть выбранные в меню 4 МБ до карты не доходили НИКОГДА: половина массива просто не
   адресуется, и пункт меню обещал то, чего у карты нет. Настоящие карты ведут себя так же - у
   NeoGS «4 МБ» это уже другая прошивка и другая схема страничности, а с gs105b потолок 2 МБ.
   Поэтому массив ужат до реального потолка (заодно вернулись 2 МБ DDR), а пункт меню назван 2M. */
#define GS_RAM_PAGES_MAX 64u                  /* 64 страницы по 32 КБ = 2 МБ - предел 6-битного порта #00 */
#define GS_RAM_SZ    (GS_RAM_PAGES_MAX * 0x8000u)
#define GS_INT_HZ    37480u                   /* частота прерывания GS */
#define GS_DAC_HZ    47996u                   /* частота ЦАП оболочки - ею же задан темп карты */
#define GS_Z80_HZ    12000000u                /* оригинальные 12 МГц (у MiSTer разогнано до 28) */

/* 🥇 v0.15.336 ЧАСТОТА КАРТЫ - ПАРАМЕТР, А НЕ КОНСТАНТА (и это НЕ вольность: MiSTer гоняет ту же
   прошивку на 28 МГц, UnrealSpeccy на 24, MAME NeoGS на 10 - к частоте gs105b не привязана).
   Зачем: на 12 МГц карта у нас впритык успевает обслужить и звук, и обмен с машиной, и на смене
   паттерна MOD-плеера кольцо квантов пустеет - карта уходит в QTFAULT (RET без EI), сэмплы не
   защёлкиваются, ЦАП держит уровень. Слышно как затык. Разгон снимает это с запасом; измерено
   свипом по периоду опроса мейлбокса (у нас насос идёт раз в 333 мкс):
       12 МГц - дыр нет только до 62 мкс опроса,  цена по ARM 1.00x
       14 МГц - до 400 мкс,                       1.08x
       18 МГц - до 1000 мкс,                      1.31x   <- дефолт опции машины
       24 МГц - до 650 мкс,                       1.55x
       36 МГц - те же числа, что у 24,            2.15x   (не окупается, в меню не выведена)
   ЧТО НЕ МЕНЯЕТСЯ: прерывание карты 37480 Гц и ЦАП 47996 Гц. Частота говорит ровно одно - СКОЛЬКО
   ТАКТОВ карта успевает между двумя прерываниями (12 МГц -> 320, 18 -> 480, 24 -> 640).
   СМЕНА НА ЛЕТУ БЕЗОПАСНА: ни одна из производных величин не является состоянием карты. Счётчик до
   прерывания (gs_int_left) досчитывает старым остатком и перезаряжается уже новым периодом, дробь
   Брезенхэма считается по неизменной GS_INT_HZ, долг времени (gs_debt) хранится в тактах и сам
   упирается в новый потолок при первом же пополнении. Прошивка карты частоту не мерит (память -
   мерит, поэтому объём ОЗУ требует перезапуска, а частота нет).
   🥇 МАСШТАБИРОВАТЬ ОБЯЗАНЫ ВСЕ ПЯТЬ ВЕЛИЧИН, включая потолок tcy: он ограничивает догон want*=8,
   и если оставить его на 4000, то на 18 МГц догон (375*8 = 3000, плюс долг) упрётся в потолок и
   молча срежется - разгон превратится в замедление ровно в тех местах, ради которых он сделан. */
static uint32_t gs_clk_hz    = GS_Z80_HZ;                          /* текущая частота карты, Гц */
static uint32_t gs_int_per_v = GS_Z80_HZ / GS_INT_HZ;              /* целых тактов на прерывание */
static uint32_t gs_int_rem_v = GS_Z80_HZ - (GS_Z80_HZ / GS_INT_HZ) * GS_INT_HZ;   /* его дробь */
static uint32_t gs_smp_per_v = GS_Z80_HZ / GS_DAC_HZ;              /* целых тактов на сэмпл ЦАП */
static uint32_t gs_smp_rem_v = GS_Z80_HZ - (GS_Z80_HZ / GS_DAC_HZ) * GS_DAC_HZ;   /* его дробь */
static uint32_t gs_tcy_cap_v = 4000u;                              /* потолок тактов на сэмпл */
void gs_set_clock_hz(uint32_t hz){
    if(hz < 1000000u)  hz = 1000000u;         /* ниже мегагерца прошивка карты не имеет смысла */
    if(hz > 64000000u) hz = 64000000u;        /* и выше 64 МГц ARM всё равно не потянет */
    gs_clk_hz    = hz;
    gs_int_per_v = hz / GS_INT_HZ;
    gs_int_rem_v = hz - gs_int_per_v * GS_INT_HZ;
    gs_smp_per_v = hz / GS_DAC_HZ;
    gs_smp_rem_v = hz - gs_smp_per_v * GS_DAC_HZ;
    gs_tcy_cap_v = (uint32_t)(((uint64_t)4000u * hz) / GS_Z80_HZ);
}
unsigned gs_get_clock_hz(void){ return gs_clk_hz; }
unsigned gs_int_per_get(void){ return gs_int_per_v; }   /* приборы стендов и меню */
unsigned gs_smp_per_get(void){ return gs_smp_per_v; }

/* ОЗУ и ПЗУ держим в КЭШИРУЕМОЙ DDR: интерпретатору это критично по скорости, а с фабрикой они не
 * делятся (в отличие от кадра и банков машины, которые живут в некэшируемом окне 0x0F700000+). */
static uint8_t  gs_rom[GS_ROM_SZ];
static uint8_t  gs_ram[GS_RAM_SZ];
static uint32_t gs_ram_sz = 16u * 0x8000u;    /* сколько ОЗУ карта ВИДИТ сейчас (по умолчанию 512 КБ) */
static void gs_pages_rebuild(void);           /* v298: таблица баз страниц, тело ниже (см. карту памяти) */
void gs_set_ram_kb(unsigned kb){              /* 128 / 512 / 1024 / 2048; ниже 128 КБ не пускаем */
    uint32_t sz = (uint32_t)kb * 1024u;
    if(sz < 4u*0x8000u)   sz = 4u*0x8000u;
    if(sz > GS_RAM_SZ)    sz = GS_RAM_SZ;
    gs_ram_sz = sz & ~0x7FFFu;                /* только целые страницы по 32 КБ */
    gs_pages_rebuild();                       /* объём меняется РЕДКО - здесь и пересчитываем */
}
unsigned gs_get_ram_kb(void){ return (unsigned)(gs_ram_sz >> 10); }
unsigned gs_pages_get(void){ return (unsigned)(gs_ram_sz >> 15); }   /* страниц по 32 КБ */
static int      gs_rom_ok = 0;                /* ПЗУ загружено с карты */
static int      gs_on     = 0;                /* GS включён в опциях машины */

static Z80_STATE gs_cpu;
static unsigned gs_n_latch, gs_n_vol, gs_n_int, gs_n_cmdrd;   /* счётчики для стенда */
static unsigned gs_n_prd[16], gs_n_pwr[16];                   /* гистограмма обращений по портам */

/* --- регистры обмена со Спектрумом (их теневые копии держит фабрика, ARM синхронизирует) --- */
static volatile uint8_t gs_cmd;               /* порт #BB, запись Спектрумом  -> внутренний порт 1 */
static volatile uint8_t gs_dout;              /* внутренний порт 3            -> чтение #B3 */
static volatile uint8_t gs_b0;                /* флаг команд: ставит машина, снимает САМА карта (порт #05) */
static volatile uint8_t gs_outp;              /* карта записала байт для Спектрума, он его ещё не забрал */
