static uint32_t gs_int_frac;     /* дробь Брезенхэма для периода прерывания */
static uint32_t gs_n_cyc;        /* v269: всего исполнено тактов (для проверки темпа прибором) */
static int      gs_int_pend;     /* v299: INT ВЫСТАВЛЕН и ещё не принят - у Z80 это уровень (см. gs_run) */
static unsigned gs_n_intheld;    /* v299: сколько шагов прерывание пришлось держать (карта была в DI) */
/* v317: окно диагностики слышимого перехода MOD-паттерна. Обычный underrun считает очередь ЦАП,
   но не видит, что GS продолжает выдавать старую защёлку. Поэтому измеряем виртуальные такты между
   реальными чтениями картой окна сэмплов 0x6000..0x7FFF и запоминаем PC/позицию MOD худшего разрыва. */
