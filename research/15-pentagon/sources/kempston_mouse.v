`timescale 1ns/1ps
//-------------------------------------------------------------------------------------------------
// kempston_mouse.v - мышь Kempston: три порта на чтение живут в фабрике, «рука» - на ARM.
//
// ЗАЧЕМ. Физической мыши у нас нет, а мышиного софта на Спектруме много: Z-Player 4.1 (браузер
// музыки прямо с образа), ART Studio, Sprite Magic, файловые менеджеры. Без мыши музыку живым
// плеером не запустить вообще. Поэтому интерфейс делаем НАСТОЯЩИЙ, а руку подставляет оболочка:
// сейчас это цифровая клавиатура, завтра - настоящая мышь PS/2, если она появится. Протокол между
// фабрикой и ARM от источника движения не зависит - меняется только тот, кто считает координаты.
//
// КАРТА ПОРТОВ сверена по ЖИВОМУ апстриму, а не по вендоренной копии (правило проекта, оплаченное
// дефектом геометрии wd1793: наша копия оказалась старше апстрима и увела диагностику):
//   MiSTer-devel/ZX-Spectrum_MiSTer, `rtl/mouse.v` (Sorgelig) + верхний уровень `ZX-Spectrum.sv`:
//       wire kemp_sel = addr[5:0] == 6'h1F;
//       mouse mouse( ..., .addr(addr[10:8]), ... );
//       casex(addr[10:8]): 3'b011 -> X, 3'b111 -> Y, 3'bX10 -> кнопки, иначе не отвечаем.
//   Отсюда канонические адреса:  #FBDF = X,  #FFDF = Y,  #FADF = кнопки.
//   Младший байт у всех трёх ОДИН И ТОТ ЖЕ (#DF), различают их СТАРШИЕ биты A10/A9/A8.
//
// ⚠ ОДНО СОЗНАТЕЛЬНОЕ ОТЛИЧИЕ ОТ АПСТРИМА. MiSTer декодирует только `a[5:0] == 6'h1F`, то есть у
// него мышь отвечает ещё и на #FA1F/#FB1F/#FF1F, а на время работы мыши он ОТКЛЮЧАЕТ джойстик
// целиком (`kemp_dout <= kemp_mode ? mouse_data : joyk`). Нам так нельзя: команда `IN A,(#1F)`
// кладёт на A15..A8 содержимое регистра A, поэтому у обычного чтения джойстика старшие биты
// адреса СЛУЧАЙНЫ - мышь начала бы перехватывать джойстик у игр, которые о ней не знают. Поэтому
// декодируем полный младший байт `#DF`: весь известный мышиный софт бьёт ровно в #FADF/#FBDF/#FFDF,
// а порт джойстика #1F остаётся неприкосновенным, и обе железки живут одновременно, как на
// настоящей машине с двумя картами в слотах.
//
// ПОЧЕМУ ЗДЕСЬ НЕТ ВЫХОДА `sup` (в отличие от nemo_ide.v). У NEMO командные порты ЧЁТНЫЕ, то есть
// попадают в окно ULA #FE, и без подавления внутреннего декодера каждый байт сектора мигал бы
// бордюром. У мыши младший байт #DF: A0 = 1, значит это не #FE вовсе; портов Beta Disk он тоже не
// задевает (у контроллера #1F/#3F/#5F/#7F при A7 = 0 и отдельно #FF - см. beta_disk.v:85,315), и
// на запись мы не реагируем ни на одном адресе. Давить нечего.
//
// В МУЛЬТИПЛЕКСОРЕ ШИНЫ блок обязан стоять РАНЬШЕ kempston-джойстика (тот ловит одно условие
// a[5] = 0 и проглотил бы #xxDF целиком). Порядок относительно дисковода безразличен - пересечений
// адресов нет, - но ставим после него, чтобы приоритет контроллера ни при каких правках не уехал.
//-------------------------------------------------------------------------------------------------
module kempston_mouse
(
    input  wire        clk,        // такт машины (spclk)
    input  wire        reset_n,
    input  wire        en,         // мышь включена опцией машины: выключена = портов не существует,
                                   //   чтения проваливаются в прежний декодер (джойстик/плавающая шина)
    input  wire        iorq_n,
    input  wire        m1_n,       // цикл подтверждения прерывания в трап попадать не должен
    input  wire        rd_n,
    input  wire [15:0] a,          // B0132: ВЕСЬ адрес. Было [10:0] - старшего байта модуль не
                                   //   видел вовсе, поэтому строгого разбора трёх портов не мог
                                   //   сделать в принципе, а отвечал на любой #xxDF с битом A9.

    output wire [7:0]  dout,       // что отдаём процессору
    output wire        oe,         // мы отвечаем на это чтение

    // --- мост к ARM. Слово управления приходит из домена оболочки и защёлкивается ВЛАДЕЛЬЦЕМ
    //     (см. main.v) тем же тогглом, что у NEMO-IDE и General Sound; сюда уже приходят готовые
    //     поля из защёлки плюс однотактовый строб «слово обновилось», взведённый НА ТАКТ ПОЗЖЕ
    //     данных. Это наше правило CDC, оплаченное битой памятью Пентагона: нагрузку держать,
    //     синхронизировать только флаг, флаг публиковать не раньше данных. ---
    input  wire [7:0]  arm_x,
    input  wire [7:0]  arm_y,
    input  wire [2:0]  arm_btn,    // {средняя, правая, левая}, активный ВЫСОКИЙ; инвертируем здесь
    input  wire        arm_stb
);
    // ---- дешифрация ----
    wire io  = ~iorq_n & m1_n & ~rd_n;                    // чтение порта, не подтверждение прерывания
    /* B0132: было `(a[7:0] == 8'hDF) & a[9]` - отклик на ЛЮБОЙ порт с младшим байтом #DF и битом
       A9, то есть на #01DF, #7FDF, #BFDF и десятки чужих. У Kempston-мыши адреса ТРИ: #FADF кнопки,
       #FBDF X, #FFDF Y. Покой кнопок - активный НОЛЬ, поэтому чужое чтение в этом окне software
       читает как «кнопка нажата»; на этом уже строились ложные диагнозы. */
    wire sel = io & en & ((a == 16'hFADF) | (a == 16'hFBDF) | (a == 16'hFFDF));
    /* ⚠ Это СТРОЖЕ настоящего железа: у Kempston-мыши разбор частичный, и клоны отвечают на
       псевдонимы. Выбран строгий вариант сознательно - весь известный софт ходит по трём
       каноническим адресам, а частичный разбор у нас уже давал ложные срабатывания. Если
       найдётся программа, которой нужен псевдоним, это станет опцией машины, а не откатом. */

    /* Счётчики держим СВОИ, а не отдаём напрямую слово ARM, ровно по одной причине: значение
       обязано быть осмысленным ДО первой записи оболочки. Драйверы ищут мышь по тому, что X и Y
       не совпадают (в апстриме это записано прямым текстом: «dx != dy for better mouse detection»),
       а нулевое слово после сброса дало бы X = Y = 0 и «мыши нет» у софта, который успел
       опросить порты раньше, чем ARM дошёл до своей службы. */
    reg [7:0] mx, my;
    reg [2:0] btn;
    always @(posedge clk) begin
        if (!reset_n) begin
            mx <= 8'd128; my <= 8'd0; btn <= 3'b000;
        end else if (arm_stb) begin
            mx <= arm_x; my <= arm_y; btn <= arm_btn;
        end
    end

    // ---- что отдаём ----
    reg [7:0] q;
    always @* begin
        if      (!a[8])  q = {5'b11111, ~btn[2], ~btn[1], ~btn[0]};  // #FADF: кнопки, АКТИВНЫЙ НОЛЬ
        else if ( a[10]) q = my;                                     // #FFDF: Y (растёт «от себя»)
        else             q = mx;                                     // #FBDF: X (растёт вправо)
    end
    assign dout = q;
    assign oe   = sel;
endmodule
