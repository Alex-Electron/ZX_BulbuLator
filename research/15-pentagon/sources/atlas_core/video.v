reg[7:0] attrInput;
always @(posedge clock) if(ce) if(attrInputLoad) attrInput <= d;

/* 🥇 B0200 ПОРТ #FF ПЕНТАГОНА, РЕЖИМ ATTRIBUTE (опция машины, MACHINE_CFG бит29). Эталон - Sizif-512
   cpld/rtl/video.sv:283-289 (живой апстрим, сверено 24.09): у Пентагона чтение порта с младшим байтом #FF
   во время выборки бумаги отдаёт attr_next - ПОСЛЕДНИЙ выбранный атрибут, а вне бумаги шину никто не
   ведёт (#FF). Здесь то же: регистр держит байт с последнего строба attrInputLoad и сбрасывается в #FF
   вне окна выборки (dataEnable). Отличие от Sizif в первые такты строки до первой выборки атрибута: у
   Sizif там лежит цвет бордюра {00,border,border}, у нас #FF - софт, синхронизирующийся по атрибуту,
   ждёт конкретное значение атрибута, и ни то ни другое его не обманет. Фаза выдачи с точностью до такта
   с живым клоном НЕ сверена (прибора нет). Отдельный регистр, а не attrInput: attrInput держит байт
   прошлой строки на всём гашении, и порт отдавал бы атрибут там, где у Sizif #FF. */
reg[7:0] attrBus = 8'hFF;
always @(posedge clock) if(ce) begin
    if(!dataEnable) attrBus <= 8'hFF;
    else if(attrInputLoad) attrBus <= d;
end
assign qattr = attrBus;

/* Отвод для зеркала экрана BulbuLator: на стробе (a, d) - адрес и байт одной выборки ULA,
   родитель складывает их в 6912-байтное зеркало в фабрике = «экран как он лёг».
   🥇 B0178 СТРОБ ЗЕРКАЛА ОБЯЗАН СИДЕТЬ НА ФАЗЕ ВЫБОРКИ, А НЕ НА ФАЗЕ ВЫВОДА.
   ⚠ Оплачено в B0177. Регистр `a` грузится по `addrLoad` (фаза ВЫБОРКИ, от `h_fet`), а строб
   зеркала остался на `dataInputLoad`/`attrInputLoad` (прежняя фаза вывода) - и пара «адрес+байт»
   разъехалась на 4 счёта. Кадр на экране при этом ОСТАЛСЯ ЭТАЛОННЫМ (сверен бит-в-бит), сломался
   только прибор: в зеркале обнулилась каждая вторая колонка знаков, и текст с экрана машины
   читался как «T i i g 4 k» вместо «Timing 48k». То есть сторож `scrdiff.py` по кадру такую
   поломку НЕ ВИДИТ - зеркало и кадр это два разных пути. Отсюда правило: после правки видеотракта
   проверять И кадр (scrdiff.py), И читаемость ТЕКСТА через зеркало (bocr.py). */
assign scr_we = dataInputLoad | attrInputLoad;

reg[7:0] dataOutput;
wire dataOutputLoad = h_addr[2:0] == 4 && videoEnable;
always @(posedge clock) if(ce) if(dataOutputLoad) dataOutput <= dataInput; else dataOutput <= { dataOutput[6:0], 1'b0 };

reg[7:0] attrOutput;
wire attrOutputLoad = h_addr[2:0] == 4;
// 🥇 B0121 БОРДЮР У ПЕНТАГОНА ОБНОВЛЯЕТСЯ КАЖДЫЙ ПИКСЕЛЬ, А НЕ РАЗ В ВОСЕМЬ.
// Atlas - ядро СИНКЛЕРОВСКОЕ, и у него цвет бордюра защёлкивается вместе с атрибутом, раз в 8
// пикселей (4 такта Z80). Для Синклера это верно - там бордюр действительно квантуется цепочкой
// выборки атрибутов. У Пентагона ULA так НЕ делает, и на нашей сетке любой бордюрный эффект
// рассыпается на блоки по 8 пикселей: волна, которая должна ползти на 1-2 такта в строке, ложится
// на грубую сетку и выглядит лесенкой из квадратов (жалоба владельца 12.08 по Across the Edge).
// Два независимых эталона говорят одно и то же:
//   MiSTer   rtl/ula.sv:184-185  - отдельная ветка с комментарием «1T update for border in Pentagon mode»
//   Sizif-512 cpld/rtl/video.sv:186 - border_update = screen_update || (machine == MACHINE_PENT && ck7)
// Цвет кладём в ОБА поля (бумага И чернила), как оба эталона: иначе на переходе бумага->бордюр
// dataOutput ещё до восьми пикселей досдвигается нулями, и в этом окне светится протухшая краска
// из attrInput[2:0].
// Одно присваивание с ЯВНЫМ разрешением, а не два подряд с расчётом на «последнее побеждает»:
// так синтезатору виден обычный триггер с разрешением и мультиплексором. Два присваивания подряд
// дали разводку с недотрассированной цепью питания (VCC -> SLICE.CLK, DRC RTSTAT-9) в двух прогонах
// B0121 подряд, а у B0120 такого не было ни в одном из трёх - то есть корень был в форме записи.
// 🥇 B0122 ГЕЙТ ТОНКОГО БОРДЮРА — ПО КЛЕТКЕ, А НЕ ПО ФЛАГУ videoEnable.
// В B0121 тонкая ветка гейтилась `~videoEnable`, а этот флаг обновляется только по hUla[3],
// то есть падает на 3-4 пикселя РАНЬШЕ, чем сдвигатель домалывает последний байт бумаги
// (загрузка на h_addr[2:0]==4, вывод — следующие восемь тактов). Результат: последние 3-4
// пиксельных столбца БУМАГИ в КАЖДОЙ строке красились цветом бордюра. Владелец увидел это как
// «непонятный сдвиг бордюра вправо, и INT H его не лечит» — и правильно, INT H двигает программу,
// а тут ехал наш собственный край картинки.
// Оба эталона гейтят по КООРДИНАТЕ отображаемой бумаги: MiSTer rtl/ula.sv:185
// (`hc_next<12 | hc_next>267 | vc>=192`), Sizif cpld/rtl/video.sv:184,264-267 (окно screen_show).
// Здесь то же самое, но без магических чисел и без зависимости от живой настройки paper_h:
// признак «эта знакоместная клетка — БУМАГА» защёлкивается ТЕМ ЖЕ стробом attrOutputLoad, что и
// сама клетка, поэтому окно совпадает с выводом сдвигателя такт-в-такт по построению.
// Вариант без лишнего триггера: окно берём КООРДИНАТАМИ, буквально как MiSTer
// (`hc_next<12 | hc_next>267 | vc>=192`). Бумага ПОКАЗЫВАЕТСЯ на h_addr 12..267 (загрузка
// сдвигателя на h_addr[2:0]==4, вывод — следующие восемь тактов), по вертикали окно v_addr < 192.
// Разности h_addr/v_addr модульные, поэтому «до начала бумаги» само попадает в ветку бордюра.
// Регистр paperShown из первой редакции убран: на 91 % LUT он столкнул схему с обрыва —
// ExtraTimingOpt перестал РАЗМЕЩАТЬ, а Explore разместил, но развести не удалось (перекрытия
// колебались 25..49 тысяч вместо схождения к нулю).
// B0169 ОКНО ПОКАЗА БУМАГИ - ОДНО НА ВСЕ МАШИНЫ, И БОРДЮРНАЯ ВЕТКА ГЕЙТИТСЯ ИМ.
// Прежде тонкая ветка Пентагона считалась по КООРДИНАТЕ (это верно и осталось), а бордюрная защёлка
// на 48K/128K - по флагу `videoEnable`, и вот в чём разница: флаг обновляется только в окне
// h_addr[3]=1, поэтому падает на h_addr 264, тогда как сдвигатель домалывает последний байт бумаги
// до h_addr 268. До B0168 это было безвредно (`attrOutput` просто держал последний атрибут), но
// добавленный там принудительный взвод `border_start` срабатывал по этому же флагу - и красил
// ПОСЛЕДНИЕ 4 ПИКСЕЛЯ БУМАГИ цветом бордюра в каждой строке. Владелец увидел это как <<правый край
// бумаги не дорисовывается, будто бордюр на него наложился>>; стенд дал число: 252 px вместо 256.
// Эталон гейтит именно координатой: MiSTer rtl/ula.sv:185 `hc_next<12 | hc_next>267 | vc>=192`,
// Sizif cpld/rtl/video.sv:184,264-267 (окно screen_show). Здесь то же окно, одно на обе ветки.
wire paperShow  = (v_addr < 9'd192) & (h_addr >= 9'd12) & (h_addr <= 9'd267);
wire borderFine = pentagon & ~paperShow;
// 🥇 НА СОВПАДЕНИИ СТРОБОВ ПОБЕЖДАЕТ БОРДЮР, КАК У ЭТАЛОНА (было наоборот).
// Прежний текст объяснял приоритет через регистр paperShown, которого в этой редакции уже НЕТ
// (выброшен, сказано выше) - объяснение через несуществующий сигнал.
// Эталон: MiSTer пишет атрибут (rtl/ula.sv:178) и следом ПЕРЕТИРАЕТ его бордюрной веткой
// (rtl/ula.sv:185) - при совпадении побеждает БОРДЮР. У нас одно присваивание (форма выбрана
// из-за DRC RTSTAT-9, см. выше), поэтому порядок задаётся ЯВНО термом ~borderFine.
// СЕГОДНЯ ЭТО NO-OP, И ЭТО ДОКАЗАНО, А НЕ ОБЕЩАНО: комбинация attrOutputLoad & videoEnable &
// borderFine НЕДОСТИЖИМА ни при каком paper_h. После правки videoEnableLoad (:162) разрешение на
// такте L = dataEnable с последнего строба h_rel[3] перед L: для строба h_addr = 16n+4 это
// de(16n-2), для h_addr = 16n+12 - de(16n+10). В окне borderFine эти выборки дают ноль всегда:
// h_addr = 4 -> de(446) (конец строки, h_rel >= 256); h_addr >= 268 -> de(>= 266); v_addr >= 192 ->
// de = 0 всей строкой. Стенд подтверждает числом: 0 расхождений с прежней формой на полном кадре
// 143360 px во ВСЕХ конфигурациях (paper_h 0..4 / 5..14 / 15 / 127 / 440 / 447, Пентагон и
// Синклер), при том что сам регистр attrOutput в этих же прогонах меняется десятки тысяч тактов за
// кадр - то есть стимул до места доходит, а наружу не выходит.
// ЗАЧЕМ ТОГДА ПРАВИТЬ: недостижимость - свойство ТАЙМИНГА videoEnable, а не структуры записи.
// Сдвинется точка выборки ещё раз - и мы разойдёмся с эталоном МОЛЧА, цветом первой клетки.
// 🥇 БОРДЮР КЛАДЁТСЯ В ОБА ПОЛЯ И В ГРУБОЙ ВЕТКЕ ТОЖЕ (догнали эталон).
// Было `{ 2'b00, border, attrInput[2:0] }`: при videoEnable = 0 в чернилах оставалась ПРОТУХШАЯ
// краска последнего атрибута, и до восьми пикселей на переходе бумага->бордюр она могла светиться
// (сдвигатель в этом окне ещё домалывает последний байт, единицы в нём выбирают именно чернила).
// Оба эталона пишут цвет бордюра в ОБА поля одним присваиванием: MiSTer rtl/ula.sv:178,
// Sizif-512 cpld/rtl/video.sv:267. Тонкая ветка (Пентагон) так делала с самого B0121 - теперь обе.
// Форма записи прежняя и по той же причине: ОДНО присваивание с явным разрешением, а не два
// подряд с расчётом на «последнее побеждает» (см. DRC RTSTAT-9 выше).
// Проверено стендом: сам регистр attrOutput при этом РАЗНЫЙ (11776 тактов за кадр у Пентагона,
// 92664 у Синклера), а видимый выход - НЕТ: 0 расхождений на полном кадре по всему набору выходов
// модуля, и в Пентагоне (тонкая ветка перетирает следующим тиком), и в 48/128 (в этих тактах
// сдвигатель уже вымыт нулями, dataOutput[7] = 0, то есть чернила не выбираются). То есть правка
// каноническая и заведомо безопасная, а не косметика «на глазок».
// 🥇 B0164: ФАЗА 8-ПИКСЕЛЬНОЙ ГРУППЫ ЗАЩЁЛКИ БОРДЮРА - ОТДЕЛЬНАЯ ЖИВАЯ РУЧКА.
// Измерено на плате (кадр cmd 14, SHOCK ч.2, 03.09): первые ПЯТЬ пикселей каждой строки несут цвет
// ПРЕДЫДУЩЕЙ строки - строка 100 x0..4 = 5 и дальше 4, строка 101 x0..4 = 4. То есть защёлка бордюра
// срабатывает на 5 px ПОЗЖЕ начала видимой области (hUla 421 при видимой с 416), и наружу выходит
// зубчатый край: 172 строки из 302 имеют переход в левом бордюре, 84 строки имеют левый бордюр НЕ
// равный правому. Эталон (ZEsarUX, лента SHOCK_PART2_ONLY_g.TAP, владелец подтвердил «идёт идеально»)
// даёт 0 переходов в бордюрах и 0..3 строки с лев != прав: у настоящей машины защёлка попадает в
// ГАШЕНИЕ.
// 🥇 Лечится это НЕ задержкой и НЕ фазой прерывания, а фазой границы группы - у Потапова тот же
// симптом и тот же вывод (`ep4spectrum/source/video.v:590-600`): «a real 48K cannot do that: its ULA
// takes the border once per 8-pixel group, so a border edge can only ever land on a group boundary…
// it is why no amount of delay or interrupt trimming would take it». У него это BORD_PHASE (16 счётов
// на группу, живая ручка на клавиатуре), значение 5 для 48K/128K, снято btime на ЖИВОЙ машине.
// Здесь то же самое в наших единицах: h_addr идёт с пиксельной частотой, группа = 8 счётов.
// ⚠ УМОЛЧАНИЕ БИТ-В-БИТ ПРЕЖНЕЕ: при bph_en = 0 фаза = 4, то есть border_upd = ~videoEnable &
// attrOutputLoad - подмножество прежнего разрешения записи, и поведение не меняется НИ НА ТАКТ.
// Ручка сидит в ula_tune2[11:8] и НЕ трогает tune_en: включать лабораторию целиком нельзя, она
// заодно переводит io_cont_tap/int_sel/fb_tap на лабораторные значения и увела бы CONTP с эталона.
// 🥇 B0166: РУЧКА ФАЗЫ ТЕПЕРЬ ЗАМЕНЯЕТ ТОЧКУ ЗАЩЁЛКИ, А НЕ ДОБАВЛЯЕТ ЕЩЁ ОДНУ.
// В B0164 `border_upd` стоял в разрешении записи РЯДОМ с `attrOutputLoad`, и старая точка на фазе 4
// продолжала срабатывать всегда. Поэтому свип восьми фаз на живой плате 03.09 давал одну и ту же
// гистограмму переходов (x = 5,13,21,29,37) - не потому, что фаза не лечит, а потому что ручка
// ничего не меняла. Вывод «фазу вычеркнуть» был сделан по неработающему прибору и СНЯТ.
// Теперь разрешение разложено на два НЕПЕРЕСЕКАЮЩИХСЯ терма:
//   attr_upd   - клетка БУМАГИ, строб выборки атрибута (фаза 4, машинная, её не трогаем);
//   border_upd - клетка БОРДЮРА, строб с настраиваемой фазой.
// ⚠ Умолчание бит-в-бит прежнее: при bph_en = 0 фаза = 4, и объединение термов тождественно
// прежнему `attrOutputLoad | borderFine`, потому что при videoEnable = 1 писался атрибут, а при
// videoEnable = 0 - бордюр, ровно на том же стробе.
// 🥇 B0167: РУЧКА ПЕРЕЕХАЛА НА ЖИВОЙ ПРОВОД. `ula_tune2` В ВЕРХНЕМ МОДУЛЕ НЕ ПОДКЛЮЧЁН ВООБЩЕ,
// а `ula_tune` подменён словом `pint_active` (регистр PENT_INT, CDC + защёлка по vsync,
// `bulbulator_zx_ddr_top.v:1483-1493,1558`). Провод `ctl_ula_tune` там объявлен (:173) и НИКУДА не
// присоединён - выход `ctl_ula_tune_o` управляющей плоскости в топе не разведён (:715 берёт только
// `ctl_pent_int_o`). Поэтому запись в 0x43C001C0 и 0x43C001C4 не доходит до ядра НИ ОДНИМ БИТОМ, и
// свипы фазы 03.09 и 08.09 не могли ничего изменить - оба раза прибор был мёртв.
// ⚠ Отсюда же следствие для чтения прежних записей: всё, что «настраивалось лабораторией» на плате,
// настраивалось СЛОВОМ PENT_INT, а не ULA_TUNE.
// Свободен бит 3 (у lab-слова заняты [2:0] фаза, [6:4] io_cont_tap, [8:7] int_sel, [14:9] сдвиг ULA,
// [23:15] сдвиг INT, [25:24] задержка бордюра, [29:26] задержка бумаги, [30] заморозка, [31] включение).
// Умолчание PENT_INT = 0x00EF0146: бит3 = 0, значит фаза остаётся 4 и поведение бит-в-бит прежнее.
