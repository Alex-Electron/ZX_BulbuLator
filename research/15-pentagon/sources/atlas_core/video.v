   Тот же механизм уже был у B0154 и записан выше: заряд за кадр меняется, вход в HALT уезжает,
   выход из HALT квантован по 4 такта - и код прыгает на 8 px.
   ПОЭТОМУ: `cn` (ввод-вывод и бордюр) остаётся ровно тем, что был; отдельное `cn_mem` уходит на
   свою фазу и питает ТОЛЬКО сравнение для памяти (main.v, `vduC_mem`). Выборка, адрес и плавающая
   шина тоже остались на прежней фазе - значит картинка не может измениться в принципе, а тесты
   35/36/37 держатся, потому что расстояние «шина минус окно ввода-вывода» не тронуто. */
assign cn     = dataEnable && (hUla[3] || hUla[2]);
/* 🥇 B0182 ФАЗА УЗОРА ШТРАФА - ОТДЕЛЬНАЯ РУЧКА, РАЗВЯЗАННАЯ С ОКНОМ БУМАГИ.
   ⚠ НАЙДЕНО СВЕРКОЙ С КАНОНОМ ДОСТУП-ЗА-ДОСТУПОМ (`cmondiff.py`), а не рассуждением.
   Тест 3 занятый: 2930 штрафов, 2929 совпали с каноном WoS идеально, врёт РОВНО ОДИН - первый
   занятый доступ кадра: канон +4, у нас +6. Разложение по позициям восьмитактового цикла:
       позиция:  0  1  2  3  4  5  6  7
       канон:    6  5  4  3  2  1  0  0    свободные слоты на позициях 6,7 (hUla 12..15)
       у нас:    0  0  6  5  4  3  2  1    свободные слоты на позициях 0,1 (hUla 0..3)
   Тот же узор, повёрнутый на 2 позиции. Дальше по строке процессор залочивается контеншеном и
   садится в точку, где обе фазы дают одно и то же - оттого врёт только первый, НЕЗАЛОЧЕННЫЙ доступ.
   Он же уводит t0 на 2 такта и даёт шов в ШОК ч.2 (запись бордюра выезжает из гашения).
   ⚠ ПОЧЕМУ НЕ `memc_off`: та ручка сдвигает и `hUla_mem`, и `de_mem` (край окна бумаги) разом -
   получается каскад на граничных доступах, одни тесты чинятся, другие ломаются (проверено полным
   прогоном: 64/74 против 59/71, но НАБОРЫ провалов разные). Здесь двигается ТОЛЬКО фаза узора,
   окно бумаги остаётся на своём месте.
   `patrot` = сколько счётов прибавить к hUla ПЕРЕД проверкой бит. Свободный слот уезжает на
   (16 - patrot) mod 16: при 4 он встаёт на hUla 12..15, то есть на канонические позиции 6,7.
   Ручка `ula_tune2[27]` = задана, `[26:24]` = значение; при нуле поведение прежнее (B0181).
   ❌ ГИПОТЕЗА ОТВЕРГНУТА ЭТОЙ ЖЕ РУЧКОЙ (10.09). Свип поворота на тесте 3 занятом:
       поворот 0..3 -> R=49 loop=405 sp=23315   (loop КАНОНИЧЕСКИЙ)
       поворот 4    -> R=117 loop=407 sp=23300  (предсказанный «канон» - ЛОМАЕТ loop)
       поворот 5,6  -> loop=407;  поворот 7 -> loop=409
   Если бы узор был повёрнут на 2 позиции, поворот 4 дал бы эталон. Вместо этого он рушит СУММАРНЫЙ
   заряд за кадр, который при нынешней фазе КАНОНИЧЕСКИЙ (loop=405 = эталон). Значит расхождение -
   не фаза узора и не величина штрафа, а одноразовый переходный эффект на первом, ещё не залоченном
   доступе кадра. Разложение `[0,0,6,5,4,3,2,1]` против канона `[6,5,4,3,2,1,0,0]` арифметически
   верно, но НЕ описывает наше железо: половинная тактовая сетка `cpuck` меняет отображение
   «момент запроса -> позиция в цикле». Ручка оставлена ПРИБОРОМ: она навсегда отвечает на вопрос
   «а не повёрнут ли узор» за один прогон.
   ⚠ Мина при свипе: бит включения - 27, то есть `TUNE2=0C000000` (не `04000000`, это бит 26).
   Два первых свипа ушли впустую именно на этом - ручка не включалась, числа не менялись. */
wire [3:0] patrot   = ula_tune2[27] ? {1'b0, ula_tune2[26:24]} : 4'd0;
wire [4:0] hUlaP_s  = {1'b0, hUla_mem[3:0]} + {1'b0, patrot};
wire [3:0] hUla_pat = hUlaP_s[3:0];
assign cn_mem = dataEnableM && (hUla_pat[3] || hUla_pat[2]);
/* B0182: тот же поворот узора и для окна ВЫБОРКИ КОМАНДЫ. ⚠ Без этого ручка мертва на тестах:
   тело большинства тестов - сплошные выборки (NOP, LD r,r, INC/DEC r), и они идут через `cn_m1`,
   а не через `cn_mem` (main.v: `vduC_acc = (~m1_d) ? vduC_m1 : vduC_mem`). Первый свип это и показал:
   все восемь положений дали одни и те же числа. */
wire [4:0] hUla1P_s  = {1'b0, hUla_m1[3:0]} + {1'b0, patrot};
wire [3:0] hUla_m1p  = hUla1P_s[3:0];
assign cn_m1  = dataEnableM1 && (hUla_m1p[3] || hUla_m1p[2]);

// B0172: ГАШЕНИЕ ЗАДЕРЖИВАЕТСЯ ВМЕСТЕ С КАРТИНКОЙ. Иначе чёрные поля по краям остаются на месте,
// а бордюр и бумага уезжают на out_delay - и края разъезжаются ровно на эту величину (в B0171 это
// видно было прибором как расхождения на столбцах 47, 303 и 304).
wire blank_raw = hBlank | vBlank;
reg [14:0] pipe_bl = 15'd0;
always @(posedge clock) if(ce) pipe_bl <= {pipe_bl[13:0], blank_raw};
wire hsync_raw = pentagon ? (hUla >= 332 && hUla < 364) : (hUla >= 340 && hUla < 372);  // B0165: 32-clk centered in 316..411 blank (front porch 24, sync 32, back porch 40);
wire vsync_raw = pentagon ? (vUla >= 300 && vUla < 304) : (vUla >= 248 && vUla < 252);  // move vsync later for small top border after vsync -> logo higher in frame like reference;
assign blank = (out_delay == 4'd0) ? blank_raw : pipe_bl[out_delay - 4'd1];
// B0173: СИНХРОСИГНАЛЫ ЕДУТ ТЕМ ЖЕ КОНВЕЙЕРОМ. В B0172 задержаны были только цвет и гашение, а
// hsync/vsync остались на месте - захват кадра равняется по ним, и вся картинка уезжала на
// out_delay пикселей (прибор: 232 расходящиеся строки на любом ненулевом значении). Задержка
// всего видеосигнала целиком по построению невидима: меняется только СРОК защёлки.
reg [14:0] pipe_hs = 15'd0, pipe_vs = 15'd0;
always @(posedge clock) if(ce) begin
    pipe_hs <= {pipe_hs[13:0], hsync_raw};
    pipe_vs <= {pipe_vs[13:0], vsync_raw};
end
assign hsync = (out_delay == 4'd0) ? hsync_raw : pipe_hs[out_delay - 4'd1];
assign vsync = (out_delay == 4'd0) ? vsync_raw : pipe_vs[out_delay - 4'd1];

// Output: direct attrOutput for crisp 1-pixel fonts and full border across frame
// B0171: ВОЗВРАЩЕНА РАЗДЕЛЬНАЯ ЗАДЕРЖКА ПУТЕЙ БОРДЮРА И БУМАГИ (была в B0157, удалена в B0158
// чужой сессией без приёмки). Это НЕ косметика: без неё у нас всего одна ручка на две разные
// величины, и они жёстко связаны.
//   СРОК   - на каком такте закрывается защёлка бордюра (кого она успевает поймать);
//   ПОЛОЖЕНИЕ - где защёлкнутый цвет появляется на экране.
// Фаза `b_phase` двигает ОБА сразу, поэтому 08.09 свип всех восьми фаз на живой плате дал ровно
// размен: значения, убиравшие чёрточку в левом верхнем квадрате esh2, возвращали сдвиг полос,
// и наоборот. Разорвать размен можно только парой «фаза раньше + пиксельные ступени назад».
// Ровно это и делает Потапов: `BORD_PHASE`/`BORD_DELAY` = 5/2 на 48K, снято btime на живой машине
// («the deadline moves, the position does not», ep4spectrum 04e8c25), плюс отдельная задержка
// бумаги `pap_tap` = 9, про которую у него сказано прямо: восемь пикселей из девяти существуют
// затем, что «ничем другим бордюр на группу равномерно не сдвинуть».
// УМОЛЧАНИЯ ЗДЕСЬ НУЛЕВЫЕ И ЭТО НАМЕРЕННО: b_delay = 0, pap_delay = 0 дают картинку БИТ-В-БИТ
// как у B0170. Правка добавляет степень свободы, а не меняет поведение; значения подбираются
// живым свипом через PENT_INT и только потом становятся умолчанием.
// Разрядность: b_delay 0..3 px (ula_tune[25:24]), pap_delay 0..15 px (ula_tune[29:26]).
// B0172: ОДНА РУЧКА ВМЕСТО ПАРЫ - составить её неправильно нельзя по построению.
// `bord_early` = на сколько пикселей раньше закрывается защёлка бордюра. Компенсация считается
// сама: фаза уезжает на столько же назад, а весь вывод (бордюр, бумага И гашение) задерживается
// на ту же величину. Итог - картинка не меняется ни на пиксель, а СРОК уезжает: запись, которая
// приходила впритык, в эту группу больше не успевает.
// Зачем: чёрная чёрточка 8x1 px в левом верхнем квадрате esh2 (строка 54, x 57..64) - это
// последняя группа защёлки перед бумагой, в неё успевает чёрный `OUT (C),0` первой строки экрана.
// У живого 48K её нет, у FUSE и ZEsarUX есть (разбор Потапова, ep4spectrum 4f902f7/137628d).
// Почему одной фазой не лечится: фаза двигает И срок, И положение, поэтому свип всех восьми
// значений 08.09 дал чистый размен - что убирало чёрточку, ломало полосы (232 расходящиеся строки).

// Защёлка бордюра - тем же стробом, что и раньше (:border_upd), поэтому при нулевых задержках
// выход совпадает с прежним.
reg [2:0] border_lat = 3'b000;
reg [2:0] border_d1  = 3'b000, border_d2 = 3'b000, border_d3 = 3'b000;
always @(posedge clock) if(ce) begin
    /* 🥇 B0192 ВОЗВРАТ ТОНКОГО БОРДЮРА ПЕНТАГОНА. Жалоба владельца 16.09: на финале демки Rage
       (RageEnd) секторы на бордюре идут СТУПЕНЬКАМИ по 8 px вместо плавных полос. Измерено кадром:
       граница сектора в верхнем бордюре держится ровно 8 строк и прыгает ровно на 8 px, а в бумаге
       та же граница идёт по 1 px на строку. Причина: когда в B0172 завели конвейер задержки бордюра
       (bord_early, border_d1..d3), вывод переключили с attrOutput на новый border_lat, а он берёт
       цвет ТОЛЬКО по квантованному стробу border_upd. Попиксельная ветка borderFine осталась жива,
       но обновляет attrOutput, который на бордюр больше не влияет - то есть починку B0121/B0122
       («тонкий бордюр Пентагона», принято на плате 12.08) потеряли молча.
       Терм добавлен в условие защёлки. На 48K/128K это ТОЖДЕСТВЕННЫЙ НОЛЬ по построению:
       borderFine = pentagon & ~paperShow (:332), значит условие у них не меняется ни на такт. */
    if(border_upd | borderFine) border_lat <= border;
    border_d1 <= border_lat;
    border_d2 <= border_d1;
    border_d3 <= border_d2;
end
wire [2:0] border_live = (bord_early == 2'd3) ? border_d3 :
                         (bord_early == 2'd2) ? border_d2 :
                         (bord_early == 2'd1) ? border_d1 : border_lat;

// Пиксельный конвейер бумаги (0..15 ступеней).
// B0172: селектор берёт окно ПОКАЗА, а не загрузки. paperShow (:227) - это окно ЗАГРУЗКИ
// сдвигателя, h_addr 12..267; на экран бумага выходит на пиксель позже, 13..268. В B0171 селектор
// стоял на окне загрузки, и ПОСЛЕДНИЙ столбец бумаги в каждой строке отдавался бордюру - прибор
// поймал это сразу: 21 расходящаяся строка, и все расхождения на одном столбце 303.
reg paperShow_d = 1'b0;
always @(posedge clock) if(ce) paperShow_d <= paperShow;
wire raw_act = paperShow_d;
wire raw_r   = dataSelect ? attrOutput[1] : attrOutput[4];
wire raw_g   = dataSelect ? attrOutput[2] : attrOutput[5];
wire raw_b   = dataSelect ? attrOutput[0] : attrOutput[3];
wire raw_i   = attrOutput[6];
reg [14:0] pipe_act = 15'd0, pipe_r = 15'd0, pipe_g = 15'd0, pipe_b = 15'd0, pipe_i = 15'd0;
always @(posedge clock) if(ce) begin
    pipe_act <= {pipe_act[13:0], raw_act};
    pipe_r   <= {pipe_r[13:0],   raw_r};
    pipe_g   <= {pipe_g[13:0],   raw_g};
    pipe_b   <= {pipe_b[13:0],   raw_b};
    pipe_i   <= {pipe_i[13:0],   raw_i};
end
wire is_paper = (out_delay == 4'd0) ? raw_act : pipe_act[out_delay - 4'd1];
wire dot_r    = (out_delay == 4'd0) ? raw_r   : pipe_r[out_delay - 4'd1];
wire dot_g    = (out_delay == 4'd0) ? raw_g   : pipe_g[out_delay - 4'd1];
wire dot_b    = (out_delay == 4'd0) ? raw_b   : pipe_b[out_delay - 4'd1];
wire dot_i    = (out_delay == 4'd0) ? raw_i   : pipe_i[out_delay - 4'd1];

// ⚠ При нулевых задержках это тождественно прежнему выводу: вне бумаги `attrOutput` несёт цвет
// бордюра в ОБОИХ полях (см. блок attrOutput выше), а `border_lat` защёлкнут тем же стробом,
// поэтому обе ветки дают одно и то же значение.
assign r = is_paper ? dot_r : border_live[1];
assign g = is_paper ? dot_g : border_live[2];
assign b = is_paper ? dot_b : border_live[0];
assign i = is_paper ? dot_i : 1'b0;
assign dbg_h = hCount;
assign dbg_v = vCount;

