   ⚠ ОПЛАЧЕНО СЛОМАННОЙ КАРТИНКОЙ НА ПЛАТЕ. Первая версия правки переводила стробы загрузки
   сдвигателя прямо на сдвинутую фазу — и на экране появились УДВОЕННЫЕ символы: строб вывода
   (`dataOutputLoad`, фаза 4) брал из входного регистра байт уже СЛЕДУЮЩЕЙ колонки. Проверено
   снимком кадра: вместо «(c) 1982 Sinclair Research Ltd» читалось «9922SSnnllii eeeerrhhLLdd».
