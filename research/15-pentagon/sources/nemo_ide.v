`timescale 1ns/1ps
//-------------------------------------------------------------------------------------------------
// nemo_ide.v - интерфейс NEMO-IDE: регистры ATA в фабрике, сам «диск» на ARM.
//
// Почему NEMO, а не ATM/SMUC/PROFI: интерфейс ПАРАЛЛЕЛЬНЫЙ и регистровый, никакого SPI и эмуляции
// SD, а подача секторов ложится на тот же приём, которым уже живёт дисковод - буфер плюс мост к ARM.
// И это единственная из русских схем, которая работает при ВЫКЛЮЧЕННОМ теневом ПЗУ Beta Disk.
//
// Карта портов снята по схеме `nedopc.com/NEMOIDE/nemohddsch.png` и сверена по шести источникам
// (zx-evo, Karabas-Pro, MAME, Xpeccy, UnrealSpeccy, драйверы zxfdisk/zx-midiplayer):
//
//   #10 CS0 reg0  Data, младшие D0-D7      |  #90 CS0 reg4  LBA1
//   #11 защёлка   старший байт D8-D15      |  #B0 CS0 reg5  LBA2
//   #30 CS0 reg1  Error / Features         |  #D0 CS0 reg6  Drive/Head, LBA3
//   #50 CS0 reg2  Sector Count             |  #F0 CS0 reg7  Status / Command
//   #70 CS0 reg3  LBA0                     |  #C8 CS1 reg6  Alt Status / Device Control
//
// Дешифрация ТОЛЬКО по младшему байту (A8..A15 не участвуют):
//   ebl = (a[1]==0) && (a[2]==0) && !m1 && !dos_rom_paged;
//   reg = a[7:5];   cs0_n = a[3];   cs1_n = a[4];   hi_latch = a[0];
//
// 🥇 ДВЕ МИНЫ, обе из разбора и обе учтены здесь:
//  1. Все командные порты NEMO ЧЁТНЫЕ, то есть это порты ULA `#FE`. На Пентагоне `#FE`
//     декодируется только по A0=0, поэтому `IN A,(#F0)` без мер вернёт КЛАВИАТУРУ, а `OUT (#10)`
//     будет мигать бордюром на каждом байте сектора. В железе это решено сигналом /IORQCE: плата
//     давит дешифратор портов материнки на всё окно EBL. Отсюда выход `sup` - его владелец обязан
//     завести в подавление внутреннего декодера машины.
//  2. Kempston-джойстик. Если он декодируется по «A5==0», то перехватит #10/#30/#50/#70, поэтому в
//     машине блок NEMO обязан стоять СТРОГО РАНЬШЕ kempston (так же сделано в UnrealSpeccy).
//
// M1 в гейте обязателен: без него цикл подтверждения прерывания попадёт в трап.
//
// Данные 16-битные, и порядок ЖЁСТКИЙ (две внешние защёлки на A0, отдельные на чтение и запись):
//   чтение  - сначала #10 (даёт младший и попутно защёлкивает старший), потом #11;
//   запись  - сначала #11 (в защёлку), потом #10 (выставляет сразу 16 бит и даёт строб).
//
// B0117: DRQ ведёт ФАБРИКА (подробный разбор - у объявления drq_hw). Коротко: ARM подкладывает блок
// и говорит «данные готовы», а снимает DRQ домен машины - в тот же такт, когда указатель дошёл до
// конца буфера. Слово состояния от ARM теперь несёт и служебную метку в бите 1 - «этот блок в
// передаче последний»; машине этот бит не показывается.
//-------------------------------------------------------------------------------------------------
module nemo_ide
(
    input  wire        clk,          // такт машины (spclk)
    input  wire        reset_n,
    input  wire        en,           // интерфейс включён опцией машины
    input  wire        dos_paged,    // вставлена страница ПЗУ TR-DOS: тогда NEMO молчит
    input  wire        iorq_n,
    input  wire        m1_n,
    input  wire        rd_n,
    input  wire        wr_n,
    input  wire [7:0]  a,            // младший байт адреса
    input  wire [7:0]  din,          // шина данных процессора (запись)
    output wire [7:0]  dout,         // что отдаём процессору
    output wire        oe,           // мы отвечаем на это чтение
    output wire        sup,          // подавить внутренний декодер портов машины (аналог /IORQCE)

    // --- мост к ARM (домен машины; наружу уходит через синхронизаторы, как у дисковода) ---
    output wire [7:0]  ide_cmd,      // последняя команда, записанная в #F0
    output wire        ide_cmd_stb,  // строб команды (тоггл)
    output wire [7:0]  ide_feat, ide_cnt, ide_lba0, ide_lba1, ide_lba2, ide_head,
    input  wire [7:0]  ide_status,   // что ARM держит в регистре состояния
    input  wire [7:0]  ide_error,
    // буфер сектора: пишет ARM, читает машина
    input  wire [8:0]  buf_waddr,
    input  wire [7:0]  buf_wdata,
    input  wire        buf_we,
    input  wire        arm_stb,      // B0115: строб «слово от ARM защёлкнуто», один такт (см. arm_reg_we)
    output wire [8:0]  buf_raddr,
    output wire        dev_slave,    // B0113: бит DEV регистра #D0 (E0 = master, F0 = slave)    // куда сейчас смотрит машина (диагностика)
    input  wire        buf_arm_owns, // 1 = ARM наполняет буфер, машине отдаём BSY
    /* B0117: наружу отдаём СВОЙ взгляд на передачу - им прошивка узнаёт про вычерпанный блок ФАКТОМ,
       а не гаданием по указателю. Указатель для этого плох принципиально: ноль после вычерпывания
       и ноль сразу после записи команды - одно и то же значение, и прошивке приходилось отличать
       их по истории наблюдений (см. g_ide_rd_seen). */
    output wire        drq_live,     // в буфере лежит блок, машина его забирает
    output wire        gap_wait      // блок вычерпан, передача не окончена: ждём блок от ARM
);
    // ---- дешифрация ----
    wire io      = ~iorq_n & m1_n;                 // обращение к порту, не подтверждение прерывания
    wire ebl     = io & en & ~dos_paged & (a[1] == 1'b0) & (a[2] == 1'b0);
    wire cs0     = ebl & ~a[3];
    wire cs1     = ebl & ~a[4] & a[3];
    wire hi      = a[0];                           // A0 = обращение к защёлке старшего байта
    wire [2:0] rg = a[7:5];

    assign sup = ebl;                              // окно EBL давит декодер портов машины

    // ---- регистры ATA (те, что ведёт машина) ----
    reg [7:0] r_feat, r_cnt, r_lba0, r_lba1, r_lba2, r_head, r_cmd;
    reg [7:0] wr_hi;                               // защёлка старшего байта на запись
    reg       cmd_tog;
    reg [8:0] rptr;                                // адрес чтения буфера сектора
    reg [7:0] rd_hi;                               // защёлкнутый старший байт на чтение

    assign ide_feat = r_feat; assign ide_cnt = r_cnt;
    assign ide_lba0 = r_lba0; assign ide_lba1 = r_lba1; assign ide_lba2 = r_lba2;
    assign ide_head = r_head; assign ide_cmd = r_cmd; assign ide_cmd_stb = cmd_tog;
    assign buf_raddr = rptr;
    assign dev_slave = r_head[4];    /* на slave надо отвечать «устройства нет», иначе софт полезет
                                        работать со вторым диском, которого у нас нет */

    /* ---- B0115: ЗАПИСЬ РЕГИСТРОВ ATA СО СТОРОНЫ ARM ----
       Драйверы NEMO (проверено на Proteus File Manager) после команды 0x90 EXECUTE DEVICE
       DIAGNOSTIC читают СИГНАТУРУ: #50 = 01, #70 = 01, #90 = 00, #B0 = 00. Регистры вёл только
       хост, поэтому там лежали нули, и драйвер по ним решал, что диска нет. Та же дорога нужна
       для 0x91 INIT DEVICE PARAMETERS - иначе заданную хостом геометрию не прочитать.

       Свободных БИТ в слове управления не осталось, зато есть свободное СОСТОЯНИЕ: при снятом
       стробе буфера (`buf_we` = 0) поля адреса и данных не значат ничего - прошивка пишет туда
       нули. Его и занимаем, отделив маркером в 6 бит, чтобы случайное слово не уехало в регистр:
           buf_we = 0, buf_waddr[8:3] = 101010, buf_waddr[2:0] = номер регистра, buf_wdata = значение.
       Нумерация регистров - та же, что у дешифратора машины ниже (2 cnt, 3 lba0, 4 lba1, 5 lba2,
       6 head), поэтому обе стороны читаются одним взглядом.
       ⚠ Кто соберётся положить в это слово новое поле, обязан держать `buf_waddr[8:3]` нулями при
       снятом стробе, иначе получит паразитную запись регистра ATA.

       🥇 ОДНОГО БИТА РАЗЛИЧИЯ МАЛО - в это слово уже уперлись измерением. Маркер 101010 - это
       адрес 336, то есть при заливке сектора байты 336..343 дают РОВНО ТУ ЖЕ комбинацию
       `buf_waddr[8:3]`, и от записи регистра их отличает единственный бит `buf_we`. А слово
       приходит из другого домена одной защёлкой без упругой очереди, и смаз битов двух соседних
       слов у нас НЕ гипотеза: он измерен на железе (подпись сектора 55 AA приехала как 55 .. .. AA
       - байт лёг на адрес из чужого слова). Смазанный `buf_we` превратил бы восемь байт настоящего
       сектора в восемь записей в файл регистров ATA - то есть в порчу LBA прямо посреди отдачи
       данных. Добавляем в условие `buf_arm_owns`: заливка буфера идёт при owns = 0 (см. вызовы
       `nemo_push(0x58, 0, buf, 512)` в прошивке), запись регистра - при owns = 1
       (`nemo_reg_write(..., 1, ...)`). Теперь состояния расходятся ДВУМЯ битами разом, и чтобы
       перепутать их, смаз обязан переврать оба сразу и в противоположные стороны. */
    wire arm_reg_we = arm_stb & ~buf_we & buf_arm_owns & (buf_waddr[8:3] == 6'b101010);

    /* ---- B0115: АППАРАТНЫЙ BSY НА ОКНО «КОМАНДА ЗАПИСАНА, ОТВЕТА ЕЩЁ НЕТ» ----
       По ATA устройство обязано поднять BSY В ТОМ ЖЕ цикле, в котором хост записал команду в #F0.
       У нас BSY выставлял ARM, а он узнаёт о команде только на следующем обходе главного цикла -
       то есть между `OUT (#F0),#90` и ответом прошивки статус ПРОШЛОЙ команды виден как готовый
       (BSY снят). Драйвер, честно дождавшийся снятия BSY, читает сигнатуру ДО того, как ARM её
       выставил, и получает старые значения регистров - ровно тот отказ, который мы и лечим.
       Поэтому строб команды поднимает признак занятости прямо здесь, в домене машины.

       Снимаем его ЛЮБЫМ словом от ARM (`arm_stb`), а не «правильным ответом»: первое, что делает
       прошивка, поймав команду, - это `nemo_push(0x80, 1, ...)`, то есть BSY продолжает держаться
       уже через `buf_arm_owns`. Разрыва не возникает и по таймингу: `nemo_ctl_l` защёлкивается на
       фронт РАНЬШЕ, чем взводится `arm_stb` (см. main.v), значит новое состояние уже стоит на
       входах, когда мы гасим `cmd_busy`.

       Сторожевой счётчик - обязателен, и вот почему выбран именно он. Любое условие снятия,
       завязанное ТОЛЬКО на ARM, даёт ARM право заморозить машину навсегда: не запущена прошивка,
       выключена опция IDE, ушёл в исключение, перезагружено ядро - и Z80 крутится в ожидании
       снятия BSY до выключения питания, причём вылечить это изнутри машины нечем. С таймером
       худший случай деградирует до СТАРОГО поведения (драйвер увидит прошлый статус), а не до
       зависания. Порог 2^23 тактов ≈ 148 мс на 56.7 МГц: нормальный оборот главного цикла ARM -
       доли миллисекунды, так что на живой прошивке таймер не срабатывает никогда, а мёртвая
       задерживает машину на десятую долю секунды и отпускает.
       Сброс #C8 бит2 тоже снимает занятость: хост явно сбрасывает интерфейс, и оставлять его
       после этого «занятым» значило бы отобрать у машины последний способ выпутаться. */
    reg        cmd_busy;
    reg [22:0] busy_wd;

    /* ================================================================================================
       🥇 B0117: DRQ СНИМАЕТ ФАБРИКА ПО ФАКТУ ВЫЧЕРПЫВАНИЯ БУФЕРА, А НЕ ARM СЛОВОМ СОСТОЯНИЯ.

       ИЗМЕРЕННЫЙ ДЕФЕКТ (свой код на Z80, два прогона по 64 сектора): при многосекторном чтении
       машина забирала 512 байт и видела DRQ ВСЁ ЕЩЁ ПОДНЯТЫМ - потому что снять его мог только ARM,
       а он узнаёт об окончании блока лишь на следующем обходе службы (опрос rptr). В эту щель
       машина успевала прочитать НАЧАЛО СТАРОГО буфера: указатель 9-битный, за 512 байт он приходит
       обратно в ноль и честно отдаёт байты уже отданного блока. Прогон 1: 105 битых байт (сектора
       1, 17, 22, 36), прогон 2: 87 байт (сектор 23) - позиции ПЛАВАЮТ, то есть это гонка, а не
       систематический сдвиг. Обход «сначала дождаться BSY, только потом DRQ» давал 0 расхождений,
       но так читает только НАШ код: штатный драйвер по ATA ждёт именно DRQ, и обязан на это право
       иметь. Это же и самый правдоподобный ответ на «Z-Player 4.1 замолкает»: он спотыкается на
       разборе раздела, то есть на данных, которые ему приехали порчеными.

       ЛЕЧИМ ТАМ, ГДЕ ФАКТ: конец блока знает домен машины, а не ARM. Указатель дошёл до конца -
       фабрика в ТОТ ЖЕ такт снимает DRQ. Щели не остаётся вообще, потому что снятие и последнее
       чтение происходят одним фронтом.

       ТРИ СОСТОЯНИЯ, и разводить их обязательно:
         drq_hw  - в буфере лежит блок, машине разрешено его забирать;
         gap_busy- блок вычерпан, передача НЕ окончена, следующего блока ещё нет: машина обязана
                   видеть ЗАНЯТОСТЬ, иначе она прочитает старый буфер по второму разу (ровно тот
                   отказ, который мы и лечим);
         ничего  - передача окончена: ни DRQ, ни BSY.

       КАК ФАБРИКА УЗНАЁТ, ЧТО БЛОК ПОСЛЕДНИЙ. Взято НЕ из счётчика секторов #50, хотя он у нас
       есть, и вот почему: `r_cnt` пишет ХОСТ, а по ATA его положено декрементировать по мере
       передачи - то есть фабрике пришлось бы вести свой теневой счётчик и повторять разбор
       команды (0 = 256 секторов, 8-битные образы, отказ чтения посреди пачки). А главное - у
       IDENTIFY регистр #50 к делу не относится вовсе: там лежит что угодно, оставшееся от прошлой
       команды, и фабрика решила бы, что блоков много, и повесила бы gap_busy на ровном месте.
       Поэтому последний блок ОТМЕЧАЕТ ARM - он один знает, сколько блоков осталось, и знает это
       ТОЧНО. Признак едет В ТОМ ЖЕ слове, которым поднимается DRQ (иначе между «DRQ» и «последний»
       появилась бы своя гонка), в бите 1 слова состояния: бит IDX объявлен устаревшим ещё в ATA-4,
       ни один настоящий диск его не выставляет, и наша прошивка никогда его не использовала.
       Машине этот бит НЕ ПОКАЗЫВАЕМ (см. st_mach ниже) - канал служебный.

       СТАРАЯ ПРОШИВКА НА НОВОМ ЯДРЕ РАБОТАЕТ: она метку не ставит, значит каждый блок считается
       непоследним и после вычерпывания встаёт gap_busy - а его снимает ЛЮБОЕ следующее «чистое»
       слово состояния от ARM, которое служба и так шлёт, закончив передачу. Разница только в
       лишнем окне занятости в доли миллисекунды, и это законное поведение по ATA, а не отказ.
       ================================================================================================ */
    reg drq_hw;      // DRQ, которым распоряжается ФАБРИКА
    reg gap_busy;    // буфер вычерпан, следующий блок ещё не подложен
    reg last_blk;    // блок, лежащий в буфере, - последний в этой передаче

    /* «Чистое» слово состояния от ARM: без строба буфера и не запись регистра ATA. Именно оно
       завершает `nemo_push` (строка `NEMO_CTL = base`), то есть приходит, когда все 512 байт уже
       в буфере. Поднимать DRQ раньше нельзя: слова заливки несут статус 0x58 с уже поднятым DRQ,
       и до B0117 машина имела право забрать полупустой буфер прямо посреди наполнения. Эта дыра
       закрывается тем же движением, что и основная. */
    wire arm_plain = arm_stb & ~buf_we & ~arm_reg_we;

    /* Конец блока ловится ниже, в секции чтения машиной: `rd_done` / `blk_done` объявлены там,
       рядом с сигналами шины, из которых они и собираются. */

    /* Занятость машине: BSY от ARM, владение буфером, окно команды и НОВОЕ окно между блоками. */
    wire       hw_busy = cmd_busy | gap_busy;
    wire       bsy = ide_status[7] | buf_arm_owns | hw_busy;
    /* Слово состояния, каким его видит машина. DRQ - наш, бит1 (служебная метка «последний блок»)
       вырезан, остальное от ARM. При поднятом BSY гасим и DRQ: по ATA при BSY остальные биты
       недействительны, и драйвер, увидевший «занят, но данные готовы», вправе полезть в буфер. */
    wire [7:0] st_mach = {bsy, ide_status[6:4], drq_hw & ~bsy, ide_status[2], 1'b0, ide_status[0]};

    assign drq_live = drq_hw;
    assign gap_wait = gap_busy;

    // ---- буфер сектора: 512 байт, порт A пишет ARM, порт B читает машина ----
    (* ram_style = "block" *) reg [7:0] sbuf [0:511];
    reg [7:0] sbuf_q;
    always @(posedge clk) begin
        if (buf_we) sbuf[buf_waddr] <= buf_wdata;
        sbuf_q <= sbuf[rptr];
    end

    // ---- чтение машиной ----
    reg  rd_d;
    reg  rd_was_data;                              // заканчивающееся обращение было к порту данных #10
    wire rd_acc = (cs0 | cs1) & ~rd_n;
    wire wr_acc = (cs0 | cs1) & ~wr_n;
    reg  wr_d;
    wire wr_edge = wr_acc & ~wr_d;                 // фронт записи (тот же, по которому пишутся регистры)
    wire wr_cmd  = wr_edge & cs0 & ~hi & (rg == 3'd7);   // OUT (#F0) - запись КОМАНДЫ
    wire wr_srst = wr_edge & cs1 & din[2];              // #C8 бит2 SRST - сброс интерфейса хостом

    /* B0117: конец обращения к порту данных - тот самый спад, по которому двигается указатель
       (правило проекта: указатель двигать по КОНЦУ обращения, см. B0114 ниже). Блок вычерпан, когда
       этот спад пришёлся на ПОСЛЕДНЕЕ слово буфера: rptr идёт шагами по два и 510 - последний. */
    wire rd_done  = ~rd_acc & rd_d & rd_was_data;
    wire blk_done = rd_done & drq_hw & (rptr == 9'd510);

    reg [7:0] q;
    always @* begin
        if (cs1)                q = st_mach;                     // Alt Status
        else if (hi)            q = rd_hi;                       // #11: старший байт защёлки
        else case (rg)
            3'd0: q = sbuf_q;                                    // #10: данные
            3'd1: q = ide_error;
            3'd2: q = r_cnt;
            3'd3: q = r_lba0;
            3'd4: q = r_lba1;
            3'd5: q = r_lba2;
            3'd6: q = r_head;
            default: q = st_mach;                                // #F0 Status
        endcase
    end
    assign dout = q;
    assign oe   = rd_acc;

    always @(posedge clk) begin
        rd_d <= rd_acc;
        if (rd_acc & ~rd_d) rd_was_data <= cs0 & ~hi & (rg == 3'd0);
        wr_d <= wr_acc;
        if (!reset_n) begin
            r_feat <= 0; r_cnt <= 0; r_lba0 <= 0; r_lba1 <= 0; r_lba2 <= 0;
            r_head <= 8'hE0; r_cmd <= 0; rptr <= 0; wr_hi <= 0; rd_hi <= 0; cmd_tog <= 0;
            rd_was_data <= 1'b0;
            cmd_busy <= 1'b0; busy_wd <= 23'd0;
            drq_hw <= 1'b0; gap_busy <= 1'b0; last_blk <= 1'b0;
        end else begin
            // --- запись машиной ---
            if (wr_edge) begin
                if (cs1) begin
                    /* #C8 Device Control: сброс интерфейса битом 2 */
                    if (din[2]) rptr <= 0;
                end else if (hi) begin
                    wr_hi <= din;                                 // #11: старший байт в защёлку
                end else case (rg)
                    3'd0: rptr <= rptr + 9'd2;                    // #10: 16 бит ушли (данные пишет ARM)
                    3'd1: r_feat <= din;
                    3'd2: r_cnt  <= din;
                    3'd3: r_lba0 <= din;
                    3'd4: r_lba1 <= din;
                    3'd5: r_lba2 <= din;
                    3'd6: r_head <= din;
                    default: begin r_cmd <= din; cmd_tog <= ~cmd_tog; rptr <= 0; end   // #F0 Command
                endcase
            end else if (arm_reg_we) begin
                /* Приоритет у МАШИНЫ, и это не вкусовщина: свою потерянную запись ARM видит
                   обратным чтением и повторяет, а потерянную запись хоста (`OUT (#50)` перед
                   следующей командой) обнаружить нечем - она молча превратится в чтение чужого
                   сектора. Совпасть эти два пути почти не могут: `buf_arm_owns` теперь входит в
                   условие `arm_reg_we`, то есть запись регистра ARM физически возможна только при
                   поднятом BSY, а при BSY хост по ATA файл регистров трогать не имеет права. */
                case (buf_waddr[2:0])
                    3'd2: r_cnt  <= buf_wdata;
                    3'd3: r_lba0 <= buf_wdata;
                    3'd4: r_lba1 <= buf_wdata;
                    3'd5: r_lba2 <= buf_wdata;
                    3'd6: r_head <= buf_wdata;   // он же двигает dev_slave (r_head[4])
                    default: ;                   // rg=1 Features - только хост→устройство, не даём
                endcase
            end
            /* --- чтение машиной: #10 отдаёт младший и защёлкивает старший, #11 отдаёт защёлку ---
               🥇 B0114. УКАЗАТЕЛЬ ДВИГАТЬ ПО КОНЦУ ОБРАЩЕНИЯ, А НЕ ПО НАЧАЛУ. Z80 забирает байт в
               последнем такте цикла ввода, а сигнал чтения держится весь цикл. Сдвиг по фронту
               успевал сменить `sbuf_q` на СЛЕДУЮЩЕЕ слово, и процессор получал младший байт чужого
               слова (старший при этом верен - он берётся из защёлки). Измерено своим кодом на Z80:
               подпись сектора 55 AA приезжала как 55 .. .. AA. Та же болезнь, что была у сдвига
               регистра джойпада NES: уровень живёт весь такт чтения, значит работать по спаду. */
            /* B0117: двигаем указатель ТОЛЬКО при поднятом DRQ. Без DRQ буфер пуст, и настоящий
               диск в этом состоянии указателем не шевелит. Гейт нужен не для красоты: пока его не
               было, драйвер, читающий данные после конца блока, УВОДИЛ указатель дальше по кругу -
               и служба ARM, следящая за оборотом, видела «указатель снова растёт» и считала, что
               машина взялась за новый блок, которого никто не подкладывал. Байт 511 при этом не
               теряется: `rd_hi` защёлкивается на ТОМ ЖЕ фронте, когда DRQ ещё поднят, и чтение
               #11 после конца блока законно отдаёт защёлку. */
            if (rd_done & drq_hw) begin
                rd_hi <= sbuf[rptr + 9'd1];
                rptr  <= rptr + 9'd2;
            end
            /* --- B0115: занятость на время исполнения команды (обоснование - у объявления bsy) ---
               Приоритет у записи команды: если хост записал #F0 ровно в тот такт, когда пришло
               слово от ARM, это слово относится к ПРОШЛОЙ команде, и гасить им новую занятость
               нельзя. */
            if (wr_cmd) begin
                cmd_busy <= 1'b1;
                busy_wd  <= 23'd0;
            end else if (arm_stb | wr_srst) begin
                cmd_busy <= 1'b0;
                busy_wd  <= 23'd0;                /* B0117: любой признак жизни ARM отодвигает сторож.
                                                     Он и задуман как «ARM молчит слишком долго», а
                                                     не «занятость длится слишком долго»: наполнение
                                                     буфера - это 512 слов подряд, и мерить его тем
                                                     же порогом, что и смерть прошивки, неправильно. */
            end else if (hw_busy) begin
                busy_wd <= busy_wd + 23'd1;
                if (&busy_wd) begin               // сторож: мёртвый ARM не должен морозить машину
                    cmd_busy <= 1'b0;
                    gap_busy <= 1'b0;             /* B0117: и окно между блоками сторожим тем же
                                                     счётчиком - оно точно так же держится ТОЛЬКО
                                                     обещанием ARM подложить следующий блок, а
                                                     обещание может не сдержать ни мёртвая прошивка,
                                                     ни выключенная опция IDE, ни смена ядра. */
                end
            end
            /* B0117: сторож ВЗВОДИТСЯ ЗАНОВО на каждое окно занятости. Раньше счётчик обнуляла
               только запись команды - это было верно, пока занятость поднимал ровно один источник.
               Теперь их два, и окно между блоками начиналось бы с ТОГО ЗНАЧЕНИЯ, на котором его
               бросило прошлое окно: досчитавший почти до предела счётчик снял бы законную занятость
               через несколько тактов, то есть ровно посреди подкладывания блока. */
            if (!hw_busy) busy_wd <= 23'd0;

            /* ---- B0117: жизненный цикл DRQ (обоснование - у объявления drq_hw) ---- */
            if (wr_cmd | wr_srst) begin
                /* Новая команда или сброс интерфейса хостом отменяют всё, что лежало в буфере:
                   его содержимое относится к ПРОШЛОМУ запросу. Указатель обнуляется здесь же
                   ветками дешифратора выше. */
                drq_hw <= 1'b0; gap_busy <= 1'b0; last_blk <= 1'b0;
            end else begin
                if (blk_done) begin
                    /* Блок вычерпан - данных в буфере больше нет, и это ФАКТ домена машины. */
                    drq_hw <= 1'b0;
                    /* На промежуточном блоке машина обязана увидеть занятость, пока ARM не
                       подложит следующий; на последнем не остаётся ни DRQ, ни BSY - передача
                       окончена, и вешать занятость было бы враньём. */
                    if (!last_blk) gap_busy <= 1'b1;
                end
                if (arm_plain) begin
                    /* Слово от ARM - свежее знание, поэтому оно имеет приоритет над `blk_done`
                       в один и тот же такт: если ARM успел подложить блок ровно в тот такт, когда
                       машина дочитала прошлый, в буфере уже лежат НОВЫЕ данные. Совпасть они
                       почти не могут (ARM подкладывает блок, только УВИДЕВ оборот указателя), но
                       порядок должен быть определён, а не «как получится». */
                    drq_hw   <= ide_status[3];
                    last_blk <= ide_status[1];    // служебная метка «этот блок последний»
                    gap_busy <= 1'b0;
                end
            end
        end
    end
endmodule
