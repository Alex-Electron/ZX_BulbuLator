// gs_flow.v - управление потоком на портах General Sound: ТАКТЫ ОЖИДАНИЯ + сторож + прибор.
// Contact: lavrinovich.alex@gmail.com
//-------------------------------------------------------------------------------------------------
// 🥇 B0119: ДВА СМЫСЛА НА ОДНОМ БИТЕ - ЭТО ОБМАН ГОСТЯ, А НЕ ОБРАТНОЕ ДАВЛЕНИЕ.
// В B0118 признак бита7 порта #BB собирался как ИЛИ из «очередь почти полна» и «у карты есть байт».
// У настоящей карты этот бит значит РОВНО ОДНО: у карты есть байт для тебя - это флаг одного
// двунаправленного регистра данных. Плеер ждёт единицу в нём циклом IN A,(#BB) / RLCA / JR NC,
// то есть на нашем «занято» он делал вывод «пришёл ОТВЕТ», читал протухший байт из #B3 и продолжал
// лить дальше. Мы сами провоцировали то переполнение, от которого защищались: приёмка B0118 дала
// 7 эпизодов потери данных на 88 паузах оболочки длиннее 1 мс.
//
// ЛЕЧИМ ТЕМ, ЧЕМ ЛЕЧИТ ЖЕЛЕЗО. Медленная периферия на настоящей шине не врёт флагами - она
// ДЕРЖИТ ПРОЦЕССОР сигналом ожидания. У нас для этого уже есть штатный механизм: разрешения такта
// pc3M5/nc3M5 в main.v (обе фазы - T80 защёлкивает данные на nc3M5; в cpu_ten вставлять нельзя,
// это только экспорт наружу для тейпового счётчика). Значит: байт в очередь ПРИНИМАЕМ всегда, а
// цикл записи в #B3 РАСТЯГИВАЕМ, пока очередь не опустится ниже нижнего порога. Гость при этом
// не обязан ничего опрашивать - его OUTI просто идёт дольше, ровно как перед медленной картой.
//
// 🥇 СТОРОЖ ОБЯЗАТЕЛЕН, И ЕГО СМЫСЛ - «ОБОЛОЧКА УМЕРЛА», А НЕ «ЖДЁМ СЛИШКОМ ДОЛГО».
// Любое условие снятия, завязанное только на ARM, даёт ARM право заморозить машину навсегда: не
// запущена прошивка, выключена опция GS, ушла в исключение, перезагружено ядро - и Z80 стоит до
// выключения питания, причём изнутри машины вылечить это нечем. Поэтому счётчик 2^23 тактов
// (~148 мс на 56.7 МГц, тот же порог, что у NEMO-IDE) ВЗВОДИТСЯ ЗАНОВО на каждый вынутый оболочкой
// байт: живая оболочка отодвигает сторож бесконечно, а измеренные паузы (до 134 мс на наполнении
// звукового кольца) его не задевают, потому что внутри такой паузы очередь всё равно вычерпывается
// порциями. Сработал - снимаем давление СОВСЕМ (`wd_off`) до первого признака жизни: держать
// машину по 148 мс на каждый байт было бы хуже, чем деградировать до старого поведения с потерей,
// а потеря теперь СЧИТАЕТСЯ поштучно и видна прошивке.
//
// ПРИБОР. Считаем то, что раньше померить было нечем: ПОТЕРЯННЫЕ БАЙТЫ (а не эпизоды - эпизод
// ничего не говорит о размере ущерба), число удержаний и суммарную цену удержаний в тактах
// процессора. Последнее нужно, чтобы видеть, не платим ли мы за корректность скоростью машины.
//-------------------------------------------------------------------------------------------------
module gs_flow #(
    parameter integer WDB = 19                 // сторож в тактах ПРОЦЕССОРА: 2^19 / 3.5 МГц ≈ 150 мс
)(
    input  wire        clock,                  // домен машины (spclk)
    input  wire        reset_n,
    input  wire        ten,                    // разрешение такта процессора ДО нашего вмешательства
    input  wire        wr_acc_b3,              // УРОВЕНЬ: идёт цикл записи в порт данных #B3
    input  wire        wr_evt_b3,              // фронт этой записи: байт предъявлен очереди
    input  wire        wq_afull,               // очередь выше верхнего порога
    input  wire        wq_full,                // очередь ПОЛНА -> предъявленный байт потерян
    input  wire        drain,                  // оболочка вынула байт: признак жизни для сторожа
    output reg         hold,                   // 1 = держать процессор тактами ожидания
    output wire [31:0] stat2,                  // {потеряно байт[27:16], удержаний[11:0]}
    output wire [31:0] stat3                   // {сторож[31:30], тактов процессора в ожидании[19:0]}
);
    /* Разрядности выбраны ПО ЦЕНЕ В КРИСТАЛЛЕ, а не «на всякий случай»: первая сборка B0119 с
       широкими насыщающимися счётчиками не разместилась (не хватило 16 слайсов из 4400 при 91.6 %
       LUT). Счётчики свободно ПЕРЕПОЛНЯЮТСЯ - прошивка и так смотрит на приращение, а 4095
       потерянных байт или 4095 удержаний - это давно уже приговор, точное число там не нужно.
       Сторож считает такты ПРОЦЕССОРА, а не такты кристалла: их в 16 раз меньше при том же
       времени, и счётчик становится на четыре разряда короче. Пока мы держим шину, разрешение
       такта продолжает приходить (мы гасим его ПОСЛЕ этой точки), так что время идёт честно. */
    reg [WDB-1:0] wd = {WDB{1'b0}};
    reg           wd_off = 1'b0;               // сторож сработал: давление снято до оживления оболочки
    reg [11:0]    lost7 = 12'd0;               // ПОТЕРЯННЫЕ БАЙТЫ - штуками, а не эпизодами
    reg [11:0]    stall_n = 12'd0;             // сколько раз пришлось придержать шину
    reg [19:0]    hold_ts = 20'd0;             // и на сколько тактов процессора суммарно (~0.3 с)
    reg [1:0]     wd_hits = 2'd0;              // сколько раз срабатывал сторож

    /* Требование удержания РЕГИСТРИРУЕМ. Комбинационный путь «дешифратор порта + порог очереди»
       уходил бы прямо в разрешение такта с огромным разветвлением - худший путь для тайминга.
       Такт 56.7 МГц здесь ничего не стоит: цикл записи Z80 держится порядка сорока таких тактов. */
    wire hold_req = wr_acc_b3 & wq_afull & ~wd_off;

    always @(posedge clock) begin
        if (!reset_n) begin
            hold <= 1'b0; wd <= {WDB{1'b0}}; wd_off <= 1'b0;
            lost7 <= 12'd0; stall_n <= 12'd0; hold_ts <= 20'd0; wd_hits <= 2'd0;
        end else begin
            hold <= hold_req;
            if (hold_req & ~hold) stall_n <= stall_n + 12'd1;
            if (hold & ten)       hold_ts <= hold_ts + 20'd1;
            /* Потеря считается ПО ФАКТУ предъявления байта в полную очередь - ровно там же, где
               ставится липкий признак в main.v. Один байт = одна единица, никаких эпизодов. */
            if (wr_evt_b3 & wq_full) lost7 <= lost7 + 12'd1;
            /* Сторож: считаем только пока держим, и обнуляем на каждый признак жизни оболочки. */
            if (drain) begin
                wd     <= {WDB{1'b0}};
                wd_off <= 1'b0;                // оболочка ожила - давление возвращаем
            end else if (hold & ten) begin
                wd <= wd + 1'b1;
                if (&wd) begin wd_off <= 1'b1; wd_hits <= wd_hits + 2'd1; end
            end else if (!hold) begin
                wd <= {WDB{1'b0}};
            end
        end
    end

    assign stat2 = {4'd0, lost7, 4'd0, stall_n};
    assign stat3 = {wd_hits, 10'd0, hold_ts};
endmodule
