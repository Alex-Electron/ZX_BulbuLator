`timescale 1ns/1ps
//-------------------------------------------------------------------------------------------------
// divmmc_card.v - КАРТА SD В ФАБРИКЕ, НА БАЙТОВОМ УРОВНЕ. Том, CSD/CID, FAT и запись - на ARM.
//
// ПОЧЕМУ ОНА ЗДЕСЬ, А НЕ В ПРОШИВКЕ. У esxDOS дедлайн ответа на команду - 12800 опросов по 36 T
// (`esxdos.asm` L1DD2) = 130.1 мс, а худший проход главного цикла оболочки - 134 мс. Схема, где R1
// отвечает ARM, отказывает случайно с запасом МИНУС три процента. Автомат в фабрике отвечает
// немедленно; ARM остаётся только дедлайн токена данных - 1.30 с (L1DC4, 10 подходов).
//
// ГРАНИЦА С УЖЕ СИНТЕЗИРОВАННЫМ ЖЕЛЕЗОМ. Биты в байты собирает `cores/zx/src/spi.v` (его и `usd.v`
// не трогаем - в них и есть ценность схемы). Мы висим на его же проводах `ck`/`mosi`/`miso` и НЕ
// дешифруем ни одного порта: второго декодера `#E7`/`#EB` в машине не появляется (мина немого
// SAA1099 - это два модуля с одним именем, но по адресу порта она повторилась бы так же).
//
// 🥇 КАДРИРОВАНИЕ ПОЛУЧАЕТСЯ ФИЗИЧЕСКИ, А НЕ ДИСЦИПЛИНОЙ. `spi.v` даёт РОВНО восемь фронтов `ck` на
// байт и держит `ck` в нуле между передачами (`count[4]` = простой, `ck = count[0]`). Поэтому наш
// счётчик бит `bitc` не может уехать: он считает то, чего физически ровно восемь. Из этого следует
// правило, нарушать которое нельзя: `bitc` НЕ СБРАСЫВАЕТСЯ НИ ПО КАКОМУ СБРОСУ. У `spi.v` сброса
// нет вовсе (`count` только с `initial`), и сброс нашего счётчика посреди чужой передачи - это
// перекос на бит НАВСЕГДА, то есть «чужой сектор через месяц», а не ошибка.
//
// НАЧАЛО КОМАНДЫ ЛОВИТСЯ ПО СТАРТ-БИТУ `01`, А НЕ ПО ФРОНТУ CS. esxDOS не снимает `#E7` между
// командами: L1DE0 перед каждой лишь ЗАПИСЫВАЕТ туда то же значение `($3dfe)`. Автомат по фронту CS
// увидел бы первую команду и потерял все следующие. Обратная сторона: в фазе ПРИЁМА данных
// (CMD24/CMD25) приёмник команд обязан молчать - иначе каждый четвёртый байт полезной нагрузки
// (старшие биты `01`) был бы разобран как команда.
//
// ОБРАТНОЕ ДАВЛЕНИЕ - ТОЛЬКО `0xFF` («карта не готова»), НИКАКИХ ТАКТОВ ОЖИДАНИЯ. У модуля нет и не
// может появиться выхода в `cpu_hold`: мёртвый ARM не имеет права заморозить Z80. esxDOS такое
// давление держит по построению - L1DD2 (перед R1), L1DC4 (перед токеном, 10x130 мс) и опрос после
// блока записи - это всё циклы «читать, пока 0xFF».
//
// ЭТАЛОН ПОВЕДЕНИЯ - `arm/divmmc_card.c`, исполняемая спецификация (10 000 случайных секторов на
// хостовом стенде, 0 расхождений). Наш стенд `tb_divmmc_card.sv` гоняет ТУ ЖЕ модель через DPI-C и
// сверяет поток машине байт-в-байт. Отступления от неё - три, все осознанные и перечислены внизу.
//
//=================================================================================================
// ЧТО ОБЯЗАНА ДЕЛАТЬ ОБОЛОЧКА (порядок важен, иначе карта молча отдаст не то)
//=================================================================================================
// Монтирование:
//   1. `DMMC_CAP` (0x1B8) = ёмкость карты в секторах. Она ОБЯЗАНА быть кратна 1024: esxDOS берёт
//      объём только из `C_SIZE` CSD v2.0 и умножает на 1024 (esxdos.asm L1EA3/L1E97). Ноль = «предел
//      не задан», проверки адреса не будет.
//   2. `DMMC_BUFA` = 0x600, дальше четыре записи `DMMC_BUFW` - это CSD; затем BUFA = 0x610 и ещё
//      четыре - CID. Их содержимое строит ARM (`build_csd`/`build_cid` эталона), фабрика их только
//      отдаёт блоком с токеном.
//   3. `DMMC_CTL` = EN(бит0) | CCS(бит2), при томе только на чтение ещё WP(бит1).
// Обслуживание чтения (дедлайн 1.30 с - десять подходов L1DC4):
//   `DMMC_STAT`бит0 = 1 -> взять сектор из `DMMC_LBA`, положить 512 байт в буфер A (BUFA=0x000) или
//   B (0x200), затем `DMMC_CTL` = ... | RD_SEQ(эхо STAT[3:2]) | RD_ACK | RD_BUF(какой буфер).
//   Пока подтверждения нет, машина получает 0xFF - это законно и ничего не ломает.
//   Упреждающее чтение окупается: пока машина тянет один блок, следующий кладётся во второй буфер.
// Обслуживание записи:
//   `DMMC_STAT`бит1 = 1 -> забрать 512 байт из буфера записи (BUFA=0x400, дальше `DMMC_BUFR`),
//   записать в том и ответить `WR_SEQ`(эхо) | WR_ACK, при отказе ещё WR_ERR.
// ⚠ Три правила, нарушение которых даёт МОЛЧАЛИВУЮ порчу данных:
//   * `RD_SEQ`/`WR_SEQ` - это ЭХО номера запроса из `DMMC_STAT[3:2]`. Подтверждение с чужим номером
//     карта игнорирует намеренно: иначе повторяется болезнь GS и клавиатуры - подтверждение
//     запроса, который карта уже сняла.
//   * `FSM_RST` (бит3) в словах подтверждения обязан быть НУЛЁМ. Он действует по тому же стробу и
//     сбросил бы автомат посреди блока.
//   * `DMMC_BUFR` двигает указатель ПО ФАКТУ чтения. Читать «на всякий случай» нельзя - пропустите
//     слово.
//-------------------------------------------------------------------------------------------------
module divmmc_card #(
    parameter [3:0] P_NCR   = 4'd1,   // байтов 0xFF между кадром команды и R1 (N_CR)
    parameter [3:0] P_NAC   = 4'd2,   // байтов 0xFF между R1 и токеном блока (N_AC)
    parameter [2:0] P_A41   = 3'd2,   // сколько ACMD41 ответят «ещё не готова»
    parameter [3:0] P_WBUSY = 4'd4,   // байтов 0x00 занятости после приёма блока
    parameter       P_CRC16 = 1       // 1 = честный CRC16 блока (esxDOS его выбрасывает, а UnoDOS и
                                      //     самописные драйверы проверяют); 0 = 0xFFFF, дешевле
)(
    //---- домен машины (spclk 56.667 МГц) --------------------------------------------------------
    input  wire        clk,
    input  wire        ce,        // ⚠ НЕ ИСПОЛЬЗУЕТСЯ с B0145: выборка идёт по ФРОНТУ sck (см. ниже),
                                  // поэтому карте всё равно, чем тактуется движок и на какой он
                                  // скорости. Порт оставлен, чтобы не трогать топ и чужие деревья.
    input  wire        rst_n,     // сброс машины. B0135: протокол по нему НЕ сбрасывается - см. ниже
    input  wire        en,        // MACHINE_CFG[17]: DivMMC включён
    input  wire        cs_n,      // usd.cs: 0 = карта выбрана (esxDOS пишет 0xF6 в #E7)
    input  wire        sck,       // usd.ck
    input  wire        mosi,      // usd.mosi
    output wire        miso,      // -> usd.miso
    input  wire [8:0]  map_dbg,   // {mapram залипал, page[4:0], mapram, conmem, automap} из memory.v

    //---- домен оболочки (fclk100) ---------------------------------------------------------------
    input  wire        aclk,
    input  wire        arst_n,
    input  wire [31:0] ctl,       // 0x19C DMMC_CTL
    input  wire        ctl_we,    // тоггл (флаг догоняет данные через два такта - в axi_ctl)
    input  wire [31:0] cap_in,    // 0x1B8 DMMC_CAP: ёмкость карты в секторах
    input  wire [31:0] bufa_in,   // 0x1A0 DMMC_BUFA
    input  wire        bufa_we,
    input  wire [31:0] bufw_in,   // 0x1A4 DMMC_BUFW  {b3,b2,b1,b0}
    input  wire        bufw_we,
    input  wire        bufr_re,   // 0x1A8 DMMC_BUFR (строб чтения)
    output wire [31:0] bufa_q,
    output wire [31:0] bufr_q,
    output wire [31:0] stat,      // 0x1AC DMMC_STAT
    output wire [31:0] lba_q,     // 0x1B0 DMMC_LBA
    output wire [31:0] dbg        // 0x1B4 DMMC_DBG
);

    //---------------------------------------------------------------------------------------------
    // Состояния. 0..13 - один в один с enum эталона (divmmc_card.c:69-85), чтобы поле состояния в
    // DMMC_STAT читалось теми же именами. 14 - НАШ, его у модели быть не может: там запись в
    // носитель мгновенна, а у нас её делает ARM.
    //---------------------------------------------------------------------------------------------
    localparam [3:0] S_IDLE=4'd0,  S_ARG=4'd1,   S_NCR=4'd2,   S_RESP=4'd3,
                     S_NAC=4'd4,   S_TOKEN=4'd5, S_TX=4'd6,    S_TXCRC=4'd7,
                     S_MBGAP=4'd8, S_RXWAIT=4'd9,S_RX=4'd10,   S_RXCRC=4'd11,
                     S_RXRESP=4'd12,S_BUSY=4'd13,S_RXACK=4'd14;

    // Раскладка буферной BRAM 2048x9 (бит 8 - метка «CS снимали внутри блока»).
    localparam [10:0] B_RDA=11'h000, B_RDB=11'h200, B_WR=11'h400,
                      B_CSD=11'h600, B_CID=11'h610;

    localparam [7:0] TOK_START = 8'hFE;   // токен блока (чтение и одиночная запись)
    localparam [7:0] TOK_MULTI = 8'hFC;   // токен блока мультиблочной записи
    localparam [7:0] TOK_STOP  = 8'hFD;   // конец мультиблочной записи
    localparam [7:0] TOK_RDERR = 8'h08;   // токен ошибки чтения (у эталона его нет, см. низ файла)

    //=============================================================================================
    // Буферная BRAM: 1 x RAMB18, 2048x9, два порта и два такта. Через неё же идёт весь обмен
    // блоками с ARM - собственного моста данных не заводим.
    //=============================================================================================
    reg [8:0] bmem [0:2047];
    reg [8:0] a_q = 9'd0, b_q = 9'd0;

    /* ⚠ Начальные значения тут ОБЯЗАТЕЛЬНЫ, и это не косметика. Триггер ПЛИС при включении встаёт
       в своё initial-значение, а без него автомат стороны оболочки в симуляции стартует в X, и
       условие `astep == 0` навсегда остаётся X: сброса-то на этой стороне почти нет. Поймано
       стендом - буфер молча не наполнялся, машина читала нули. */
    reg  [10:0] a_addr = 11'd0;  reg [8:0] a_din = 9'd0;  reg a_we = 1'b0;
    reg  [10:0] b_addr = 11'd0;  reg [8:0] b_din = 9'd0;  reg b_we = 1'b0;

    always @(posedge aclk) begin
        if (a_we) bmem[a_addr] <= a_din;
        a_q <= bmem[a_addr];
    end
    always @(posedge clk) begin
        if (b_we) bmem[b_addr] <= b_din;
        b_q <= bmem[b_addr];
    end

    //=============================================================================================
    // Сторона оболочки: указатель и обмен по 4 байта. Указатель ЖИВОЙ (читается обратно), пачка из
    // четырёх байт разворачивается в четыре обращения к 9-битному порту - иначе слово не влезает.
    //=============================================================================================
    reg [10:0] aptr  = 11'd0;
    reg [2:0]  astep = 3'd0;   // 0 = простой; 1..4 запись, 1..5 чтение (лишний шаг - конвейер BRAM)
    reg        awr   = 1'b0;   // 1 = идёт пачка записи
    reg [31:0] awdat = 32'd0, ardat = 32'd0;
    reg [10:0] abase = 11'd0;

    always @(posedge aclk) begin
        a_we <= 1'b0;
        if (!arst_n) begin
            aptr <= 11'd0; astep <= 3'd0; awr <= 1'b0; ardat <= 32'd0; abase <= 11'd0;
        end else if (astep == 3'd0) begin
            if (bufa_we) begin                     // установка указателя + упреждающее чтение
                aptr  <= bufa_in[10:0];
                abase <= bufa_in[10:0];
                a_addr<= bufa_in[10:0];
                awr   <= 1'b0; astep <= 3'd1;
            end else if (bufw_we) begin            // запись 4 байт по текущему указателю
                awdat <= bufw_in; abase <= aptr;
                a_addr<= aptr; a_din <= {1'b0, bufw_in[7:0]}; a_we <= 1'b1;
                aptr  <= aptr + 11'd4;
                awr   <= 1'b1; astep <= 3'd1;
            end else if (bufr_re) begin            // отдали накопленное слово, читаем следующее
                abase <= aptr + 11'd4;
                a_addr<= aptr + 11'd4;
                aptr  <= aptr + 11'd4;
                awr   <= 1'b0; astep <= 3'd1;
            end
        end else begin
            astep <= (awr ? (astep == 3'd4) : (astep == 3'd5)) ? 3'd0 : astep + 3'd1;
            if (awr) begin
                a_addr <= abase + {8'd0, astep};
                case (astep)
                    3'd1: a_din <= {1'b0, awdat[15: 8]};
                    3'd2: a_din <= {1'b0, awdat[23:16]};
                    default: a_din <= {1'b0, awdat[31:24]};
                endcase
                a_we <= (astep <= 3'd3);
            end else begin
                a_addr <= abase + {8'd0, astep};
                /* a_q отстаёт от адреса РОВНО на такт, поэтому забирать байт надо на шаг позже,
                   чем выставлен его адрес. На шаге 1 в a_q лежит ещё ЧУЖОЕ слово от прошлой
                   операции - именно на этом стенд поймал сдвиг всего блока на байт. */
                case (astep)
                    3'd2: ardat[ 7: 0] <= a_q[7:0];
                    3'd3: ardat[15: 8] <= a_q[7:0];
                    3'd4: ardat[23:16] <= a_q[7:0];
                    3'd5: ardat[31:24] <= a_q[7:0];
                    default: ;
                endcase
            end
        end
    end

    assign bufa_q = {21'd0, aptr};
    assign bufr_q = ardat;

    //=============================================================================================
    // ARM -> машина. Приём тот же, что у NEMO-IDE и мыши (B0114/B0116): три триггера на тоггл,
    // слово защёлкивается ТЕМ ЖЕ фронтом, которым найден фронт флага. Сдвиг флага на два такта
    // относительно данных сделан на стороне axi_ctl.
    //=============================================================================================
    (* ASYNC_REG="TRUE" *) reg [2:0] we_s = 3'b000;
    reg [31:0] ctl_l = 32'd0;
    reg [31:0] cap_l = 32'd0;
    reg        arm_stb = 1'b0;
    always @(posedge clk) begin
        we_s    <= {we_s[1:0], ctl_we};
        arm_stb <= we_s[2] ^ we_s[1];
        if (we_s[2] ^ we_s[1]) begin
            ctl_l <= ctl;
            cap_l <= cap_in;   // ёмкость держится оболочкой неподвижно и защёлкивается тем же стробом
        end
    end

    wire       cfg_en    = ctl_l[0];    // карта вставлена (том смонтирован)
    wire       cfg_wp    = ctl_l[1];    // том только на чтение
    wire       cfg_ccs   = ctl_l[2];    // 1 = SDHC, адресация блоками
    wire       cfg_rst   = ctl_l[3];
    wire [1:0] ack_rseq  = ctl_l[7:6];
    wire       ack_rd    = ctl_l[8];
    wire       ack_rderr = ctl_l[9];
    wire [1:0] ack_wseq  = ctl_l[11:10];
    wire       ack_wr    = ctl_l[12];
    wire       ack_wrerr = ctl_l[13];
    wire       ack_rbuf  = ctl_l[14];
    // 🥇 B0150 БЫСТРОЕ ПОДТВЕРЖДЕНИЕ ЗАПИСИ (опция владельца). После байтов занятости карта отдаёт
    // ОДИН байт 0x01 перед 0xFF. Зачем: esxDOS 0.8.9 ждёт конца занятости циклом «читать до ≠0xFF,
    // не более 12 800 раз» (ESXMMC.ROM 1E55/1EC2) - по спеке SD такого байта нет никогда, и цикл
    // всегда упирается в таймаут: 132 мс на КАЖДЫЙ сектор, `.mkdir` (256 секторов нулей) - 35 с.
    // Драйверы KOE («ждать ≠0») и NedoOS («ждать ≠FF») байт 0x01 принимают за «занятость снята».
    // Отход от буквы спеки, поэтому за битом, а не безусловно.
    wire       cfg_fast  = ctl_l[15];

    wire attached = en & cfg_en;

    //=============================================================================================
    // Битовый двигатель. Единственное место, где мы вообще смотрим на биты.
    //=============================================================================================
    reg  [7:0] osr = 8'hFF;      // что отдаём (сдвигается вслед за spi.v)
    reg  [7:0] isr = 8'hFF;      // что приняли
    reg  [2:0] bitc = 3'd0;      // ⚠ БЕЗ СБРОСА - см. шапку
    reg  [7:0] rx_lat = 8'hFF;
    reg        byte_ev = 1'b0;

    wire       sel  = ~cs_n;
    /* 🥇 ВЫБОРКА ИДЁТ ПО ФРОНТУ sck, А НЕ ПО ЕГО УРОВНЮ, И ВХОД `ce` В НЕЙ НЕ УЧАСТВУЕТ.
       Было `smp = ce & sck`. Пока движок тактовался `ne7M0` (один такт из восьми), уровень и фронт
       совпадали. С B0142 движок стал переключаемым, а в топе стоит `.ce(1'b1)`: в стандартном
       режиме 3.5 МГц уровень `sck` живёт ВОСЕМЬ тактов spclk, поэтому `bitc` набирал +8 (то есть
       +0 по модулю 8), а `isr` восемь раз задвигал ОДИН И ТОТ ЖЕ бит - принятый байт вырождался в
       0x00/0xFF и счётчик рассинхрона насыщался на 15. Проверено симуляцией связки usd_bulb +
       divmmc_card (tb_zc_speed.v).
       Разделение обязательно ИМЕННО такое, это режим 0 SPI:
         * MOSI берём на ПЕРЕДНЕМ фронте - хост держит бит весь высокий полупериод;
         * свой байт двигаем на СПАДЕ - тогда miso стоит неподвижно всё время, пока движок его
           защёлкивает (`usd_bulb.v:87` делает это в конце высокого полупериода).
       Взять оба события на одном фронте нельзя: на переднем поедет MISO (движок прочитает уже
       сдвинутый бит - в симуляции это R1 = 0x03 вместо 0x01), на спаде поедет MOSI (движок к тому
       времени уже выставил следующий бит). В режиме turbo, где полупериод равен одному такту,
       поведение остаётся байт-в-байт прежним - проверено тем же стендом. */
    reg        sck_d  = 1'b0;
    reg        mosi_r = 1'b1;
    wire       smp_r = sck & ~sck_d;         // передний фронт sck: берём бит хоста
    wire       smp   = ~sck & sck_d;         // спад sck: шаг байтового автомата и смена своего бита
    wire       last = (bitc == 3'd7);
    wire [7:0] rx_w = {isr[6:0], mosi_r};

    assign miso = (attached & sel) ? osr[7] : 1'b1;

    //=============================================================================================
    // Автомат карты
    //=============================================================================================
    reg [3:0]  state = S_IDLE;
    reg [47:0] fr    = 48'd0;     // кадр команды: {cmd, arg[31:0], crc7}
    reg [2:0]  fcnt  = 3'd0;
    reg [6:0]  crc7  = 7'd0;
    reg [39:0] resp  = 40'd0;
    reg [2:0]  rcnt  = 3'd0;
    reg [3:0]  after = S_IDLE;
    reg [3:0]  wcnt  = 4'd0;
    reg [10:0] dbase = B_RDA;
    reg [9:0]  dcnt  = 10'd0;
    reg [9:0]  dlen  = 10'd512;
    reg [15:0] crc16 = 16'd0;
    reg [31:0] lba   = 32'd0;
    reg        multi = 1'b0, stopnext = 1'b0;
    reg        idle_st = 1'b1, spi_md = 1'b0, app = 1'b0;
    reg [2:0]  a41   = P_A41;
    reg        cs_mark = 1'b0;               // CS снимали внутри блока - метка в бит 8 буфера

    // мост запросов к оболочке
    reg        rq_rd = 1'b0, rq_wr = 1'b0;
    reg [1:0]  rq_seq = 2'd0;
    reg        rd_rdy = 1'b0, rd_err = 1'b0;   // ответ ARM на запрос блока
    reg        wr_rdy = 1'b0, wr_err = 1'b0;
    reg        rbuf   = 1'b0;

    // приборы
    reg [7:0]  c_cmds = 8'd0, c_rd = 8'd0, c_wr = 8'd0;
    reg [3:0]  c_ill = 4'd0, c_desync = 4'd0;
    reg [5:0]  last_cmd = 6'd0, last_unk = 6'd0;
    reg        crc7_bad = 1'b0;

    // конвейер загрузки выходного байта
    reg [7:0]  nxt_byte = 8'hFF;
    reg        nxt_bram = 1'b0;
    reg [1:0]  ld_cnt   = 2'd0;

    /* Временные переменные разбора команды (блокирующие, живут внутри одного шага автомата): ветки
       различаются одним байтом R1 и одним из ТРЁХ хвостов, поэтому разбор отдаёт узкие управляющие
       значения, а широкое слово ответа собирается ОДИН раз.
       ⚠ Это сделано для ЧИТАЕМОСТИ, а не ради кристалла: замерено 482 LUT до и 487 после, то есть
       мультиплексор на 40 бит синтезатор сворачивал и сам. Не тратить на такие переписывания время
       второй раз - у этого модуля разброс между прогонами больше самой правки (см. таблицу внизу). */
    reg [7:0]  r1v;      // байт R1 этой команды
    reg [1:0]  tsv;      // какой хвост: 0 нули, 1 эхо R7 (CMD8), 2 регистр OCR (CMD58)
    reg [31:0] tlv;
    reg [2:0]  rcv;      // сколько байт в ответе
    reg [3:0]  afv;      // куда уйти, когда ответ дошлётся

    wire [47:0] fr_new = {fr[39:0], rx_lat};
    wire [5:0]  idx    = fr_new[45:40];
    wire [31:0] argv   = fr_new[39:8];
    wire [7:0]  crcb   = fr_new[7:0];
    wire [7:0]  r1b    = idle_st ? 8'h01 : 8'h00;
    // Ноль в DMMC_CAP = «предел не задан»: иначе забытая оболочкой ёмкость превратила бы КАЖДОЕ
    // чтение в отказ по адресу, и отлаживали бы мы не то.
    wire        oor    = (cap_l != 32'd0) && (argv >= cap_l);
    wire        sniff  = multi & ((state==S_NAC)|(state==S_TOKEN)|(state==S_TX)|
                                  (state==S_TXCRC)|(state==S_MBGAP));

    function [6:0] crc7_b;
        input [6:0] c; input [7:0] b;
        integer i; reg [6:0] cc; reg [7:0] bb; reg t;
        begin
            cc = c; bb = b;
            for (i = 0; i < 8; i = i + 1) begin
                t  = cc[6] ^ bb[7];
                cc = {cc[5:0], 1'b0};
                if (t) cc = cc ^ 7'h09;
                bb = {bb[6:0], 1'b0};
            end
            crc7_b = cc;
        end
    endfunction

    function [15:0] crc16_b;
        input [15:0] c; input [7:0] b;
        integer i; reg [15:0] cc;
        begin
            cc = c ^ {b, 8'h00};
            for (i = 0; i < 8; i = i + 1)
                cc = cc[15] ? ((cc << 1) ^ 16'h1021) : (cc << 1);
            crc16_b = cc;
        end
    endfunction

    always @(posedge clk) begin
        //---- биты ------------------------------------------------------------------------------
        sck_d <= sck;
        if (smp_r) mosi_r <= mosi;           // бит хоста снят на переднем фронте, ждёт спада
        byte_ev <= 1'b0;
        if (smp) begin
            isr  <= rx_w;
            bitc <= bitc + 3'd1;              // ⚠ считает ВСЕГДА, и при снятом CS тоже
            if (attached & sel) begin
                if (last) begin rx_lat <= rx_w; byte_ev <= 1'b1; end
                else           osr    <= {osr[6:0], 1'b1};
            end
        end

        //---- строб буфера по умолчанию снят ------------------------------------------------------
        b_we <= 1'b0;

        //---- ответ оболочки на запрос -------------------------------------------------------------
        // 🥇 Эхо seq обязательно: ack принимается, ТОЛЬКО если он про тот запрос, который карта ещё
        // держит. Без этого повторяется болезнь GS и клавиатуры - подтверждение снятого запроса.
        if (arm_stb) begin
            if (rq_rd & ack_rd & (ack_rseq == rq_seq)) begin
                rq_rd <= 1'b0; rd_rdy <= 1'b1; rd_err <= ack_rderr;
                rbuf  <= ack_rbuf;
                dbase <= ack_rbuf ? B_RDB : B_RDA;
            end
            if (rq_wr & ack_wr & (ack_wseq == rq_seq)) begin
                rq_wr <= 1'b0; wr_rdy <= 1'b1; wr_err <= ack_wrerr;
            end
        end

        //---- конвейер выходного байта ------------------------------------------------------------
        // Грузим через ДВА такта после шага автомата: такт на адрес BRAM, такт на её выход. Между
        // соседними выборками miso у sck не меньше четырёх тактов (варп 4x) и шестнадцати в
        // штатном режиме, так что запас есть. Загрузка стоит ПОСЛЕ сдвига - у неё приоритет.
        if (byte_ev) ld_cnt <= 2'd2;
        else if (ld_cnt != 2'd0) begin
            ld_cnt <= ld_cnt - 2'd1;
            if (ld_cnt == 2'd1) begin
                osr <= nxt_bram ? b_q[7:0] : nxt_byte;
                if (nxt_bram && (P_CRC16 != 0)) crc16 <= crc16_b(crc16, b_q[7:0]);
            end
        end

        //---- снятие CS --------------------------------------------------------------------------
        // Эталон (divmmc_card.c:338-346) забывает НЕДОБРАННЫЙ кадр команды и больше ничего: `app`
        // после CMD55 обязан пережить снятие CS, потому что esxDOS его там и снимает (L1D67 -> L1D71
        // -> L1D5E пишет 0xFF в #E7 на ответ 0x01, а следом шлёт ACMD41).
        if (!sel) begin
            if (state == S_ARG) begin state <= S_IDLE; fcnt <= 3'd0; end
            if ((state == S_RX) || (state == S_RXCRC) || (state == S_RXWAIT)) cs_mark <= 1'b1;
        end

        //---- шаг автомата ------------------------------------------------------------------------
        if (byte_ev) begin
            nxt_byte <= 8'hFF;
            nxt_bram <= 1'b0;

            /* 🥇 ЕДИНСТВЕННАЯ ТОЧКА ИСПОЛНЕНИЯ CMD12, ПОЙМАННОЙ В ПОТОКЕ ЧТЕНИЯ.
               Раньше её было две, и они вели себя по-разному: в S_TXCRC карта досылала R1 и
               занятость, а в S_MBGAP (пауза между блоками) уходила в S_IDLE МОЛЧА - `nxt_byte`
               оставался 0xFF, и драйвер, который ждёт R1b на стоп-команду, опрашивал порт вечно.
               Ровно этот снимок снят с виса Z-Player 4.1 19.08: state=IDLE, last_cmd=18,
               card_busy=0, дельта команд и чтений за 4 с нулевая. А пауза между блоками - это не
               узкое окно: она длится столько, сколько думает оболочка, и канонический драйвер
               (elm-chan, u-boot mmc_spi, drivers/mmc/mmc.c:425) шлёт CMD12 РОВНО на границе
               блока, вычитав и оба байта CRC, - то есть попадает именно сюда.
               Спека требует ответа в обоих случаях: SD Physical Layer 6.00, Figure 7-5 (после
               стоп-команды идёт response) и §7.2.8 «in the SPI mode, the card will always respond
               to a command».
               Заодно снят второй перекос: стоп больше не ждёт конца текущего блока. Раньше R1
               приходил через остаток блока плюс два байта CRC (до 515 байт), а если CMD12 попала
               в S_NAC, карта досылала ЦЕЛЫЙ ненужный блок 512+2 - и драйвер, ищущий первый байт
               с нулевым старшим битом, законно принимал за R1 байт ДАННЫХ.
               ⚠ `rq_rd` здесь НЕ снимается. Он парен с `rq_seq`/`ack_rseq`, и односторонний сброс
               со стороны карты - это ровно тот полуоткрытый хэндшейк, что уже стоил нам GS и
               клавиатуры. Ack приедет по своему номеру, `rd_rdy` обнулит следующая CMD17/CMD18. */
            if (stopnext & sniff) begin
                multi <= 1'b0; stopnext <= 1'b0; fcnt <= 3'd0;
                resp  <= {r1b, 32'd0}; rcnt <= 3'd1; after <= S_BUSY;
                wcnt  <= P_NCR; state <= (P_NCR != 4'd0) ? S_NCR : S_RESP;
                if (P_NCR == 4'd0) nxt_byte <= r1b;
            end else
            case (state)
            //-------------------------------------------------------------------- приём команды --
            S_IDLE, S_ARG: begin
                if (fcnt == 3'd0) begin
                    if (rx_lat[7:6] != 2'b01) begin
                        if (rx_lat != 8'hFF) c_desync <= (c_desync==4'hF) ? c_desync : c_desync+4'd1;
                    end else begin
                        fr <= fr_new; fcnt <= 3'd1; crc7 <= crc7_b(7'd0, rx_lat); state <= S_ARG;
                    end
                end else if (fcnt < 3'd5) begin
                    fr <= fr_new; fcnt <= fcnt + 3'd1; crc7 <= crc7_b(crc7, rx_lat);
                end else begin
                    //---- шестой байт: исполняем ------------------------------------------------
                    fr <= fr_new; fcnt <= 3'd0;
                    app <= 1'b0;
                    last_cmd <= idx;
                    c_cmds   <= (c_cmds == 8'hFF) ? c_cmds : c_cmds + 8'd1;
                    // CRC7 команд карта в SPI не обязана проверять, и esxDOS шлёт его честно только
                    // для CMD0 ($95) и CMD8 ($87) (L1D9A). Мы не отказываем, но НЕСОВПАДЕНИЕ ловим:
                    // это единственный дешёвый прибор на перекос битности сдвигателя.
                    if ((crcb != 8'hFF) && (crcb != {crc7, 1'b1})) crc7_bad <= 1'b1;

                    r1v = r1b; tsv = 2'd0; rcv = 3'd1; afv = S_IDLE;   // умолчание: короткий R1

                    if (!spi_md && (idx != 6'd0)) begin
                        // до CMD0 карта в SPI-режим не переведена: «idle + недопустимая команда».
                        // Настоящая карта не ответила бы вовсе, но тогда драйвер завис бы навсегда.
                        r1v = 8'h05;
                    end else if (app && (idx == 6'd41)) begin
                        // ACMD41: аргумент 0x40000000 = хост понимает карты большой ёмкости
                        if (a41 != 3'd0) begin a41 <= a41 - 3'd1; r1v = 8'h01; end
                        else            begin idle_st <= 1'b0;    r1v = 8'h00; end
                    end else begin
                        case (idx)
                        6'd0: begin                                    // GO_IDLE_STATE
                            spi_md <= 1'b1; idle_st <= 1'b1; a41 <= P_A41; r1v = 8'h01;
                        end
                        6'd1: begin                                    // SEND_OP_COND (карты v1)
                            if (a41 != 3'd0) begin a41 <= a41 - 3'd1; r1v = 8'h01; end
                            else            begin idle_st <= 1'b0;    r1v = 8'h00; end
                        end
                        6'd8: begin tsv = 2'd1; rcv = 3'd5; end        // SEND_IF_COND: R7 = эхо 12 бит
                        6'd9, 6'd10: begin                             // SEND_CSD / SEND_CID
                            // 🥇 Это НЕ «R1 и следом 16 байт», а настоящий блок с токеном: L1D2F
                            // после команды зовёт L1DC4 (ждать 0xFE) и лишь потом `ld b,$12 : inir`.
                            // Ответ без токена упирает инициализацию в 1.3 с и даёт «Disk error».
                            if (!idle_st) begin                        // до готовности карта их не отдаёт
                                r1v = 8'h00; afv = S_TOKEN; multi <= 1'b0;
                                dbase <= (idx == 6'd9) ? B_CSD : B_CID;
                            end
                        end
                        6'd12: begin multi <= 1'b0; stopnext <= 1'b0; end   // STOP_TRANSMISSION
                        6'd13: rcv = 3'd2;                             // SEND_STATUS: R2 = два байта
                        6'd16:                                         // SET_BLOCKLEN (только при CCS=0)
                            r1v = r1b | ((argv == 32'd512) ? 8'h00 : 8'h40);
                        6'd17, 6'd18: begin                            // READ_SINGLE / READ_MULTIPLE
                            if (idle_st | oor) r1v = r1b | (idle_st ? 8'h00 : 8'h40);
                            else begin
                                r1v = 8'h00; afv = S_NAC;
                                lba <= argv; multi <= (idx == 6'd18); stopnext <= 1'b0;
                                rq_rd <= 1'b1; rq_seq <= rq_seq + 2'd1;
                                rd_rdy <= 1'b0; rd_err <= 1'b0;
                            end
                        end
                        6'd24, 6'd25: begin                            // WRITE_BLOCK / WRITE_MULTIPLE
                            if (idle_st | oor) r1v = r1b | (idle_st ? 8'h00 : 8'h40);
                            else begin
                                r1v = 8'h00; afv = S_RXWAIT;
                                lba <= argv; multi <= (idx == 6'd25);
                            end
                        end
                        6'd55: app <= 1'b1;                            // APP_CMD (ответ esxDOS не проверяет)
                        6'd58: begin tsv = 2'd2; rcv = 3'd5; end       // READ_OCR: R3
                        6'd59: ;                                       // CRC_ON_OFF: вежливо соглашаемся
                        default: begin
                            // 🥇 Неизвестная команда обязана быть ВИДНА: R1 бит2 плюс её номер в
                            // DMMC_STAT[25:20]. Без этого прибора отладка сводится к гаданию.
                            last_unk <= idx;
                            c_ill    <= (c_ill == 4'hF) ? c_ill : c_ill + 4'd1;
                            r1v      = r1b | 8'h04;
                        end
                        endcase
                    end

                    case (tsv)
                    2'd1: tlv = {20'd0, argv[11:0]};                   // R7: эхо младших 12 бит
                    2'd2: tlv = {((idle_st ? 8'h40 : 8'hC0) & {1'b1, cfg_ccs, 6'h3F}),
                                 8'hFF, 8'h80, 8'h00};                 // R3: OCR, бит30 = CCS
                    default: tlv = 32'd0;
                    endcase

                    resp  <= {r1v, tlv};
                    rcnt  <= rcv;
                    after <= afv;
                    wcnt  <= P_NCR;
                    state <= (P_NCR != 4'd0) ? S_NCR : S_RESP;
                    if (P_NCR == 4'd0) nxt_byte <= r1v;
                end
            end

            //------------------------------------------------------------------------ пауза N_CR --
            S_NCR: begin
                if (wcnt <= 4'd1) begin state <= S_RESP; nxt_byte <= resp[39:32]; end
                wcnt <= wcnt - 4'd1;
            end

            //---------------------------------------------------------------------------- ответ --
            S_RESP: begin
                resp <= {resp[31:0], 8'h00};
                rcnt <= rcnt - 3'd1;
                if (rcnt > 3'd1) begin
                    nxt_byte <= resp[31:24];
                end else begin
                    case (after)
                    S_NAC: begin                       // блок сектора: 512 байт
                        dcnt <= 10'd0; dlen <= 10'd512; crc16 <= 16'd0;
                        wcnt <= P_NAC;
                        state <= (P_NAC != 4'd0) ? S_NAC : S_TOKEN;
                        if (P_NAC == 4'd0) begin nxt_byte <= TOK_START; b_addr <= dbase; end
                    end
                    S_TOKEN: begin                     // короткий блок CSD/CID: 16 байт, без N_AC
                        dcnt <= 10'd0; dlen <= 10'd16; crc16 <= 16'd0;
                        state <= S_TOKEN; nxt_byte <= TOK_START; b_addr <= dbase;
                    end
                    S_RXWAIT: begin state <= S_RXWAIT; cs_mark <= 1'b0; end
                    S_BUSY: begin                      // хвост остановленного CMD12 мультиблока
                        wcnt <= P_WBUSY; state <= S_BUSY; nxt_byte <= 8'h00;
                    end
                    default: begin state <= after; if (after == S_IDLE) fcnt <= 3'd0; end
                    endcase
                end
            end

            //------------------------------------------------------------------------ пауза N_AC --
            // Здесь же и ждём оболочку: пока блока нет, гоним 0xFF. Это и есть всё наше обратное
            // давление. Запас у esxDOS - 10 подходов по 130 мс (L1DC4).
            S_NAC: begin
                if (wcnt != 4'd0) wcnt <= wcnt - 4'd1;
                if ((wcnt <= 4'd1) && rd_rdy) begin
                    if (rd_err) begin
                        state <= S_IDLE; fcnt <= 3'd0; multi <= 1'b0;
                        nxt_byte <= TOK_RDERR;
                    end else begin
                        state <= S_TOKEN; nxt_byte <= TOK_START;
                        b_addr <= dbase;
                    end
                end
            end

            //---------------------------------------------------------------------------- токен --
            S_TOKEN: begin
                state <= S_TX; dcnt <= 10'd0;
                b_addr <= dbase; nxt_bram <= 1'b1;
                // считаем БЛОКИ СЕКТОРОВ, а не все блоки: CSD/CID тоже идут через токен
                if (dlen == 10'd512) c_rd <= (c_rd == 8'hFF) ? c_rd : c_rd + 8'd1;
            end

            //------------------------------------------------------------------------ тело блока --
            S_TX: begin
                if ((dcnt + 10'd1) >= dlen) begin
                    state <= S_TXCRC; dcnt <= 10'd0;
                    nxt_byte <= (P_CRC16 != 0) ? crc16[15:8] : 8'hFF;
                end else begin
                    dcnt <= dcnt + 10'd1;
                    b_addr <= dbase + {1'b0, dcnt} + 11'd1;
                    nxt_bram <= 1'b1;
                end
            end

            //------------------------------------------------------------------------------ CRC --
            S_TXCRC: begin
                if (dcnt == 10'd0) begin
                    dcnt <= 10'd1;
                    nxt_byte <= (P_CRC16 != 0) ? crc16[7:0] : 8'hFF;
                end else begin
                    dcnt <= 10'd0;
                    if (multi) begin
                        // Запрос следующего блока поднимаем РОВНО ОДИН РАЗ, здесь. Поднимать его в
                        // промежутке по условию «блок готов» нельзя: ответ оболочки взводит тот же
                        // признак, и запрос пошёл бы по кругу на каждый холостой байт.
                        // `stopnext` тут всегда 0: пойманную CMD12 исполняет общая точка ПЕРЕД
                        // разбором состояний. Единственный остаток - кадр CMD12, закончившийся
                        // РОВНО на этом байте: запрос успевает уйти, стоп сработает следующим
                        // байтом, и оболочка отдаст блок, который никому не нужен. Это и есть
                        // наблюдаемый на плате DMMC_LBA = аргумент CMD18 + 1; рукопожатие цело,
                        // ack приезжает по своему seq.
                        lba <= lba + 32'd1;
                        rq_rd <= 1'b1; rq_seq <= rq_seq + 2'd1;
                        rd_rdy <= 1'b0; rd_err <= 1'b0;
                        wcnt <= 4'd1; state <= S_MBGAP;
                    end else begin
                        multi <= 1'b0; stopnext <= 1'b0; fcnt <= 3'd0; state <= S_IDLE;
                    end
                end
            end

            //--------------------------------------------------------- промежуток мультиблока ----
            S_MBGAP: begin
                if (wcnt != 4'd0) wcnt <= wcnt - 4'd1;
                if (wcnt <= 4'd1) begin
                    // Ветки `stopnext` здесь больше нет: остановку исполняет общая точка выше, и
                    // делает она это НА СЛЕДУЮЩЕМ ЖЕ байте после кадра, не дожидаясь блока.
                    if (rd_rdy && rd_err) begin
                        multi <= 1'b0; fcnt <= 3'd0; state <= S_IDLE; nxt_byte <= TOK_RDERR;
                    end else if (rd_rdy) begin
                        dcnt <= 10'd0; dlen <= 10'd512; crc16 <= 16'd0;
                        state <= S_TOKEN; nxt_byte <= TOK_START; b_addr <= dbase;
                    end else wcnt <= 4'd1;               // блока ещё нет - держим 0xFF
                end
            end

            //-------------------------------------------------------------------- приём блока -----
            S_RXWAIT: begin
                if ((rx_lat == TOK_START) || (rx_lat == TOK_MULTI)) begin
                    dcnt <= 10'd0; state <= S_RX;
                end else if (rx_lat == TOK_STOP) begin
                    multi <= 1'b0; wcnt <= P_WBUSY; state <= S_BUSY; nxt_byte <= 8'h00;
                end
            end

            S_RX: begin
                b_addr <= B_WR + {1'b0, dcnt};
                b_din  <= {cs_mark, rx_lat};
                b_we   <= 1'b1;
                if ((dcnt + 10'd1) >= 10'd512) begin
                    dcnt <= 10'd0; state <= S_RXCRC;
                    // Запрос на запись поднимаем СРАЗУ на 512-м байте, а не после CRC: оболочке
                    // достаётся ещё два байта времени, а data-response остаётся на своём месте.
                    if (!cfg_wp) begin
                        rq_wr <= 1'b1; rq_seq <= rq_seq + 2'd1; wr_rdy <= 1'b0; wr_err <= 1'b0;
                    end
                    c_wr <= (c_wr == 8'hFF) ? c_wr : c_wr + 8'd1;
                end else dcnt <= dcnt + 10'd1;
            end

            S_RXCRC: begin
                // CRC принятого блока обе половины связки не считают (esxDOS шлёт два 0xFF, L1DEA),
                // и рвать запись из-за него нельзя. Принимаем и выбрасываем.
                if (dcnt == 10'd0) dcnt <= 10'd1;
                else begin
                    dcnt <= 10'd0;
                    if (cfg_wp) begin
                        resp <= {8'hED, 32'd0}; state <= S_RXRESP; nxt_byte <= 8'hED;
                    end else if (wr_rdy) begin
                        resp <= {(8'hE0 | (wr_err ? 8'h0D : 8'h05)), 32'd0};
                        state <= S_RXRESP;
                        nxt_byte <= 8'hE0 | (wr_err ? 8'h0D : 8'h05);
                    end else state <= S_RXACK;
                end
            end

            S_RXACK: begin                             // ждём вердикт оболочки, гоня 0xFF
                if (wr_rdy) begin
                    resp <= {(8'hE0 | (wr_err ? 8'h0D : 8'h05)), 32'd0};
                    state <= S_RXRESP;
                    nxt_byte <= 8'hE0 | (wr_err ? 8'h0D : 8'h05);
                end
            end

            S_RXRESP: begin
                wcnt <= P_WBUSY;
                if (P_WBUSY != 4'd0) begin state <= S_BUSY; nxt_byte <= 8'h00; end
                else if (multi) begin lba <= lba + 32'd1; state <= S_RXWAIT; cs_mark <= 1'b0; end
                else begin state <= S_IDLE; fcnt <= 3'd0; end
            end

            S_BUSY: begin
                // B0150: в режиме FAST ПОСЛЕДНИЙ из P_WBUSY байтов занятости - 0x01 (см. cfg_fast).
                // `nxt_byte` - байт СЛЕДУЮЩЕГО обмена, поэтому решение принимается на шаг раньше:
                // при wcnt==2 готовим четвёртый байт. Стенд tb_divmmc_card поймал это как
                // расхождение с эталоном (RTL отдавал 0x01 пятым, после четырёх нулей).
                nxt_byte <= (cfg_fast && (wcnt == 4'd2)) ? 8'h01 : 8'h00;
                if (wcnt <= 4'd1) begin
                    nxt_byte <= 8'hFF;             // после занятости - 0xFF, как у настоящей карты
                    if (multi) begin
                        lba <= lba + 32'd1; state <= S_RXWAIT; cs_mark <= 1'b0;
                    end else begin state <= S_IDLE; fcnt <= 3'd0; end
                end
                wcnt <= wcnt - 4'd1;
            end

            default: state <= S_IDLE;
            endcase

            //---- ПАРАЛЛЕЛЬНЫЙ приёмник CMD12 -----------------------------------------------------
            // Мультиблочное чтение останавливают командой ПОСРЕДИ потока - паузы у карты нет. Пока
            // карта отдаёт данные, хост обязан держать 0xFF, ложных срабатываний быть не может.
            // 🥇 В состояниях ПРИЁМА данных этот приёмник обязан молчать: там каждый четвёртый байт
            // полезной нагрузки имеет старшие биты 01.
            if (sniff) begin
                if (fcnt == 3'd0) begin
                    if (rx_lat[7:6] == 2'b01) begin
                        fr <= fr_new; fcnt <= 3'd1; crc7 <= crc7_b(7'd0, rx_lat);
                    end
                end else begin
                    fr <= fr_new;
                    if (fcnt < 3'd5) begin fcnt <= fcnt + 3'd1; crc7 <= crc7_b(crc7, rx_lat); end
                    else begin
                        fcnt <= 3'd0;
                        if (idx == 6'd12) stopnext <= 1'b1;
                        else c_desync <= (c_desync == 4'hF) ? c_desync : c_desync + 4'd1;
                    end
                end
            end
        end

        //---- сбросы ------------------------------------------------------------------------------
        // ⚠ `bitc` СЮДА НЕ ВХОДИТ: он обязан оставаться в фазе со счётчиком spi.v, у которого
        // сброса нет вовсе. Сброс автомата - это сброс ПРОТОКОЛА, а не выравнивания.
        /* 🥇 B0135 КАРТА НЕ СБРАСЫВАЕТСЯ ВМЕСТЕ С МАШИНОЙ. Было `!rst_n ||` - и комментарий у порта
           уверял, что «esxDOS после сброса всё равно начинает с CMD0». Это НЕВЕРНО, проверено на
           плате 14.08: esxDOS держит в своём ОЗУ метку «я уже стартовал» ($2D42 = $AA) и, увидев
           её, уходит МИМО инициализации - счётчик команд карты после сброса не растёт вовсе.
           Настоящая SD-карта сброса Спектрума не замечает и остаётся инициализированной; у нас же
           она обнулялась, и получалось рассогласование: система считает карту готовой, карта себя -
           нет, и первое же чтение отдаёт 0xFF. Теперь ведём себя как настоящая карта. Сбросить
           протокол по-прежнему может оболочка (cfg_rst) и снятие карты (!attached). */
        if ((arm_stb && cfg_rst) || !attached) begin
            state <= S_IDLE; fcnt <= 3'd0; rcnt <= 3'd0; after <= S_IDLE;
            dcnt <= 10'd0; dlen <= 10'd512; crc16 <= 16'd0; wcnt <= 4'd0;
            multi <= 1'b0; stopnext <= 1'b0; cs_mark <= 1'b0;
            spi_md <= 1'b0; idle_st <= 1'b1; app <= 1'b0; a41 <= P_A41;
            rq_rd <= 1'b0; rq_wr <= 1'b0; rd_rdy <= 1'b0; wr_rdy <= 1'b0;
            nxt_byte <= 8'hFF; nxt_bram <= 1'b0; osr <= 8'hFF; ld_cnt <= 2'd0;
            dbase <= B_RDA;
            if (arm_stb && cfg_rst) begin
                c_cmds <= 8'd0; c_rd <= 8'd0; c_wr <= 8'd0; c_ill <= 4'd0; c_desync <= 4'd0;
                last_cmd <= 6'd0; last_unk <= 6'd0; crc7_bad <= 1'b0; rq_seq <= 2'd0;
            end
        end
    end

    //=============================================================================================
    // Мост запросов наружу. Правило CDC: НАГРУЗКУ ДЕРЖИМ (lba/seq/буфер не меняются, пока запрос не
    // снят), синхронизируем ТОЛЬКО флаг и отдаём его на два такта ПОЗЖЕ данных. Оплачено памятью
    // Пентагона (B0074): у совпавших фронтов данных и флага приёмник берёт ПРЕДЫДУЩУЮ транзакцию.
    //=============================================================================================
    reg [1:0] rq_dly = 2'd0;
    reg       rq_rd_p = 1'b0, rq_wr_p = 1'b0;
    always @(posedge clk) begin
        rq_dly  <= {rq_dly[0], (rq_rd | rq_wr)};
        rq_rd_p <= rq_dly[1] & rq_rd;
        rq_wr_p <= rq_dly[1] & rq_wr;
    end
    (* ASYNC_REG="TRUE" *) reg [2:0] rrd_a = 3'd0, rwr_a = 3'd0;
    always @(posedge aclk) begin
        rrd_a <= {rrd_a[1:0], rq_rd_p};
        rwr_a <= {rwr_a[1:0], rq_wr_p};
    end

    wire card_busy = ((state == S_NAC) & ~rd_rdy) | (state == S_RXACK) | rq_rd | rq_wr;

    assign lba_q = lba;          // держится неподвижно, пока флаг поднят - синхронизатор не нужен
    assign stat  = {crc7_bad, map_dbg[8], state, last_unk, last_cmd,
                    map_dbg[7:0], card_busy, rbuf, rq_seq, rwr_a[2], rrd_a[2]};
    assign dbg   = {c_cmds, c_rd, c_wr, c_ill, c_desync};

    //=============================================================================================
    // ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ (чтобы следующий не искал):
    //  * выхода в `cpu_hold` - его нет и быть не должно (см. шапку);
    //  * настоящего CRC7 команд как ПРИЧИНЫ ОТКАЗА - карта в SPI его не обязана проверять, а esxDOS
    //    честный шлёт только для CMD0/CMD8; мы его считаем и отдаём несовпадение в DMMC_STAT[31];
    //  * CRC16 ПРИНЯТОГО блока - его не считает ни одна половина связки (L1DEA шлёт два 0xFF), а
    //    рвать запись по нему нельзя;
    //  * дешифрации портов - её делает `usd.v`, второго декодера не заводим.
    //
    // ТРИ ОСОЗНАННЫХ ОТСТУПЛЕНИЯ ОТ ЭТАЛОНА `arm/divmmc_card.c`:
    //  1. Отказ носителя на ЧТЕНИИ. У модели он известен мгновенно и уезжает в R1 (бит 0x40); у нас
    //     R1 уже отдан, когда оболочка сообщает об отказе, поэтому мы отдаём токен ошибки 0x08 -
    //     ровно так поступает настоящая карта.
    //  2. Ожидание оболочки. Пока блока нет, мы гоним 0xFF в N_AC (чтение) и в S_RXACK (запись).
    //     При мгновенном ответе оболочки поток байт-в-байт совпадает с моделью.
    //  3. Сброс машины сбрасывает автомат. У модели входа сброса нет вовсе; esxDOS после сброса
    //     всё равно начинает с CMD0, а застрявший в приёме 512 байт автомат съел бы его кадр.
    //
    // ЦЕНА В КРИСТАЛЛЕ (13.08.2026, xc7z010clg400-1).
    //   Изолированно (OOC): 487 LUT / 445 FF / 1 RAMB18 при умолчании синтеза, 433 LUT при
    //   `-directive AreaOptimized_high`; WNS изолированно +6.39 нс на 56.667 МГц - логика мелкая.
    //   🥇 В СОСТАВЕ ДИЗАЙНА (A/B двух синтезов на ОДНОМ дереве, отличие - только этот модуль и его
    //   провода): **+727 LUT-ячеек, +495 FF, +1 RAMB18** (плитки 58.0 -> 58.5). В эту дельту входят
    //   и восемь слов AXI: у `axi_ctl` растут и мультиплексор чтения, и дешифратор записи.
    //   Это ВТРОЕ больше бюджета «+240 LUT на сборку», которым живёт проект, и вдвое больше оценки
    //   плана на всю схему целиком (300-450). Знать это надо ДО сборки: слайсы уже 4400/4400, и
    //   размещение на 16029 LUT один раз уже отказало (B0122). Риск здесь - РАЗМЕЩЕНИЕ, а не логика.
    //   Где резать, если размещение не сойдётся (по убыванию отдачи и по возрастанию потерь):
    //     * обратные чтения `DMMC_CTL`/`DMMC_CAP` - чистое удобство отладки, два входа мультиплексора;
    //     * `DMMC_BUFA`/`DMMC_BUFW` не регистрировать в `axi_ctl`, а отдавать `s_wdata` со стробом
    //       (модуль их и так защёлкивает) - минус 64 триггера и их мультиплексоры;
    //     * проверка диапазона `argv >= cap_l` (32-битный компаратор + 32 триггера `cap_l`) - ценой
    //       того, что чтение за концом карты даст токен ошибки вместо R1 бит6.
    //   Резать САМ протокол (мультиблок, CRC7, CRC16) бессмысленно - см. следующий абзац.
    // ⚠ Оценка плана «карта 150-250 LUT» занижена вдвое, и это надо знать ДО сборки. Якорь выбран
    // неверно: `nemo_ide` (48 LUT) - регистровый файл, а мы - протокольный автомат, как `wd1793`
    // (617 LUT).
    // Отдельная измеренная неприятность: ОТКЛЮЧЕНИЕ отдельных кусков LUT не экономит, а увеличивает
    // (проверка диапазона -> 498, мультиблок -> 515, CRC7 -> 479 при базовых 487). То есть у модуля
    // этого размера разброс перекладки БОЛЬШЕ вклада любой отдельной функции - резать функционал
    // ради места здесь бессмысленно, экономить надо не тут. Честный CRC16 стоит 7 LUT и 16 FF.
    //=============================================================================================
endmodule
