// Зачем отдельный модуль, а не общий async_fifo из шага 08: тому нужен только признак «полна», а
// здесь нужна ЗАНЯТОСТЬ В ДОМЕНЕ ЗАПИСИ - без неё нельзя поднять «занято» ЗАРАНЕЕ, с запасом на те
// записи, которые гость делает не спрашивая флага. Править общий файл нельзя (его читают шаги 06-14,
// и два модуля с одним именем = молчаливая подмена, это у нас уже оплачено немым SAA1099), поэтому
// у очереди GS своё имя и свой файл.
//
// 🥇 ПОЧЕМУ ОБРАТНОЕ ДАВЛЕНИЕ, А НЕ «ПОБОЛЬШЕ ГЛУБИНЫ» (оплачено сутками поиска на Z-Player 4.1).
// Плеер заливает свой драйвер в карту потоком OUTI на #B3: флаг он проверяет ПОСЛЕ записи, а на
// перевороте счётчика делает ДВЕ записи подряд вообще без проверки. Байт у него уходит примерно раз
// в 4.7 мкс, то есть очередь на 32 байта - это 150 мкс запаса. Любая пауза оболочки длиннее (чтение
// сектора 1.25 мс, наполнение звукового кольца до 134 мс) молча съедала байт: на 816-м байте из 4260
// вставал липкий признак переполнения, драйвер на карте оказывался битым, и машина навсегда висла в
// ожидании бита 7. Глубиной эту дыру закрыть НЕЛЬЗЯ в принципе - 134 мс это 28 тысяч байт. Настоящая
// карта не теряет не потому, что у неё большой буфер, а потому, что она успевает забрать байт и снять
// флаг. Значит и нам надо не «успевать», а ЧЕСТНО СКАЗАТЬ «занято» - тогда гость подождёт сам, как он
// и написан ждать перед настоящей картой, и терять станет нечего.
//
// Признак «занято» поднимается по ВЕРХНЕМУ ПОРОГУ (HI), а не по полноте: между тем мигом, когда мы
// сказали «занято», и тем, когда гость это увидит, он успевает записать ещё несколько байт (у
// Z-Player минимум два, у развёрнутых блоков OUTI бывает и шестнадцать, и тридцать два). Резерв
// HDR мест и есть плата за эту слепую зону. Гистерезис (снимаем «занято» только на LO) нужен, чтобы
// гость не дёргался по одному байту на границе: после паузы он получает целую пачку.
//
// Указатель чтения приходит в домен записи через синхронизаторы, то есть он СТАРЕЕ настоящего, и
// занятость получается завышенной. Для обратного давления это правильный знак ошибки: можно поднять
// «занято» чуть раньше, чем нужно (гость подождёт лишние наносекунды), но нельзя - позже.
//-------------------------------------------------------------------------------------------------
module gs_wq_fifo #(
    parameter DW  = 8,
    parameter AW  = 8,                     // глубина 2^AW
    parameter HDR = 32,                    // резерв мест под записи БЕЗ опроса флага
    parameter LO  = (1 << AW) / 2          // порог снятия «занято» (гистерезис)
)(
    input  wire           wr_clk,
    input  wire           wr_rst_n,
    input  wire           wr_en,
    input  wire [DW-1:0]  din,
    output wire           full,            // настоящая полнота: только для липкого признака потери
    output reg            afull,           // «занято» для машины - верхний порог с запасом
    output wire [AW:0]    wr_count,        // занятость в домене записи (завышенная, см. выше)
    /* B0119: ПРИЗНАК ЖИЗНИ ОБОЛОЧКИ, ПРИВЕДЁННЫЙ В ДОМЕН МАШИНЫ. Такты ожидания на шине держит
       сторож (gs_flow.v), и взводиться заново он обязан именно на «оболочка вынула байт», а не на
       «ждём слишком долго»: наполнение звукового кольца законно занимает до 134 мс, и мерить его
       тем же порогом, что и смерть прошивки, значило бы отпускать давление посреди нормальной
       работы. Сдвиг указателя чтения уже приведён сюда синхронизаторами - берём его изменение. */
    output wire           drain_w,         // импульс в домене ЗАПИСИ: оболочка вынула байт

    input  wire           rd_clk,
    input  wire           rd_rst_n,
    input  wire           rd_en,
    output wire [DW-1:0]  dout,
    output wire           empty,
    output reg  [AW:0]    rd_count
);
    localparam [AW:0] HI = (1 << AW) - HDR;         // порог подъёма «занято»
    (* ram_style = "distributed" *) reg [DW-1:0] mem [0:(1<<AW)-1];

    // Оба указателя объявлены ЗАРАНЕЕ: каждый домен ссылается на «серый» указатель соседа, и при
    // объявлении по месту получается использование до объявления (xvlog это законно отвергает).
    reg  [AW:0] wbin = 0, wgray = 0;                // домен записи
    reg  [AW:0] rbin = 0, rgray = 0;                // домен чтения
    reg  [AW:0] rgray_w1 = 0, rgray_w2 = 0;         // указатель чтения, приведённый в домен записи
    reg  [AW:0] wgray_r1 = 0, wgray_r2 = 0;         // указатель записи, приведённый в домен чтения

    // ---- домен записи (машина, spclk) ----
    reg         full_r = 1'b0;
    wire        wr_do      = wr_en & ~full_r;
    wire [AW:0] wbin_next  = wbin + wr_do;
    wire [AW:0] wgray_next = (wbin_next >> 1) ^ wbin_next;
    wire        full_next  = (wgray_next == {~rgray_w2[AW:AW-1], rgray_w2[AW-2:0]});
    assign      full = full_r;

    /* Серый -> двоичный: занятость нужна арифметикой, через код Грея её не сравнить.
       🥇 Именно НЕПРЕРЫВНЫМИ присваиваниями, а не `always @(*)`: блок с событийным списком
       чувствительности не исполняется, пока входной сигнал не ИЗМЕНИТСЯ, а указатель чтения
       стоит в нуле до первого вычерпывания - и всё это время занятость оставалась X, сравнение
       с порогом было ложным, «занято» не поднималось и очередь молча переполнялась ровно так же,
       как на плате. Стенд tb_gs_wq_fifo это и поймал (потеря на 256-м байте). */
    wire [AW:0] rbin_w;
    assign rbin_w[AW] = rgray_w2[AW];
    genvar gi;
    generate for (gi = AW-1; gi >= 0; gi = gi - 1) begin : g_r2b
        assign rbin_w[gi] = rbin_w[gi+1] ^ rgray_w2[gi];
    end endgenerate
    wire [AW:0] occ_w = wbin_next - rbin_w;         // с учётом байта, который кладём прямо сейчас
    assign      wr_count = occ_w;

    always @(posedge wr_clk or negedge wr_rst_n)
        if (!wr_rst_n) begin wbin<=0; wgray<=0; full_r<=1'b0; end
        else           begin wbin<=wbin_next; wgray<=wgray_next; full_r<=full_next; end
    always @(posedge wr_clk or negedge wr_rst_n)
        if (!wr_rst_n) begin rgray_w1<=0; rgray_w2<=0; end
        else           begin rgray_w1<=rgray; rgray_w2<=rgray_w1; end
    reg [AW:0] rgray_w3 = 0;                        // третья ступень - только чтобы увидеть ИЗМЕНЕНИЕ
    always @(posedge wr_clk or negedge wr_rst_n)
        if (!wr_rst_n) rgray_w3 <= 0; else rgray_w3 <= rgray_w2;
    assign drain_w = (rgray_w3 != rgray_w2);
    always @(posedge wr_clk or negedge wr_rst_n)
        if (!wr_rst_n) afull <= 1'b0;
        else if (occ_w >= HI) afull <= 1'b1;
        else if (occ_w <= LO) afull <= 1'b0;

    always @(posedge wr_clk) if (wr_do) mem[wbin[AW-1:0]] <= din;

    // ---- домен чтения (оболочка, fclk100) ----
    reg         empty_r = 1'b1;
    wire        rd_do      = rd_en & ~empty_r;
    wire [AW:0] rbin_next  = rbin + rd_do;
    wire [AW:0] rgray_next = (rbin_next >> 1) ^ rbin_next;
    wire        empty_next = (rgray_next == wgray_r2);
    assign      empty = empty_r;

    always @(posedge rd_clk or negedge rd_rst_n)
        if (!rd_rst_n) begin rbin<=0; rgray<=0; empty_r<=1'b1; end
        else           begin rbin<=rbin_next; rgray<=rgray_next; empty_r<=empty_next; end
    always @(posedge rd_clk or negedge rd_rst_n)
        if (!rd_rst_n) begin wgray_r1<=0; wgray_r2<=0; end
        else           begin wgray_r1<=wgray; wgray_r2<=wgray_r1; end

    assign dout = mem[rbin[AW-1:0]];                // FWFT: голова видна, пока не пусто

    wire [AW:0] wbin_r;                             // тем же способом и по той же причине
    assign wbin_r[AW] = wgray_r2[AW];
    genvar gk;
    generate for (gk = AW-1; gk >= 0; gk = gk - 1) begin : g_w2b
        assign wbin_r[gk] = wbin_r[gk+1] ^ wgray_r2[gk];
    end endgenerate
    always @(posedge rd_clk or negedge rd_rst_n)
        if (!rd_rst_n) rd_count <= 0; else rd_count <= wbin_r - rbin;
endmodule
